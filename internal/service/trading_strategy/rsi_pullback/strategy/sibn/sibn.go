// Package sibn supplies the ticker and rsi_pullback Params for SIBN (Газпром нефть).
//
// СОСТОЯНИЕ: откалиброван 2026-08-21 по штатной схеме каталога (-months 36 -train-months 12
// -test-months 6 -min-trades 20 -metric profit_factor), заведён в боевую вселенную тринадцатым.
//
// # Вердикт по планке: НЕ ВЗЯТА
//
// Планка, объявленная до прогонов: темы entry и trend ОБЕ дают pooled OOS PF >= 1.5 при >= 20
// сделках, и ведущая ось темы выбрана одинаково в >= 3 фолдах из 4. Фактически:
//
//   - тема entry — pooled OOS PF 1.378 на 50 сделках: ниже 1.5. Ведущая ось RSILower по фолдам
//     35/30/15/20 — все четыре значения разные, устойчивость 1 из 4;
//   - тема trend — pooled OOS PF 0.847 на 94 сделках: ниже 1.0. Ведущая ось EMASlow по фолдам
//     100/120/50/200 — устойчивость 0 из 4, худший показатель каталога.
//
// Не взята ни одна из двух половин планки, ни на одной из двух ключевых тем. Тикер принят по
// правилу владельца от 2026-08-21, объявленному ДО прогонов: литерал ставится и тикер заводится в
// RSI_PULLBACK_TICKERS даже при непройденной планке, если принятая точка не упирается в
// стоп-условие (pooled OOS PF < 1.0 либо < 20 сделок за 36 месяцев). Точка не упирается с запасом:
// pooled OOS PF 2.258 на 89 сделках.
//
// # Девять тем целиком (pooled OOS PF / сделок)
//
//	screen 1.106/76 · entry 1.378/50 · trend 0.847/94 · day 1.094/73 · day_spent 1.094/73 ·
//	volume 0.971/68 · risk 1.287/93 · exit 0.838/96 · trail 0.821/95
//
// Ни одна тема не взяла 1.5, три из девяти убыточны. Это худший набор тем в каталоге — и он
// согласуется с априором, записанным до прогонов (см. ниже). Тем не менее собранная ТОЧКА даёт
// pooled OOS PF 2.258 на 89 сделках без единого вырожденного фолда, потому что рабочая зона SIBN
// лежит не там, где темы мерили свои оси: темы свипуют одну ось поверх ДЕФОЛТОВ ядра, а на этом
// инструменте дефолтный стоп 0.5 ATR и выключенный объёмный гейт стоят вне зоны, где стратегия
// работает (прецедент NVTK). Разбор каждого поля — ниже.
//
// # Литерал: пять полей против baseline
//
//   - RSILower 30 -> 35 и EMASlow 100 -> 120 собраны ТОЧЕЧНЫМИ СВИПАМИ, а не темами: у entry
//     устойчивость 1 из 4, у trend 0 из 4, брать их выбор не из чего. Свип 4x5 (RSIPeriod 4-7 x
//     RSILower 15-35) поверх принятой зоны риска дал полку RSI(4)-RSI(5) x RSILower 30-35 со
//     значениями PF 2.116-2.303 при 59-91 сделке; одиночные пики RSI(7)/35 (PF 2.763 на 50
//     сделках) и RSI(6)/35 (2.620) окружены провалами (RSI(7)/30 — 1.707) и отвергнуты. Двенадцать
//     пар EMA дали полку 10/100 — 10/150 (2.230 / 2.475 / 2.541); 120 взято как её середина, а не
//     как максимум.
//   - StopDailyATR 0.5 -> 0.7 и TPDailyATR 0.6 -> 0.5 — из темы risk (мода 3 из 4), обе величины
//     подтверждены внутренними максимумами точечных кривых. Стоп 0.7 ATR — это 1.76% цены при
//     медианном дневном ATR 2.52%; уровня достигает 70.2% дней, то есть он остаётся настоящим
//     стопом, а не формальностью.
//   - UseVolume 0 -> 1 — из темы screen (4 фолда из 4). ОСИ гейта (VolMult 1.2, VolBaseDays 14)
//     остались дефолтами ядра: тема volume дала pooled 0.971 при обеих осях, гуляющих по всем
//     четырём фолдам, а выбор её четвёртого фолда (2.5 при базе 5) оказался худшей из семи
//     замеренных точек — PF 0.881 при отрицательном net.
//   - SpentDayATR остался дефолтным 0.8 ВОПРЕКИ моде тем day/day_spent (0.9 в 3 фолдах из 4):
//     ветка 0.9 держит pooled вырожденным вторым фолдом (OOS PF 25.955 на 14 сделках), ветка 0.8
//     даёт сопоставимый pooled на 89 сделках, где ни один фолд не вырожден. По правилу планки
//     вырожденный фолд не засчитывается в пользу тикера, поэтому взята ветка, которая в нём не
//     нуждается.
//   - RSIUpper остался дефолтным 70 вопреки теме exit (60/65/80/65, мода 2 из 4): на принятой зоне
//     риска максимум точечной кривой стоит ровно на 70 (1.486 против 1.393 у 65 и 1.288 у 75).
//   - Трейл выключен: тема trail — худшая из девяти, а трейл шире принятого стопа не срабатывает
//     ни разу за 36 месяцев (результат побайтово повторяет выключенный).
//   - DailyATRPeriod = 14 и VolLookbackBars = 3 не свипует НИ ОДНА тема — это дефолты ядра, а не
//     выбор калибровки.
//
// # Замер принятой точки и граница приёма
//
// Фактический прогон data/params/rsi_pullback/sibn/plateau_point.json: pooled OOS PF 2.258 на 89
// сделках, win rate 77.53%, compounded +31.69%; фолды 3.262(23) / 3.459(21) / 3.048(28) /
// 0.892(17), минимальный MaxDD 1.91% — вырожденных нет, убыточен только последний. Плато: 19
// соседей из 20 по всем осям лежат в полосе pooled 1.60-2.73, единственный обрыв — стоп 0.5 ATR
// (1.290). Разложение 24-месячного OOS-окна (84 сделки, PF 2.209): лучшая неделя даёт 17.9%
// итога, лучший месяц 28.0%, топ-5 сделок 33.6%, убыточных месяцев 4 из 22, все пять полугодий
// положительны — противоположность IVAT, где 85% результата сделала одна неделя.
//
// ГРАНИЦА ПРИЁМА: для фиксированной точки это НЕ out-of-sample. Точку собрал человек, видевший
// всю 36-месячную историю, поэтому 2.258 нельзя читать как проверку протокола — вердикт протокола
// дают тематические файлы, и он отрицательный (см. выше). Ожидание от живой торговли ставится по
// темам, а не по точке.
//
// Что известно об инструменте (кэш 2026-08-21, 36 735 30-минутных баров, расчётное окно 36.0
// месяца с 2023-08-21 — 36 321 бар, 25 609 будних); эти замеры от прогонов не устаревают:
//
//   - АПРИОР САМЫЙ СЛАБЫЙ В КАТАЛОГЕ, и это записано ДО прогонов. Колонка PFmed HO скринера
//     равна 0.20 на 9 сделках — худшее значение первой девятки рейтинга. Контрольный прогон
//     baseline на 36 месяцах: 129 сделок, PF 1.027, net +1 473 — инструмент торгует ровно в
//     ноль. Вес обоих фактов ограничен: колонка PFmed HO в этом каталоге предсказывает плохо в
//     обе стороны (WUSH с 4.24 планку провалил, LSNGP с 0.99 вытянул все девять тем выше 1.5),
//     а baseline меряет дефолты, а не рабочую зону инструмента (прецедент NVTK, где дефолтный
//     дневной гейт стоял там, где стратегии нет).
//   - ВОЛАТИЛЬНОСТЬ САМАЯ НИЗКАЯ В КАТАЛОГЕ: дневной ATR(14) медианой 2.52% цены (p10 1.87,
//     p90 3.58) против 2.77% у LSNGP и 4.38% у SVAV. Круг издержек 0.1% оборота стоит 0.040
//     ATR, то есть на стопе 0.3 ATR комиссия съедает 13.2% риска — ближе к черте 17%, по
//     которой строку 0.3 вырезали из domrf/, чем у любого другого тикера каталога. Обратная
//     сторона: стоп 1.3 ATR это всего 3.28% цены против 5.7% на SVAV.
//   - ЛИКВИДНОСТЬ ЛУЧШАЯ В КАТАЛОГЕ, С ОТРЫВОМ: оборот медианой 519 млн ₽/день при p10 = 206
//     млн (SVAV 68 при p10 = 18, IVAT 43, LENT 38). Даже десятый перцентиль вчетверо выше гейта
//     отбора скринера в 50 млн, поэтому стандартное ограничение бэктеста — наливает по цене
//     закрытия бара и не моделирует проскальзывание — на этом тикере перестаёт быть
//     содержательным риском.
//   - ДИВИДЕНДНЫЕ ГЭПЫ ПРОБИВАЮТ СТОП НАСКВОЗЬ. Стратегия держит позицию через ночь, а SIBN —
//     дивидендная бумага с регулярными отсечками. За окно пять гэпов вниз хуже −3%: −8.49%
//     (2023-12-27, это −4.69 дневного ATR), −6.64% (2024-10-14, −3.13), −5.03% (2024-06-13,
//     −1.61), −4.72% (2026-07-06, −1.35), −4.51% (2025-07-08, −2.01). Глубже дефолтного стопа
//     0.5 ATR открывается 1.8% дней. На таких днях стоп не пол, а пожелание: исполнение приходит
//     на цене гэпа.
//     Низкая волатильность работает ПРОТИВ инструмента — гэп той же процентной величины на
//     SVAV стоил бы вдвое меньше ATR. Параметра против этого в стратегии нет.
//   - ТРЕНДОВЫЙ ДОПУСК НЕ ЗАВИСИТ ОТ ПАРЫ: доля баров с EMAFast > EMASlow укладывается в
//     45.1-46.3% на всех 35 парах сетки, размах 1.2 процентного пункта. Тот же случай, что на
//     SVAV (42.4-43.6%), и не такой, как на IVAT (29.4-36.0% с монотонной зависимостью).
//     Практическое следствие: выбор пары меняет не объём допуска, а то, какие именно бары в
//     него попадают, поэтому дефицит выборки из-за медленной пары здесь невозможен, а разница
//     PF между парами — это качество фильтра, а не размер выборки.
//   - РЕЖИМ падающий, но не однобокий: train −25.0%, holdout −5.9%, всё окно −29.5%,
//     пик-минимум −61.0%; из шести полугодий растущих два (+20.9% и +0.0%). Мягче, чем у SVAV
//     (одно из шести) и IVAT (ноль из пяти), — конфигурация проверится на обоих режимах. Но и
//     защиты «завысить лонговый результат режимом нечем» здесь меньше: холдаут падает всего на
//     5.9%, то есть почти нейтрален.
//   - ИСТОРИИ 36.0 МЕСЯЦА С ЗАПАСОМ В 17 ДНЕЙ, поэтому штатный протокол §8
//     docs/rsi_pullback/strategy.md (-months 36 -train-months 12 -test-months 6) исполним, и
//     числа SIBN сопоставимы построчно с остальным каталогом — в отличие от ivat (26 мес) и
//     domrf (8.8 мес).
//
// Сетки калибровки лежат в data/params/rsi_pullback/sibn/, их оси прибиты
// internal/service/backtest/rsi_pullback_sibn_grid_test.go.
