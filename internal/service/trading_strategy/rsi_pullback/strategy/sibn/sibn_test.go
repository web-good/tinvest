// Стоп — единственное, что ограничивает убыток: RSI-выход закрывает и в плюс, и в минус. Ширина
// 0.7 взята по ВНУТРЕННЕМУ максимуму точечной кривой, а не по её краю: на дефолтной базе с целью
// 0.5 ось стопа даёт 0.3 -> 133 сделки PF 1.170; 0.5 -> 130 PF 1.113; 0.7 -> 127 PF 1.486;
// 1.0 -> 125 PF 1.387; 1.3 -> 125 PF 1.317. Капкан вытеснения убытка в RSI-выход (WUSH, LENT,
// LSNGP, IVAT, SVAV) здесь присутствует наполовину: счёт сделок на всей оси почти не меняется
// (133 -> 125), доля стоп-выходов падает вшестеро (39.1% -> 6.4%), но PF за 0.7 уже снижается —
// то есть вытесненные убытки дороже сэкономленных стопов, и выбор опирается на разворот кривой.
// Опорный замер выживаемости SIBN (доля дней, чей размах достаёт до уровня): 0.3 ATR — 98.7%,
// 0.5 — 90.4%, 0.7 — 70.2%, 1.0 — 39.4%, 1.3 — 18.7%. В процентах цены при медианном дневном ATR
// 2.52% стоп 0.7 ATR — это 1.76% цены.
func TestStopIsArmed(t *testing.T) {
	if p := DefaultParams(); p.StopDailyATR <= 0 {
		t.Fatalf("StopDailyATR = %v, want > 0", p.StopDailyATR)
	}
}

// RSI-выход закрывает большинство сделок принятой точки: 72.6% против 17.9% по цели и 9.5% по
// стопу (24-месячное OOS-окно, 84 сделки). Полоса RSIUpper = 70 оставлена дефолтной ВОПРЕКИ теме
// exit (60/65/80/65, мода лишь 2 из 4): тема мерила ось поверх дефолтного стопа 0.5, который тема
// risk отвергла, а на принятой зоне риска максимум стоит ровно на 70 — 55 -> PF 1.200; 60 -> 1.343;
// 65 -> 1.393; 70 -> 1.486; 75 -> 1.288; 80 -> 1.420. Полоса управляет не столько PF, сколько
// характером сделки: от 55 к 80 медиана удержания растёт с 5 до 12 баров, доля сделок длиннее
// одного торгового дня — с 27.1% до 57.9%. Живой раннер держит RSI-выход обязательным для всех
// тикеров реестра независимо от того, что показала бы его отключённая ветка на конкретном тикере;
// на SIBN она проиграла и по существу: 122 сделки PF 1.139 против 127 сделок PF 1.486.
func TestRSIExitIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseRSIExit != 1 {
		t.Fatalf("UseRSIExit = %d, want 1 — на принятой зоне риска ветка без RSI-выхода даёт PF 1.139 против 1.486", p.UseRSIExit)
	}
	if p.RSIUpper <= p.RSILower {
		t.Fatalf("полоса RSI вырождена: RSIUpper = %v, RSILower = %v", p.RSIUpper, p.RSILower)
	}
}

// Дневной гейт взведён на единственной ветке «день исчерпан»: ветка «день только начался»
// (FreshDayATR) держится на нуле, потому что темы day и day_spent выбрали ноль в 4 фолдах из 4 —
// ни разу за всю калибровку ненулевая ветка не выиграла ни одного обучающего окна. Сам гейт
// отсекает основную массу входов и этим держит качество: без него принятая точка даёт 296 сделок
// при PF 1.072, с ним — 76 сделок при PF 2.475 (точечные прогоны на полной истории). SpentDayATR
// остаётся дефолтным 0.8 вопреки моде тем (0.9 в 3 фолдах из 4): walk-forward принятой точки с 0.9
// даёт pooled 2.207 на 71 сделке, но его второй фолд вырожден (OOS PF 25.955 на 14 сделках), а с
// 0.8 — pooled 2.258 на 89 сделках, где ни один фолд не вырожден. Замер ветки на SIBN: порог 0.8
// оставляет 35.6% будних баров, 0.9 — 28.2%, 1.0 — 21.5%.
func TestOnlySpentDayBranchIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseDayATRGate != 1 {
		t.Fatalf("UseDayATRGate = %d, want 1 — без гейта точка даёт 296 сделок при PF 1.072 против 76 при 2.475", p.UseDayATRGate)
	}
	if p.FreshDayATR != 0 {
		t.Fatalf("FreshDayATR = %v, want 0 — ветка «день только начался» не выиграла ни одного фолда из четырёх", p.FreshDayATR)
	}
	if p.SpentDayATR <= 0 {
		t.Fatalf("SpentDayATR = %v, want > 0 — иначе гейт взведён и не отсекает ничего", p.SpentDayATR)
	}
}

// Объёмный гейт ВКЛЮЧЁН — как на SVAV и в отличие от IVAT. Флаг взят из темы screen, где он выигрывал
// в 4 фолдах из 4, а его прямая цена измерена точечно на дефолтах: (день=1, объём=0) 129 сделок
// PF 1.027 против (день=1, объём=1) 96 сделок PF 1.247. При этом ОСИ гейта взяты НЕ из темы volume:
// её собственный walk-forward дал pooled 0.971 при обеих осях, гуляющих по всем четырём фолдам
// (VolMult 1/1.2/1.5/2.5, VolBaseDays 14/14/14/5), а выбор её четвёртого фолда (2.5 при базе 5)
// оказался худшей из семи замеренных точек — PF 0.881 при отрицательном net. Точечная таблица на
// базе 14: VolMult 1.0 -> 104 сделки PF 1.188; 1.2 -> 96 PF 1.247; 1.5 -> 85 PF 1.224; 2.5 -> 56
// PF 1.139. Поэтому VolMult = 1.2 и VolBaseDays = 14 — дефолты ядра, подтверждённые максимумом
// этой таблицы, а не выбор калибратора. На walk-forward принятой точки гейт почти нейтрален
// (2.258 на 89 сделках против 1.903 на 113 при выключенном), и включён он ради качества отбора,
// а не ради pooled.
func TestVolumeGateIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseVolume != 1 {
		t.Fatalf("UseVolume = %d, want 1 — тема screen выбрала включённый гейт в 4 фолдах из 4", p.UseVolume)
	}
	if p.VolMult <= 0 || p.VolBaseDays <= 0 || p.VolLookbackBars <= 0 {
		t.Fatalf("объёмный гейт взведён (UseVolume=1), но его оси невзведены: VolMult=%v VolBaseDays=%d VolLookbackBars=%d",
			p.VolMult, p.VolBaseDays, p.VolLookbackBars)
	}
}

// Цель взведена и на принятой точке УЖЕ стопа (0.5 против 0.7) — та же асимметрия, что на WUSH,
// LENT и LSNGP, и обратная SVAV. Цель выбрана темой risk (0.5 в 3 фолдах из 4) и подтверждена
// точечной кривой, снятой ЗА краем оси каталога специально ради проверки на упор: при стопе 0.7
// TPDailyATR 0.3 -> PF 1.385; 0.4 -> 1.430; 0.5 -> 1.486; 0.6 -> 1.322; 0.8 -> 1.318; 1.0 -> 1.316;
// 1.5 -> 1.308. Нижний край оси каталога (0.5) оказался ВНУТРЕННИМ максимумом: за краем результат
// падает, значит выбор не упирается в обрезанную ось. Выше 0.6 кривая ложится в плато 1.31-1.32 —
// цель почти перестаёт срабатывать и выход отдаётся RSI. На принятой точке доля TP-выходов 17.9%.
func TestTargetIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.TPDailyATR <= 0 {
		t.Fatalf("TPDailyATR = %v, want > 0", p.TPDailyATR)
	}
	if p.TPDailyATR >= p.StopDailyATR {
		t.Fatalf("на принятой точке цель уже стопа: TPDailyATR = %v, StopDailyATR = %v", p.TPDailyATR, p.StopDailyATR)
	}
}

// Трейл выключен, и на SIBN это не развилка, а прямой вывод: тема trail — худшая из девяти
// (pooled OOS PF 0.821 на 95 сделках), а точечная ось поверх принятой зоны риска показывает, что
// трейл либо вредит, либо не существует. TrailDailyATR 0.3 -> 136 сделок PF 1.156; 0.5 -> 130
// PF 1.089; 0.7 -> 127 PF 1.445; 1.0 -> 127 PF 1.486; 1.3 -> 127 PF 1.486 — при опорной точке без
// трейла 127 сделок PF 1.486. Значения 1.0 и 1.3 совпадают с выключенным трейлом ДО КОПЕЙКИ: трейл
// шире принятого стопа 0.7 ATR не срабатывает ни разу за 36 месяцев, то есть это выключенный
// трейл, записанный как включённый. Всё, что действительно работает (0.3, 0.5, 0.7), срезает
// продолжения, ради которых стратегия и держит позицию: медиана удержания принятой точки 8 баров,
// 42.9% сделок длиннее одного торгового дня. TrailDailyATR обязан быть нулём при выключенном
// трейле, иначе выключенное поле несёт непроверенное значение, которое оживёт при первом же
// переключении флага.
func TestTrailStaysOff(t *testing.T) {
	p := DefaultParams()
	if p.UseTrail != 0 {
		t.Fatalf("UseTrail = %d, want 0 — любой рабочий уровень трейла на SIBN хуже выключенного", p.UseTrail)
	}
	if p.TrailDailyATR != 0 {
		t.Fatalf("TrailDailyATR = %v при выключенном трейле, want 0", p.TrailDailyATR)
	}
}
