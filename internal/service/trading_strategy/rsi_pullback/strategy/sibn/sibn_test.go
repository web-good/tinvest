// Литерал прибит снимком 2026-08-21. ПЛАНКА НЕ ВЗЯТА: тема entry дала pooled OOS PF 1.378 на 50
// сделках при устойчивости ведущей оси RSILower 1 из 4 (по фолдам 35/30/15/20 — все четыре
// значения разные), тема trend — pooled OOS PF 0.847 на 94 сделках при устойчивости EMASlow 0 из 4
// (100/120/50/200). Тикер принят по правилу владельца от 2026-08-21, объявленному ДО прогонов:
// литерал ставится даже при непройденной планке, если принятая точка не упирается в стоп-условие
// (pooled OOS PF < 1.0 либо < 20 сделок за 36 месяцев). Точка не упирается с запасом: фактический
// прогон data/params/rsi_pullback/sibn/plateau_point.json дал pooled OOS PF 2.258 на 89 сделках,
// win rate 77.53%, compounded +31.69%, фолды 3.262(23)/3.459(21)/3.048(28)/0.892(17) — вырожденных
// нет, минимальный MaxDD 1.91%. От core.DefaultParams() литерал отличается ПЯТЬЮ полями:
// RSILower 30->35, EMASlow 100->120, StopDailyATR 0.5->0.7, TPDailyATR 0.6->0.5, UseVolume 0->1.
// ТРИ поля собраны ПРОТИВ прямого выбора соответствующих тем, потому что темы на этом тикере не
// держатся: RSILower и EMASlow — точечными свипами поверх принятой зоны риска (у тем устойчивость
// 1 из 4 и 0 из 4); SpentDayATR остаётся дефолтным 0.8 вопреки моде тем day/day_spent (0.9 в 3
// фолдах из 4), потому что на walk-forward точки ветка 0.9 держится вырожденным вторым фолдом
// (OOS PF 25.955 на 14 сделках), а ветка 0.8 даёт сопоставимый pooled на 89 сделках без единого
// вырожденного фолда; VolMult/VolBaseDays зафиксированы дефолтами ядра, а не выбором темы volume
// (её оси гуляют по всем четырём фолдам, pooled 0.971). ГРАНИЦА ПРИЁМА: для фиксированной точки
// это НЕ out-of-sample — точку собрал человек, видевший всю историю, поэтому 2.258 нельзя читать
// как проверку протокола; вердикт протокола дают тематические файлы, и он отрицательный.
// Разбор каждого поля — в доке пакета (sibn.go).
func TestCalibratedLiteralIsPinned(t *testing.T) {
	want := core.Params{
		RSIPeriod:       4,
		RSILower:        35,
		RSIUpper:        70,
		EMAFast:         10,
		EMASlow:         120,
		DailyATRPeriod:  14,
		UseDayATRGate:   1,
		FreshDayATR:     0,
		SpentDayATR:     0.8,
		StopDailyATR:    0.7,
		TPDailyATR:      0.5,
		UseVolume:       1,
		VolBaseDays:     14,
		VolLookbackBars: 3,
		VolMult:         1.2,
		UseRSIExit:      1,
		UseTrail:        0,
		TrailDailyATR:   0,
	}
	if got := DefaultParams(); got != want {
		t.Fatalf("откалиброванный литерал SIBN изменился:\n got: %+v\nwant: %+v", got, want)
	}
}

