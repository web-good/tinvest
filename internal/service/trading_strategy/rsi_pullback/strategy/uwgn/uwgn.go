// Package uwgn supplies the ticker and rsi_pullback Params for UWGN (ПАО «Объединённая вагонная
// компания», обыкновенные акции, лот 1).
//
// СОСТОЯНИЕ: КАЛИБРОВКА НЕ ПРОВОДИЛАСЬ. DefaultParams() отдаёт baseline ядра до вердикта.
//
// РАСЧЁТНОЕ ОКНО: 2024-03-05 .. 2026-09-04 (30.0 месяца). Начало окна выбрано НЕ от истории
// инструмента, а от даты, отсекающей два известных выброса: допэмиссию ноября 2023 года и вынос
// котировки в январе 2024 — обе точки исказили бы дневной ATR и ранжирование по объёму, попади
// они в обучающие фолды. Схема прогонов — 30/10/5 (train 10 месяцев, OOS 5, четыре фолда) с
// обязательным контролем 24/12/3, аналогично прецедентам IVAT/DIAS/YDEX для укороченных окон.
//
// ОБА РИСК-ГЕЙТА ПРОЙДЕНЫ НА BASELINE: ГЕЙТ A (выживаемость эффективной защиты) — потолок 1.0 ATR
// при выживаемости 41.4%; ГЕЙТ B (просадка) — 16.35%, ужесточён до baseline (потолок 1.3x от
// собственной просадки baseline, не от чужой).
//
// ЧЕТЫРЕ ПУНКТА СТОП-УСЛОВИЯ ПЛАНА — дефолты ядра ПРОВАЛИВАЮТ пункты 3 и 4:
//
//  1. Схема 30/10/5 (расчётная): baseline 123 сделки, PF 1.055, net +5 352.54 руб., max DD 16.35%.
//     Pooled OOS walk-forward дефолтов 1.047 на 85 сделках, ОДИН прибыльный фолд из четырёх.
//  2. Контроль 24/12/3 — не проверялся отдельно walk-forward'ом дефолтов сверх пункта 3 (см. ниже).
//  3. Контроль 24/12/3 pooled OOS: 0.718 — ПРОВАЛЕН (ниже 1.0).
//  4. Издержки: чувствительность baseline к кругу 0.1% -> PF 0.929 при удвоении круга —
//     ПРОВАЛЕН (ниже 1.0).
//
// Из-за провала пунктов 3 и 4 запасной маршрут «оставить тикер на дефолтах ядра без калибровки»
// (прецедент TGKA, где дефолты прошли все проверки и заведены в прод как решение владельца)
// НА UWGN НЕДОСТУПЕН: дефолты здесь не проходная точка, а нижняя граница, которую предстоит
// улучшить калибровкой либо от которой предстоит отказаться.
//
// АПРИОР СКРИНЕРА: 25-е место, PFmed 1.38 (отчёт pullback_screen) — середина каталога, не входит
// в число тикеров с сильным априорным сигналом.
//
// ОСОБЕННОСТИ БУМАГИ:
//
//   - Шаг цены 0.02 руб. при цене ~20.64 руб. даёт круг 0.187% против моделируемых 0.1% — модель
//     ОПТИМИСТИЧНА (недооценивает реальные издержки), а не консервативна. Средняя сделка baseline
//     даёт 0.043% капитала — заметно меньше расхождения модели с реальным кругом, отсюда провал
//     пункта 4 стоп-условия при удвоении круга (0.1% -> 1.055, 0.2% -> 0.929).
//   - Ликвидность: медиана оборота 63.0 млн руб. за 12 месяцев при 52.8 млн руб. за 2026 год —
//     ограничение исполнения, калибровкой не устраняемое.
//   - Дневной ATR 3.80%.
//   - Режим за окно: -65.1%, ОДНО растущее полугодие из пяти — лонговая стратегия проверена в
//     основном против падающего рынка.
//   - Просадка baseline на полном окне: 16.35% (тот же уровень, что и гейт B выше).
