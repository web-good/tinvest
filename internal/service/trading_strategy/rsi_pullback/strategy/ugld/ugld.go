// # Что изменено 2026-08-17
//
// Три поля из восемнадцати: RSIUpper 60 → 55, FreshDayATR 0.3 → 0, TPDailyATR 1.0 → 1.5.
// Замеры принятой точки и прежнего литерала сделаны на ОДНИХ фолдах (rolling walk-forward
// -months 36 -train-months 12 -test-months 6, кэш 2026-08-17, 4 фолда):
//
//	принятая точка  pooled OOS PF 3.627 / 23 сделки, фолды 3.720(6) / 2.194(5) / 7.457(10) / 0.587(2)
//	прежний литерал pooled OOS PF 3.125 / 24 сделки, фолды 4.644(7) / 1.136(5) / 6.162(10) / 0.667(2)
//
// In-sample за 32.8 месяца: 34 сделки, PF 3.135, просадка 3.10%, CAGR 10.97%, win rate 73.53%,
// exposure около 1.4% (против 36 сделок, PF 2.555, просадки 4.44% и CAGR 9.65% у прежнего).
// Каждый календарный год прибылен: 2024 — PF 2.485 на 16 сделках, 2025 — 3.010 на 13,
// 2026 — 5.558 на 5. Смесь выходов: RSI 67.6%, TRAIL 14.7%, SL 11.8%, TP 5.9%.
//
// # Кэш и почему протокол здесь короче
//
// UGLD вышел на биржу 2023-11-22, поэтому полных 36 месяцев истории у тикера НЕТ: кэш
// UGLD_Minutes30.json на 2026-08-17 — 29 230 баров, из них 21 693 будних, 32.8 месяца.
// Фолдов всё равно четыре (окно запрашивается на 36 месяцев, и рамки фолдов считаются от
// запрошенной даты), но обучающее окно первого фолда содержит около девяти месяцев данных
// вместо двенадцати — при чтении его 3.720 это надо помнить.
//
// # Что известно об инструменте (замеры по кэшу на 2026-08-17)
//
//   - Дневной ATR(14) — 3.83% цены медианой (p10 2.70%, p90 4.99%, 786 дней). Медианный
//     дневной размах — 0.79 ATR предыдущего дня (p25 0.52, p75 1.20).
//   - Режим двусторонний и по-настоящему проверяющий: цена сходила 0.58 → 1.14 (пик
//     2024-04-11) → 0.46 (минимум 2025-07-04) → 0.67, пик-минимум −59.6%. Полугодия:
//     +30.4 / +4.9 / −3.4 / −21.8 / +22.6 / −9.9%. Последнее полугодие (holdout протокола)
//     падающее, то есть механически завышенным лонговый результат здесь не является.
//   - ТРЕНДОВАЯ ОСЬ ПОЧТИ ВЫРОЖДЕНА: доля будних баров с EMAFast > EMASlow укладывается в
//     45.6–47.7% на всех двадцати замеренных парах (от 5·50 до 40·200). Гейт режет историю
//     ровно пополам при любых периодах, и выбор пары меняет не объём допуска, а то, какие
//     именно полдня в него попадают. Отсюда практический вывод: спорить об EMA на этом
//     тикере бессмысленно, полка 100–150 плоская (3.495 / 3.485 / 3.627), обрыв только на 200.
//   - Ликвидность отличная и исполнительного риска не создаёт: лот 1000 при цене около
//     0.66 ₽, оборот 860 млн ₽/день средним и 415 млн медианой по дневному кэшу (отчёт
//     скринера от 2026-08-04 давал 765 млн на 24-месячном окне).
//   - Сигналов входа много: кроссов RSI(6) вниз через 15 — 197 будних за 32.8 месяца,
//     RSI(4)@30 — 1645. Тонкая здесь не подача сигналов, а то, что от них остаётся после
//     гейтов, — см. следующий раздел.
//
// # Главная оговорка: вход — ПИК, а не полка
//
// Плато вокруг принятой точки широкое почти по всем осям (шестнадцать соседей дают 2.45–3.73:
// EMASlow 100 — 3.495, 120 — 3.485, 200 — 2.453; EMAFast 30 — 2.877; SpentDayATR 0.9 — 2.967,
// 1.0 — 2.735; TPDailyATR 1.0 — 3.360, 2.0 — 3.177; TrailDailyATR 0.4 — 3.103, 0.6 — 3.066,
// трейл выключен — 2.528; объёмный гейт выключен — 3.586, база 10 дней — 3.185; RSIUpper 50 —
// 3.322, 60 — 3.249, 65 — 2.869). Но ось входа — обрыв: RSILower 10 даёт 0.343 на пяти
// сделках, 20 — 1.580, RSIPeriod 5 — 1.765, 7 — 1.069. Иными словами, RSI(6)@15 — единственный
// работающий угол, и никакая калибровка этого не лечит. Слепая тема entry на расширенной
// сетке (252 комбинации) это подтверждает с другой стороны: pooled OOS PF 1.195 на 71 сделке
// при выборе RSILower 45/20/15/10 — четыре разных значения на четырёх фолдах.
//
// # Вторая оговорка: риском правит трейл, а поле стопа инертно
//
// Точки StopDailyATR 0.5, 0.7, 1.0 и 1.3 дают ПОБАЙТОВО одинаковый результат. Причина в
// desiredStop: он берёт наибольший уровень, а трейл 0.5 ATR от максимума стоит с первого же
// бара ровно там, где фиксированный стоп 0.5, поэтому любой более широкий фиксированный стоп
// никогда не связывает. Что действительно меняет риск: выключение трейла (2.528 против 3.627),
// его сужение (0.4 — 3.103) или расширение (0.6 — 3.066), и стоп 0.3 — единственная точка оси
// стопа, которая вообще что-то меняет (1.992). При выключенном трейле расширение стопа только
// вредит (0.7 — 2.375, 1.0 — 1.647). Практическое следствие для живой торговли: обсуждать
// «поставить стоп шире» на этом тикере бессмысленно, пока трейл включён.
//
// # Планка и почему её нельзя считать взятой
//
// Формулировка та же, что у WUSH, LENT, LSNGP, GAZP и NVTK: pooled OOS PF ≥ 1.5 при ≥ 20
// сделках одновременно на темах entry и trend плюс устойчивость выбора ведущей оси в 3 фолдах
// из 4. Девять тем прогнаны 2026-08-17 на расширенных сетках: trend 3.780/16, exit 3.130/24,
// risk 3.045/24, day_spent 2.687/17, volume 2.473/21, day 2.379/20, trail 2.212/24,
// screen 1.839/29, entry 1.195/71. Семь тем из девяти выше 1.5 — но планка НЕ взята, и на
// этом тикере она провалена сразу по всем трём условиям:
//
//   - entry не добрал по PF (1.195 при 1.5) и не дал устойчивости (RSILower 45/20/15/10);
//   - trend по PF прошёл с большим запасом (3.780), но на 16 сделках вместо 20, и его выбор
//     EMASlow 120/120/50/50 — два совпадения из четырёх при требуемых трёх; хуже того, его
//     четвёртый фолд остался ВОВСЕ БЕЗ СДЕЛОК, а третий имел in-sample PF 4189 — то есть
//     число 3.780 держится на вырожденных окнах;
//   - выборка мала везде: пул OOS у тем — 16–29 сделок, у принятой точки 23 на четыре фолда
//     (6/5/10/2). Это самый тонкий тикер боевой вселенной, и одна сделка стоит здесь десятых
//     долей PF.
//
// Отдельно, и это не лечится ничем: четвёртый фолд (OOS 2026-02-17—2026-08-17, бумага упала
// на 9.9%) убыточен и у принятой точки (0.587), и у прежнего литерала (0.667) — на двух
// сделках. Вывод «последнее полугодие стратегия проиграла» верен, но статистически пуст.
//
// # Цена принятой правки, названная прямо
//
// RSIUpper 55 берёт второй фолд — единственный содержательно слабый в наборе (1.136 → 2.194,
// OOS 2025-02—2025-08, падение бумаги на 21.8%) — и поднимает win rate с 66.7% до 73.5%. Платой
// является ХАРАКТЕР сделки: медиана удержания падает с 11 до 8 баров, доля сделок длиннее
// одного дня — с 42% до 29%. Многодневная по замыслу стратегия на UGLD сдвигается к
// внутридневной; это тот же эффект, что RSIUpper 55 дал на LSNGP, но там он был резче. Край
// оси проверен ЗА её пределами: 50 — 3.322, 45 — 3.729. Точка 45 отвергнута не по PF, а по
// существу: при ней многодневных сделок остаётся 14%, а выход уезжает ниже средней линии RSI,
// то есть позиция закрывается, пока осциллятор ещё в нижней половине. Если сдвиг характера
// окажется неприемлемым в живой торговле, возврат к полосе 60 подготовлен файлом
// data/params/rsi_pullback/ugld/plateau_upper60.json (pooled 3.249, удержание 11 баров, 41%
// многодневных) — это единственная альтернатива, сохраняющая прежний характер.
//
// TPDailyATR 1.5 — внутренний максимум оси (1.0 — 3.360, 1.5 — 3.627, 2.0 — 3.177), и цель
// продолжает срабатывать: 5.9% выходов против 5.6% на прежней 1.0. Проверка сделана намеренно
// — на RENI цель 1.5 не срабатывала ни разу за всю историю и стратегия шла фактически без неё.
//
// FreshDayATR 0 выключает ветку «день только начался», пришедшую из первой калибровки и ни
// разу не подтверждённую: она стоит одной сделки в 33 месяца, роняет pooled PF (3.535 против
// 3.627) и поднимает просадку (4.87% против 3.10%), а слепая тема day выбирала её по фолдам
// как 0/0/0.5/0.5 — неустойчиво; тема day_spent с принудительно выключенной веткой дала 2.687
// против 2.379 у двусторонней day. UGLD был единственным боевым тикером с включённой свежей
// ветвью; теперь такого нет ни у одного.
//
// # Граница приёма
//
// Замер принятой точки сделан сеткой из одного значения, поэтому profit factor принадлежит
// конфигурации, а не процедуре отбора, — но это НЕ out-of-sample: три поля выбрал человек,
// видевший все тестовые окна. Сравнивать 3.627 с планкой 1.5 нельзя. Тикер остаётся в
// RSI_PULLBACK_TICKERS (он там с самого начала), и перекалибровка — замена литерала внутри
// уже принятого решения, а не новый ввод в прод.
