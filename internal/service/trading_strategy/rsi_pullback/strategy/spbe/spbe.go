//   - UseDayATRGate 1 — screen, ЕДИНОГЛАСНО 4/4 (совпало с дефолтом; без гейта точечно 0.889/437).
//   - FreshDayATR 0 — дефолт ядра (day: 0/0.1/0.2/0.2; плато 0 против 0.1 шириной 0.005 PF).
//   - SpentDayATR 0.8 — дефолт ядра (day: 0.8/1.25/1.5/1.0, day_spent: 0.8/1.25/1.0/0.8).
//   - StopDailyATR 0.5 — дефолт ядра (risk: 1.3/1.5/1.5/1.3, ничья 2/2; см. раздел о капкане).
