// СОСТОЯНИЕ: ДО КАЛИБРОВКИ, заведён в реестр бэктеста 2026-09-07 как кандидат на двадцать шестой
// тикер боевой вселенной. DefaultParams() обязан возвращать ровно core.DefaultParams(), пока
// калибровка не проведена: пакет существует, чтобы прогоны шли через общий реестр, а не через
// generic-ветку.
//
// # Окно и схема
//
// Расчётное окно 2023-09-07 .. 2026-09-07 (36 месяцев), интервал Minutes30, без обрезки: разрывов
// длиннее четырёх дней в получасовом ряду нет, сплитов и консолидаций тоже нет (медиана
// 30-минутного объёма падает плавно, ступеней кратности нет ни в цене, ни в объёме). Провал июля
// 2026 (57.65 -> 36.40 руб за две недели) — непрерывная распродажа без гэпов, а не корпоративное
// событие, ряд корректировать не нужно. Схема 36/12/6 (train 12 месяцев, OOS 6, четыре фолда) плюс
// обязательный контроль 24/12/3: сессия внутри окна расширялась один раз (медиана баров в буднем
// дне по полугодиям 29 -> 29 -> 34 -> 35 -> 35 -> 35).
//
// # Baseline (дефолты ядра, 36 месяцев, комиссия 0.0005)
//
// 149 сделок, PF 1.179, net +18 985.36 руб (+18.99%), win rate 62.42%, max DD 12 169.24 руб
// (11.10%), exposure 4.30%, CAGR 5.96%, expectancy 127.42 руб на сделку (0.127% капитала). Выходы:
// RSI 84 (56.4%) / SL 42 (28.2%) / TP 23 (15.4%). Удержание: медиана 9 баров, p90 20, максимум 56.
// Ночёвок 40.3%, выходов в выходную сессию 6.7%.
//
// Walk-forward дефолтов: 36/12/6 -> pooled OOS PF 1.326 на 100 сделках (пофолдово 1.708/28,
// 0.409/16, 2.048/27, 1.098/29); контроль 24/12/3 -> pooled OOS PF 1.469 на 56 сделках (пофолдово
// 1.529/10, 2.560/17, 0.784/14, 1.308/15). Это ОДИН ИЗ СИЛЬНЕЙШИХ BASELINE КАТАЛОГА, и он получен
// на бумаге, потерявшей за окно три четверти цены (buy&hold -76.8%). Маршрут «завести на дефолтах
// ядра» по прецеденту TGKA здесь формально доступен и обязателен к рассмотрению, если принятая
// точка окажется слабее дефолтов — но реальный круг издержек (см. ниже) этот маршрут закрывает: на
// нём baseline уже стоит на нуле.
//
// Полугодия baseline (PF, сделок, net): 0.864 (29, -1 594 руб), 1.008 (19, +101), 1.413 (29,
// +9 440), 0.409 (16, -9 088), 2.017 (26, +16 969), 1.117 (30, +3 157). Два убыточных полугодия из
// шести; лучшее полугодие (2.017) приходится на -22.7% по цене инструмента, то есть режим
// односторонне падающий (buy&hold -76.8%, растущих полугодий два из шести).
//
// # Издержки — главный риск бумаги
//
// Шаг цены 0.05 руб, проверено по четырём ценовым полосам отдельно (0-50, 50-100, 100-150,
// 150-250 руб). Круг из двух шагов: 0.217% при последней цене 46.25 руб (0.153% при медиане
// последних 12 месяцев 65.55 руб, 0.104% при медиане окна 96.1 руб), против 0.1%, которые считает
// модель издержек. Модель ОПТИМИСТИЧНА В 2.2 РАЗА по текущей цене — второй такой случай в каталоге
// после RTKMP (0.234%, тикер отвергнут); разрыв растёт со временем, потому что круг обратно
// пропорционален падающей цене.
//
// Чувствительность baseline к издержкам (полное окно, дефолты): круг 0.1% (модель) -> PF 1.179;
// 0.2% -> 1.024; 0.217% (реальный) -> 0.995; 0.3% -> 0.884. НА ДЕФОЛТАХ EDGE СЪЕДАЕТСЯ РЕАЛЬНЫМ
// СПРЕДОМ ЦЕЛИКОМ — отсюда пятый пункт стоп-условия плана: принятая точка обязана выжить при
// -commission 0.0011 (круг 0.22%), а маршрут «дефолты ядра» на MVID закрыт до калибровки.
//
