// Package mvid supplies the ticker and rsi_pullback Params for MVID (ПАО «М.видео», обыкновенные
// акции, лот 1).
//
// СОСТОЯНИЕ: ОТКАЛИБРОВАН 2026-09-07, ТОЧКА ПРИНЯТА ВЛАДЕЛЬЦЕМ ПРИ СРАБОТАВШЕМ ПУНКТЕ 2
// СТОП-УСЛОВИЯ (§5.8.1 спеки, коммит 9e0fecc). Формально по процедуре MVID в прод не заводится —
// пул OOS дал 15 сделок при пороге 20, форма отказа та же, что у UWGN (редкость, а не убыточность).
// Владелец решил завести точку как есть вместе с четырьмя явно принимаемыми рисками (см. ниже).
// Параметры точки решением не менялись. Полный разбор — docs/superpowers/plans/task-11-report-mvid.md.
//
// # Окно и схема
//
// Расчётное окно 2023-09-07 .. 2026-09-07 (36 месяцев), интервал Minutes30, без обрезки: разрывов
// длиннее четырёх дней в получасовом ряду нет, сплитов и консолидаций тоже нет. Провал июля 2026
// (57.65 -> 36.40 руб за две недели) — непрерывная распродажа без гэпов, а не корпоративное
// событие. Схема 36/12/6 (train 12 месяцев, OOS 6, четыре фолда) плюс обязательный контроль
// 24/12/3.
//
// # Точка поле за полем (голоса фолдов -> решение, тема)
//
// ПРИНЯТЫ ТЕМАМИ СЕМЬ ПОЛЕЙ ПРОТИВ ДЕФОЛТА ЯДРА: RSIPeriod 3,3,3,3 (тема entry, единогласно) ->
// 3 против дефолта 4; RSILower 10,10,10,15 (тема entry, большинство 3/4) -> 10 против дефолта 30,
// совпало с пиком измеренного рельефа (2.594/28); EMAFast 3,3,3,5 (тема trend, большинство 3/4) ->
// 3 против дефолта 10, НИЖНИЙ КРАЙ обеих трендовых сеток; EMASlow 50,50,50,75 (тема trend,
// большинство 3/4) -> 50 против дефолта 100, дефолт не встретился ни в одном фолде; TPDailyATR
// 0.2,0.2,0.2,0.2 (тема risk, единогласно) -> 0.2 против дефолта 0.6, максимум измеренной оси
// (1.364/173) и одновременно самый хрупкий к издержкам узел сетки; UseTrail/TrailDailyATR —
// TrailDailyATR 0.5,0.5,0.5,1.0 (тема trail, большинство 3/4) -> TrailDailyATR 0.5 и вместе с ней
// UseTrail 1, против дефолтов 0 и 0 (одно решение темы). ДВА ПОЛЯ ПРИНЯТЫ НАСТОЯЩИМ БОЛЬШИНСТВОМ,
// НО ЧИСЛЕННО СОВПАЛИ С ДЕФОЛТОМ: UseDayATRGate 0,1,1,1 (тема screen) -> 1; UseVolume 0,0,0,1
// (тема screen, большинство за выключенный гейт) -> 0. ДЕВЯТЬ ПОЛЕЙ УПАЛИ НА ДЕФОЛТ ЯДРА ЗА
// ОТСУТСТВИЕМ БОЛЬШИНСТВА: RSIUpper (тема exit 50,95,65,40 и тема exit_low 40,40,45,45 — большинства
// нет ни у одной) -> 70; DailyATRPeriod -> 14 (ось не свипуется); FreshDayATR 0.3,0,0,0.2 (раскол
// 2/2) -> 0; SpentDayATR (тема day 1.25,0.6,0.6,1.5 и тема day_spent 0.7,0.6,0.6,1.0, максимум 2/4
// в обеих) -> 0.8; StopDailyATR 0.8,0.6,1.0,0.8 (тема risk, плюрализм 2/4) -> 0.5, ни один фолд не
// выбрал сам дефолт; VolBaseDays 3,10,30,14 (тема volume, все разные) -> 14; VolMult (тема volume
// 1.2,3.0,2.5,2.0 и тема vol_window 2.0,2.0,2.0,2.0 единогласно — вторичная тема не забирает поле,
// потому что её pooled OOS 1.318 ниже pooled OOS первичной темы volume 1.625, правило §5.2 спеки
// для пары volume/vol_window) -> 1.2; VolLookbackBars 5,8,5,1 (тема vol_window, плюрализм 2/4) -> 3;
// UseRSIExit 0,0,1,1 (тема trail, ничья 2/2) -> 1, направление подтверждено рельефом (при
// UseRSIExit=0 вся ось трейла ниже). ПРАКТИЧЕСКОЕ СЛЕДСТВИЕ: при UseVolume=0 три объёмных поля
// инертны и записаны для полноты сетки.
//
// # Риск-гейт A и мёртвый трейл
//
// Эффективная защита = min(StopDailyATR=0.5, TrailDailyATR=0.5 при UseTrail=1) = 0.5 ATR.
// Выживаемость 0.5 по таблице MVID (n=762 будних дня) = 86.2% >= порога 30% — ГЕЙТ A ПРОЙДЕН с
// большим запасом, потолок гейта (1.0, выживаемость 36.0%) не достигнут ни одним принятым полем.
// portfolio.go:76-77 ставит prevMaxFavorable равным цене входа, поэтому на первом управляемом баре
// трейловый уровень maxFav-0.5*ATR точно равен фиксированному вход-0.5*ATR, и DesiredStop
// (core/core.go:527) отдаёт ничью фиксированному стопу; дальше трейл может подняться не более чем
// на 0.2 ATR, но цель 0.2 ATR снимает позицию раньше, чем это успевает произойти. В полном журнале
// (26 сделок) НЕТ НИ ОДНОГО выхода с причиной TRAIL — тема trail отдала точке большинство 3/4, но
// на пуле сделок это поле не меняет ничего: прогон с TrailDailyATR=0.7 и прогон с UseTrail=0 дают
// отчёт, побайтово совпадающий с точкой.
//
// # Walk-forward и стоп-условие
//
// Каноническая схема 36/12/6: pooled OOS PF 1.697 на 15 сделках (13 выигрышных / 2 проигрышных,
// win rate 86.67%), пофолдово 1613.052/2, 1.187/3, 0.690/5, 3169.616/5 (два фолда без единой
// убыточной сделки). Baseline (дефолты ядра) на той же схеме: 1.326 на 100 сделках. Контроль
// 24/12/3: pooled OOS PF 1.484 на 10 сделках (baseline 1.469/56) — НЕ НЕЗАВИСИМ: тестовые окна
// обеих схем покрывают один и тот же отрезок 2025-09-07..2026-09-07, пул из десяти сделок — те же
// самые сделки, что фолды 3 и 4 схемы 36/12/6. Издержки: -commission 0.001 -> 1.404, реальный круг
// -commission 0.0011 -> 1.348 (ПЯТЫЙ ПУНКТ СТОП-УСЛОВИЯ ПРОЙДЕН — ради него он и вводился; дефолты
// на той же схеме и том же круге дают 1.148, точка выигрывает 0.200 PF). Полное окно: 26 сделок, PF
// 2.015, net +7 302.05 руб (+7.30%), max DD 6 031.78 руб (5.64%) — риск-гейт B (потолок 11.10%
// baseline) ПРОЙДЕН вдвое с запасом.
//
// СТОП-УСЛОВИЕ СРАБОТАЛО ПО ПУНКТУ 2: пул OOS 15 сделок при пороге 20 (на полном окне 26 сделок за
// три года против 149 у дефолтов). Отказ по редкости, а не по убыточности — форма прецедента UWGN.
// Редкость создана СОЧЕТАНИЕМ RSIPeriod=3 (единогласие) и RSILower=10 (3/4): по отдельности каждое
// решение пул сохраняет (RSIPeriod=2 при том же RSILower=10 -> 93 сделки/1.406; RSILower=15 при том
// же RSIPeriod=3 -> 47 сделок/2.106 — оба узла доминируют точку по PF и по размеру пула сразу).
//
// ЧУВСТВИТЕЛЬНОСТЬ ПУЛА (валовые 9385.25/5530.56, два проигрыша): одна добавленная убыточная сделка
// среднего размера (2765.28) роняет пункт 1 с 1.697 до 1.131, размером с худшую (3950.02) — до
// 0.990 (ниже единицы); на пункте 5 та же добавка даёт 0.791, на пункте 3 — 0.742.
//
// # Решение владельца 2026-09-07 (§5.8.1 спеки, коммит 9e0fecc)
//
// Точка ЗАВОДИТСЯ В ПРОД КАК ЕСТЬ при сработавшем пункте 2, вместе с четырьмя принимаемыми
// рисками: (1) пул 15 сделок необязателен к статистическим выводам; (2) пройденные пункты 1, 3, 4,
// 5 наследуют слабость того же пула; (3) редкость создаёт сочетание RSIPeriod=3 x RSILower=10; (4)
// живой раннер увидит редкость как долгое молчание тикера. Параметры точки решением не менялись.
// Запасной маршрут «завести на дефолтах ядра» (прецедент TGKA) закрыт ДО решения: дефолты MVID на
// полном окне при реальном круге издержек дают 0.995, ниже единицы.
//
// # Издержки — главный риск бумаги
//
// Шаг цены 0.05 руб. Круг из двух шагов: 0.217% при последней цене 46.25 руб, против 0.1%, которые
// считает модель издержек — модель ОПТИМИСТИЧНА В 2.2 РАЗА. Принятая точка содержит цель 0.2 ATR
// ~= 0.7% цены — втрое больше реального круга; ожидание, что этот узел издержками и убьёт, НЕ
// ОПРАВДАЛОСЬ (см. пятый пункт стоп-условия выше). Причина устойчивости — размер сделки: expectancy
// 280.85 руб на полном окне против 127.42 руб у baseline.
//
// Спека: docs/superpowers/specs/2026-09-07-mvid-rsi-pullback-prep-design.md, план:
// docs/superpowers/plans/2026-09-07-mvid-rsi-pullback-prep.md, протокол замеров:
