// уже стопа; на DIAS TPDailyATR (0.6) ШИРЕ StopDailyATR (0.5) — RSI-выход и здесь остаётся основным
// закрывающим механизмом (72.5% выходов на полной истории против 13.8% по TP и 13.8% по SL), а
