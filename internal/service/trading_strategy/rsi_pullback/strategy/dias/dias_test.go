// RSI-выход несёт 72.5% всех выходов принятой точки на полной истории (TP 13.8%, SL 13.8%) — это
// несущая конструкция, а не настройка. Живой раннер держит его обязательным для всех тикеров
// реестра (TestRegisteredTickersKeepTheRSIExitArmed). Проигрыш ветки без RSI-выхода — по существу,
// не по процедуре: поверх точки walk-forward без него даёт pooled OOS PF 1.199 на 81 сделке (фолды
// 2.925/0.987/0.620/0.706 — два фолда под единицей), при том что 81 сделка квалифицируется по
// -min-trades свободно.
func TestRSIExitIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseRSIExit != 1 {
		t.Fatalf("UseRSIExit = %d, want 1 — ветка без RSI-выхода даёт pooled OOS PF 1.199 против 2.361", p.UseRSIExit)
	}
	if p.RSIUpper <= p.RSILower {
		t.Fatalf("полоса RSI вырождена: RSIUpper = %v, RSILower = %v", p.RSIUpper, p.RSILower)
	}
}

// Дневной гейт взведён на единственной ветке «день исчерпан». Гейт сам по себе зарабатывает
// больше, чем любая другая ручка точки: без него полная история даёт 338 сделок при PF 1.348
// против 153 при 1.822 на дефолтах, а поверх собранной точки выключение гейта роняет walk-forward
// до 1.366 на 293 сделках. Ветка «день только начался» (FreshDayATR) держится на нуле ВОПРЕКИ теме
// day, открывавшей её на 0.3 во ВСЕХ 4 фолдах (единственная устойчивость 4/4 у той темы, но
// pooled OOS PF темы day 1.728/63 хуже темы day_spent с закрытой веткой 1.930/93 на 0.202 — разрыв
// больше, чем 0.103 на ELFV). Поверх собранной точки закрытая ветка выигрывает ВОСЕМЬ РАЗ ИЗ
// ВОСЬМИ на каждом уровне SpentDayATR (например 0.9: 2.365 против 2.093; 1.5: 2.985 против 2.276).
// SpentDayATR=0.9 — точечный локальный максимум на здоровой выборке (138 сделок) с ровными соседями
// 0.8 (2.140/159) и 1.0 (2.178/107); верхний край оси 1.5 даёт более высокий PF (2.985), но лишь
// 40 сделок за 30 месяцев (~13 на 10-месячное обучающее окно, ниже -min-trades 20) и отвергнут по
// размеру выборки.
func TestOnlySpentDayBranchIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseDayATRGate != 1 {
		t.Fatalf("UseDayATRGate = %d, want 1 — без гейта полная история даёт 338 сделок при PF 1.348 против 153 при 1.822", p.UseDayATRGate)
	}
	if p.FreshDayATR != 0 {
		t.Fatalf("FreshDayATR = %v, want 0 — открытая ветка свежего дня стоит теме day 0.202 pooled OOS PF против day_spent", p.FreshDayATR)
	}
	if p.SpentDayATR <= 0 {
		t.Fatalf("SpentDayATR = %v, want > 0 — иначе гейт взведён и не отсекает ничего", p.SpentDayATR)
	}
}

// Объёмный гейт ВЫКЛЮЧЕН — противоположность ELFV, где та же логика включила гейт. Решётка из
// 27 комбинаций (VolMult [1.0,1.5,2.0] x VolLookbackBars [3,5,12] x VolBaseDays [3,10,14]) поверх
// собранной точки на полной истории: НИ ОДНА не бьёт выключенный гейт (2.365 на 138 сделках);
// лучшая — base10/mult1.5/окно5 даёт 2.324 на 105 сделках, худшая — base14/mult2.0/окно3 1.706 на
// 82. У ELFV, для сравнения, все 24 комбинации решётки базы и множителя били baseline без гейта.
// Walk-forward подтверждает: UseVolume=1 на дефолтах гейта -> 1.896/80 (фолд 2 падает до 0.910),
// UseVolume=1 в лучшей точке решётки (1.5/окно5/base10) -> 2.300/81 — обе конфигурации хуже точки
// и на меньшей выборке. Выключенный гейт — норма каталога: из пятнадцати принятых точек он включён
// только у SVAV, UGLD, SIBN и ELFV.
func TestVolumeGateStaysOff(t *testing.T) {
	p := DefaultParams()
	if p.UseVolume != 0 {
		t.Fatalf("UseVolume = %d, want 0 — ни одна из 27 комбинаций решётки не бьёт выключенный гейт (2.365/138 сделок)", p.UseVolume)
	}
}

// Трейл выключен: собственная сетка темы trail держит UseTrail=1 фиксированным (как во всех
// пятнадцати cal_trail.json каталога) и свипует только TrailDailyATR — победители по фолдам
// 0.7/0/0.5/0.5, устойчивости нет (2 из 4). На полной истории уровни 1.0 и 1.3 дают результат,
// ПОБАЙТОВО равный выключенному трейлу (153 сделки, PF 1.822, net +75227.18), 0.7 почти совпадает
// (1.815), а реально связывающие уровни 0.3 и 0.5 ухудшают PF до 1.446 и 1.677. Поверх точки
// walk-forward с трейлом 0.5 даёт 2.220/101 против 2.361/98 без трейла — трейл и здесь только
// мешает. TrailDailyATR обязан быть нулём при выключенном трейле, иначе выключенное поле несёт
// непроверенное значение, которое оживёт при первом же переключении флага.
func TestTrailStaysOff(t *testing.T) {
	p := DefaultParams()
	if p.UseTrail != 0 {
		t.Fatalf("UseTrail = %d, want 0 — трейл 0.5 роняет walk-forward точки с 2.361/98 до 2.220/101", p.UseTrail)
	}
	if p.TrailDailyATR != 0 {
		t.Fatalf("TrailDailyATR = %v при выключенном трейле, want 0", p.TrailDailyATR)
	}
}
