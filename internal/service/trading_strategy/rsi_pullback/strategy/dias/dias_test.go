// EMASlow тоже 2 из 4 (150/100/50/50). Обе ключевые темы не набрали устойчивость выбора — DIAS
// повторяет паттерн ELFV (обе темы прошли/провалили по-разному, но ни одна не устойчива), а не
// паттерн SIBN (обе темы провалили оба критерия) и не паттерн SVAV (обе темы взяли оба критерия).
// Тикер принят по правилу владельца от 2026-08-22, объявленному ДО прогонов: литерал ставится и
// при непройденной планке, если принятая точка не упирается в стоп-условие плана (pooled OOS PF
// < 1.0 либо < 20 сделок за 30 месяцев адаптированной схемы). Стоп-условие НЕ сработало с большим
// запасом: data/params/rsi_pullback/dias/plateau_point.json даёт pooled OOS PF 2.361 на 98 сделках
// (win rate 74.49%, expectancy 459.56, compounded 50.33%), фолды
// 6.655(26)/1.318(25)/1.444(29)/1.889(18) — ВСЕ ЧЕТЫРЕ ПРИБЫЛЬНЫЕ, чего не добилась ни одна из
