// (IPO 2024-02-13), штатный протокол §8 docs/rsi_pullback/strategy.md (36/12/6) неисполним;
// использована схема -months 30 -train-months 10 -test-months 5 (прецедент IVAT 25/9/4). Числа
// DIAS сопоставимы с IVAT, но НЕ построчно с остальным каталогом (36/12/6). От core.DefaultParams()
// литерал отличается РОВНО ЧЕТЫРЬМЯ полями: RSIPeriod 4->5, RSILower 30->35, RSIUpper 70->55,
// SpentDayATR 0.8->0.9 — по числу отличий четвёртая по консервативности точка каталога из
// пятнадцати (меньше правят только RENI 2, SVAV 2, IVAT 3). ГРАНИЦА ПРИЁМА: для фиксированной точки
// это НЕ out-of-sample в строгом смысле — точку собрал человек, видевший всю 30-месячную историю,
// поэтому 2.361 нельзя читать как проверку протокола; вердикт протокола дают темы entry и trend, и
// он отрицательный по критерию устойчивости у обеих. На полной 30-месячной истории та же точка даёт
// 138 сделок, PF 2.365, net +67180.07, MaxDD 3.90%, против baseline core.DefaultParams() (153
// сделки, PF 1.822, net +75227.18, MaxDD 7.81%). Разбор каждого поля — в доке пакета (dias.go).
func TestCalibratedLiteralIsPinned(t *testing.T) {
	want := core.Params{
		RSIPeriod:       5,
		RSILower:        35,
		RSIUpper:        55,
		EMAFast:         10,
		EMASlow:         100,
		DailyATRPeriod:  14,
		UseDayATRGate:   1,
		FreshDayATR:     0,
		SpentDayATR:     0.9,
		StopDailyATR:    0.5,
		TPDailyATR:      0.6,
		UseVolume:       0,
		VolBaseDays:     14,
		VolLookbackBars: 3,
		VolMult:         1.2,
		UseRSIExit:      1,
		UseTrail:        0,
		TrailDailyATR:   0,
	}
	if got := DefaultParams(); got != want {
		t.Fatalf("откалиброванный литерал DIAS изменился:\n got: %+v\nwant: %+v", got, want)
	}
}

