// Стоп удержан на ДЕФОЛТЕ ЯДРА (0.5) ВОПРЕКИ моде темы risk (три фолда из четырёх — 1, 1, 1.3 —
// тянули к стопу >= 1.0). Капкан широкого стопа воспроизведён поверх точки буквально (полная
// история, TPDailyATR=0.6): 0.3 -> 146 сделок, 45 SL (30.8%), PF 1.792, MaxDD 5.65%; 0.5 -> 138,
// 19 SL (13.8%), PF 2.365, MaxDD 3.90%; 0.7 -> 137, 14 SL (10.2%), PF 2.143, MaxDD 5.85%;
// 1.0 -> 135, 6 SL (4.4%), PF 2.435, MaxDD 6.94%; 1.3 -> 135, 4 SL (3.0%), PF 2.443, MaxDD 4.48%.
// Счёт сделок почти не меняется по всей оси (146 -> 135, минус 7.5%), а доля стоп-выходов падает с
// 30.8% до 3.0% — верхний край покупает PF не защитой капитала, а вытеснением убытка в RSI-выход.
// Отличие DIAS от ELFV (где по тому же правилу взяли 0.7): здесь дефолт 0.5 одновременно ЛУЧШИЙ по
// просадке во всей оси (3.90%) и отстаёт от вырожденного максимума всего на 0.078 PF — платить за
// безопасность почти не приходится. Сосед 0.7 в walk-forward даёт 2.125/98 (и роняет фолд 2 до
// 0.999), сосед 0.3 — 1.788/106.
func TestStopIsArmed(t *testing.T) {
	if p := DefaultParams(); p.StopDailyATR <= 0 {
		t.Fatalf("StopDailyATR = %v, want > 0", p.StopDailyATR)
	}
}

// Специфичный для DIAS инвариант: шаг цены 0.5 ₽ = 0.0165% медианной цены 3033.5, реальный круг
// издержек здесь ≈ 0.13% (шаг даёт круг из двух тиков — 0.033% сверх моделируемых 0.1%). На стопе
// 0.3 ATR (0.92% цены) это 14.1% риска — под чертой 17%, по которой строка 0.3 вырезана из
// domrf/ и elfv/ (там же у ELFV при вдвое дороже шаге цены та же строка отдавала 22.4%). Именно
// поэтому строка 0.3 ВОЗВРАЩЕНА в сетку cal_risk.json DIAS — но принятая точка её всё равно не
// выбрала (см. TestStopIsArmed). Уже на 0.3 ATR этот инструмент отдаёт издержкам почти седьмую
// часть риска, и литерал не имеет права оказаться уже него через правку руками.
func TestStopStaysAboveTheCostFloor(t *testing.T) {
	if p := DefaultParams(); p.StopDailyATR < 0.3 {
		t.Fatalf("StopDailyATR = %v: на стопе 0.3 ATR издержки уже съедают 14.1%% риска, уже — ещё больше", p.StopDailyATR)
	}
}

