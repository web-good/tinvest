//	FreshDayATR 0.25 -> 0.3 плоское улучшение внутри плато 0.25-0.35 (4.308 / 4.406 / 4.041) при
//	                      росте выборки с 51 до 53 сделок.
//
// RSIPeriod 5, RSILower 17, SpentDayATR 0.8, StopDailyATR 0.5, UseVolume 0 и UseTrail 0
// сохранены. RSILower 17 лежит ВНЕ узлов сетки (шаг 5) и перемерен соседями заново: 16 -> 3.674,
// 18 -> 3.524, 19 -> 3.541, 20 -> 2.772, 15 -> 2.779 против 4.406 на 17 — заменить его на узел
// сетки не на что. TrailDailyATR обнулён: прежние 0.5 при UseTrail=0 были мёртвым числом.
//
// # Результат прогонов 2026-08-14 на расширенных сетках
//
// Оси расширены по требованию владельца: RSILower до полной шкалы [10 ... 50] с шагом 5 (было
// [10 ... 25]), RSIUpper до [50 ... 90] с шагом 5 (было [55 ... 80]), тренд с 4x4 до 5x7. Прогон
// штатным протоколом (-months 36 -train-months 12 -test-months 6 -min-trades 20, 4 фолда,
// OOS-окна 2024-08-14—2026-08-14) от baseline core.DefaultParams():
//
//	screen 1.082/155 · entry 0.895/136 · trend 1.677/90 · day 0.664/77 · day_spent 1.288/83 ·
//	volume 1.071/74 · risk 1.237/109 · exit 0.991/117 · trail 0.747/104
//
// Планку 1.5 взяла ОДНА тема из девяти — trend, и та за счёт четвёртого фолда с OOS PF 41.475
// на 20 сделках. Тема entry на широкой оси УХУДШИЛАСЬ против прежней узкой редакции: 0.895
// против 1.029, а выбор RSILower разъехался на 25/35/45/50 — четыре разных значения на четырёх
// фолдах, с уходом в верхний край шкалы, где порог уже не описывает откат (RSI(4) уходит под 45
// 2980 раз по будням за три года). Это ЧЕТВЁРТЫЙ подряд замер одного эффекта: wush
// 2.000 -> 1.674, lent 1.935 -> 1.355, domrf 1.254 -> 1.112, fesh 1.029 -> 0.895.
//
// Отдельно стоит запомнить фолд 3 (OOS 2025-08-14—2026-02-14): он убыточен ВО ВСЕХ ДЕВЯТИ темах
// (OOS PF 0.465-0.877 при просадках до 19.5%). Это окно инструмент не проходит ни на каких
// параметрах, и принятый литерал тоже показывает там худший из своих фолдов.
//
// # Замеры принятой конфигурации
//
// Rolling walk-forward сеткой из ОДНОЙ точки (калибратор ничего не выбирает, profit factor
// принадлежит конфигурации): pooled PF 4.406 на 53 сделках, фолды 5.993 / 21.965 / 1.840 /
// 2.260. Второй фолд вырожденно высок — опираться надо на худший, 1.840, против 1.599 у прежнего
// литерала. In-sample за 36 месяцев: 73 сделки против прежних 60, PF 3.997 против 2.214, win
// rate 76.71% против 71.67%, чистый PnL 63.37% против 32.05%, максимальная просадка 4.62%
// против 7.26%, exposure 1.56%. Прибыль в каждом году: 2023 +6 403, 2024 +20 096, 2025 +26 912,
// 2026 +9 962.
//
// Структура выходов (73 сделки): RSI 52 (71.2%, медиана 7 баров, +45 371), TP 15 (20.5%, медиана
// 2 бара, +35 758), SL 6 (8.2%, медиана 5 баров, −17 757). У прежнего литерала было 81.7% / 3.3%
// / 15.0% — цель ожила, стоп стал реже, медиана удержания упала с 12 баров до 7.
//
// Плато проверено 30 соседями по семи осям: RSIUpper 50 -> 4.125, 53 -> 4.357, 57 -> 4.220,
// 60 -> 3.034; TPDailyATR 0.3 -> 3.480, 0.75 -> 3.484, 1.0 -> 4.049; EMAFast 10 -> 3.966,
// 30 -> 3.883; EMASlow 100 -> 3.664, 200 -> 3.882; FreshDayATR 0.25 -> 4.308, 0.35 -> 4.041,
