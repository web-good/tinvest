//	EMAFast    10 -> 20   точечная проверка: 4.308 против 3.567 при большем счёте сделок (51
//	                      против 45). Тема trend устойчивости по своей ведущей оси не дала
//	                      (EMASlow 70/50/50/50 — 50 в трёх фолдах из четырёх, но точечно 150
//	                      лучше 50 и 100 при вдвое большей выборке), поэтому EMASlow оставлена
