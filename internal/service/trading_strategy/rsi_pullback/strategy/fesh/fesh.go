//   - РЕЖИМ ПАДАЮЩИЙ ПОЧТИ ВЕСЬ: 111.35 -> 58.00 (−47.9%), от пика 118.79 сейчас −51.2%,
//     максимальная просадка цены 51.2%. Трендовый фильтр открыт 46-47% времени во ВСЕХ 35 парах
//     сетки. Для long-only это значит, что in-sample занижен режимом, а не завышен, — обратная
//     ситуация относительно lent и domrf.
//   - Дневной ATR(14) идёт медианой 4.40% цены (среднее 4.41%, p10 2.98 · p25 3.51 · p75 5.09 ·
