// гейтится — ниже порога представительности), 2024 +16 704.84 ₽ (50 сделок, PF 2.124), 2025
// +7 158.15 ₽ (54, PF 1.218), 2026 -5 061.56 ₽ (24, PF 0.658). Хвосты (по дате входа): хвост 6
