// подрезал: тема risk первого круга голосовала выше потолка (1.3/1.3/1/2), но большинства не
// набрала и осталась на дефолте 0.5; узкая тема risk второго круга голосовала 0.8/0.75/0.7/0.7,
// тоже без большинства. Цена решения по гейту A в PF — 0 в обоих кругах.
//
// # Третий контур (профиль точки против дефолтов)
//
// Точка первого круга идентична дефолтам по всем показателям контура (доля SL 25.5%, удержание
// 8/21/38 баров, ночёвок 46.0%, переносов 2+ дня 2, входов в выходные/02-06 0/0, max DD 7.41%,
// expectancy +122.77 ₽). У точки 2 (EMAFast 5): SL 26.6%, удержание 7/20/38, ночёвок 45.3%,
// переносов 2, max DD 8.64%, expectancy +119.07 ₽; у точки 2b (EMAFast 3): SL 27.1%, удержание
// 7/20/32, ночёвок 46.6%, переносов 1, max DD 7.42%, expectancy +99.13 ₽. Подписи капкана широкого
// стопа (падение доли SL вместе с ростом удержания и ночёвок) нет ни у одного варианта — доля SL,
// наоборот, выросла против дефолтов.
//
// # Гейт D — пройден, даты остаются прокси
//
// Ноль сделок через все четыре даты-прокси (2023-12-01, 2024-09-27, 2025-08-13, 2026-07-18) у
// дефолтов, точки первого круга и обоих вариантов второго. Даты — ПРОКСИ гэпов и отсечек (§5.7,
// §1 спеки: движок дивидендов не моделирует, отсечки — порядка 3-7% цены раз в год по divscreen), а
// не полный реестр: список может быть неполным или избыточным. Нулевой гейт D снимает риск только в
// измеренных прокси-точках, а не риск отсечек и гэпов как таковой (§8 спеки, риск 2) — этот риск
// применим только при заведении в прод и здесь не актуален, поскольку RTKM в прод не заводится.
//
// # Итог
