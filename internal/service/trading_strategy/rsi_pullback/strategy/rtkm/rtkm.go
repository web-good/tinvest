// # Причина на бумаге
//
// 2026 год убыточен на дефолтах и на КАЖДОМ проверенном узле обеих осей тренда и стопа: ни одна
// одиночная ось его не лечит (§6.5, §6.7 спеки; Task 8, Task 11, Task 12). Единственный измеренный
// рычаг, чинящий 2026 год, — короткая EMASlow (12-20) в связке со стопом 0.7-0.8 (арбитр
