// конкретном узле, поэтому поле тренда оба раза осталось на дефолте 100, и точка обоих кругов
// унаследовала профиль дефолтов на 2026 год. Уплотнение шага во втором круге РАЗРУШИЛО единственное
// достигнутое большинство первого круга (EMASlow), как и предупреждала спека (§5.14, урок SFIN), и
// добавило лишь одно инертное в паре с EMASlow=100 поле (EMAFast 5).
//
// # Гейт A (потолок стопа по частоте срабатывания) — не связывал точку ни разу
//
// Таблица срабатываний SL на дефолтах поверх полного окна (§5.4 спеки): стоп 0.5 -> 35 SL-выходов
// (25.5%), PF 1.251, DD 7.41%; 0.6 -> 25 (18.4%), PF 1.473, DD 6.89%; 0.7 -> 21 (15.6%), PF 1.495,
// DD 7.01%; 0.8 -> 14 (10.4%), PF 1.660, DD 5.61%; 1.0 -> 9 (6.7%), PF 1.694, DD 7.81%; 1.3 -> 4
