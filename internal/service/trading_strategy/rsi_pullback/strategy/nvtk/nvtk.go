// Package nvtk supplies the ticker and calibrated rsi_pullback Params for NVTK (Novatek).
//
// ВАЖНО: этот литерал — снимок ПОСЛЕДНЕГО прогона калибровки. Если следующий прогон даст другую
// выигрышную комбинацию, литерал обязан быть ЗАМЕНЁН: оставить старые числа после нового прогона
// значит торговать конфигурацией, которую свежие данные не подтверждали.
//
// # Калибровка 2026-08-16
//
// Каталог data/params/rsi_pullback/nvtk/ собран с нуля по форме lent/ и gazp/ в расширенной
// редакции (вход 252 комбинации, тренд 35, обе ветки дневного гейта 24, риск 35), каждая ось
// пересажена на замеры самого NVTK. До этого прогона тикер был в состоянии «калибровка не
// проводилась» и возвращал core.DefaultParams(). Данные: 36 530 30-минутных баров, из них
// 25 647 будних, за 36.0 месяца с 2023-08-17.
//
// # Как ходит цена (без этого литерал не читается)
//
// NVTK — падающий инструмент со скучным дневным профилем и огромной ликвидностью. За окно цена
// потеряла 42.1% (1597.40 -> 925.30), падают ОБА окна протокола (train 2023-08-17—2026-02-15
// −25.4%, holdout 2026-02-15—2026-08-16 −22.5%), пик-минимум по 30-минутным закрытиям −56.5%.
// Трендовый фильтр EMAFast > EMASlow открыт лишь 43-47% времени во всех двадцати парах замера —
// как у WUSH (41-43%) и в отличие от LENT (52-53%), которой аптренд держал ворота открытыми.
// Лонговый результат в таком режиме рынком ЗАНИЖЕН, а не завышен, поэтому profit factor ниже
// читается как нижняя оценка.
//
// День раскрывается медленно: медиана пройденного дневного ATR ко второму бару 0.24 (бар 5 —
// 0.33, бар 8 — 0.45, бар 12 — 0.58), полный дневной размах в долях ATR предыдущего дня — p10
// 0.52, медиана 0.88, p90 1.60. Дневной ATR 3.07% цены медианой, круг издержек 0.1% цены стоит
// 0.033 ATR. Оборот 2475 млн ₽/день медианой при лоте 1 (2023 — 1191, 2024 — 1945, 2025 — 3496,
// 2026 — 2871) — самый ликвидный инструмент вселенной, ограничения по исполнению, из-за которых
// осторожничали с LENT (38 млн), здесь нет вовсе.
//
// # Планка не взята — шестой тикер подряд, и с самым большим отрывом
//
// Требование то же, что объявлялось для WUSH, LENT, LSNGP и GAZP: pooled OOS PF >= 1.5 при >= 20
// сделках одновременно на темах entry и trend плюс устойчивость выбора ведущей оси в 3 фолдах из
// 4. Вышло: entry 1.218 на 120 сделках (RSILower 50/50/50/30 — устойчивость есть, порога нет),
// trend 1.044 на 71 (EMASlow 120/50/150/170 — четыре разных значения, порога нет). Остальные семь
// тем: volume 1.674/53, screen 1.213/66, trail 1.172/77, day_spent 1.158/72, exit 1.001/74,
// risk 0.949/73, day 0.948/68. Выше 1.5 поднялась ОДНА тема из девяти, четыре темы ниже единицы
// или на ней — это худший тематический результат в каталоге, хуже FESH (одна тема из девяти) по
// величине и хуже LSNGP (девять из девяти) по разрыву.
//
// Причина не в тикере, а в том, что тематические файлы меряют каждую ось ПОВЕРХ дефолтов, а на
// NVTK дефолты стоят ровно там, где стратегия не работает. Ниже — три вещи, которые это
// показали, и все три получены точечными прогонами (сетка из одной точки, калибратор не выбирает
// ничего).
//
// # Дневной гейт и есть вся стратегия на этом инструменте
//
// С выключенным дневным гейтом принятая конфигурация даёт pooled PF 0.996 на 614 сделках. С
// веткой «день исчерпан» она даёт 1.868 на 121 сделке при пороге 0.8, 2.823 на 93 при 0.9,
// 3.053 на 73 при 1.0, 4.075 на 34 при 1.25. Смысл механический: вход разрешён только после
// того, как день уже прошёл 0.9 своего ATR, то есть покупается исчерпание дневного снижения, а
// не всякий откат. Ветка «день только начался» вредна и выключена (FreshDayATR=0): её включение
// с порогом 0.3 роняет результат до 1.373 на 219 сделках, потому что она добавляет входы в
// начале дня, когда падение ещё впереди.
//
// Ось порога монотонная, и читать её как «чем выше, тем лучше» нельзя: profit factor растёт
// вместе с отсевом сделок, а фолды вырождаются — на 1.0 первый и четвёртый дают 6.928 и 6.650
// на 20 и 19 сделках. Принято 0.9: 93 сделки, ни один фолд не ниже 1.893, ни один не вырожден.
// Сосед 0.8 записан файлом plateau_spent08.json как главный контрдовод — у него самые ровные
// фолды набора (1.858 / 1.823 / 1.895 / 1.902 на 121 сделке) ценой трети profit factor.
//
// # Глубина отката перевёрнута против всего каталога
//
// На LENT, WUSH и UGLD вход искали на RSILower 20-25. Здесь ось монотонна в обратную сторону:
// при прочих принятых полях 30 даёт 1.229 на 36 сделках, 35 — 1.819 на 41, 40 — 2.361 на 62,
// 45 — 2.485 на 80, 50 — 2.823 на 93. Глубокий провал RSI на падающем инструменте — чаще
// продолжение падения, чем откат внутри тренда, и это же подтвердила слепая тема entry, выбравшая
// 50 в трёх фолдах из четырёх. Принятое значение стоит НА КРАЮ оси, и край здесь
// определительный, а не обрезанный: 50 — средняя линия RSI, выше неё «отката» нет по
// определению, и тест сеток это сторожит. Сосед 40 держится файлом plateau_rsilower40.json.
//
// Период RSI выбран 5 против 4 у baseline и у трёх фолдов темы entry. Цена выбора видна на
// третьем фолде — самом слабом у всех конфигураций: RSI(4) даёт там 0.750, RSI(5) — 1.893,
// RSI(6) — 1.326, RSI(7) — 1.383, при pooled 2.425 / 2.823 / 2.059 / 2.040 и 120 / 93 / 79 / 70
// сделках. Это единственное поле, где принятое значение расходится с выбором слепой темы.
//
// # Стоп 0.5 — настоящий максимум, а не вытеснение убытков
//
// На GAZP ось стопа была монотонной (PF рос с шириной при падающей доле стоп-выходов), и там
// стоп выбирали против лидерборда. Здесь картина обратная и потому доверия больше: 0.3 — 1.847,
// 0.4 — 2.035, 0.45 — 2.571, 0.5 — 2.823, 0.55 — 2.591, 0.6 — 2.526, 0.7 — 2.345, 1.0 — 2.066.
// Максимум внутренний, плато вокруг него пологое, и стоп остаётся РАБОЧИМ выходом — 24.8% всех
// выходов против 11.0% у GAZP. Полный дневной размах не достаёт до 0.5 ATR лишь в 9.1% дней,
// то есть уровень стоит в зоне, куда цена реально ходит. Цель 1.0 ATR выбрана по такой же
// пологой оси (0.6 — 2.615, 0.7 — 2.677, 0.8 — 2.710, 1.0 — 2.823, 1.2 — 2.365, 2.0 — 2.441) и
// срабатывает в 6.6% сделок.
//
// # Оба необязательных гейта отвергнуты
//
// Объёмный гейт формально улучшает результат (1.2x при базе 10 дней — 3.032 на 78 сделках) и
// был выбран темой screen во всех четырёх фолдах, но это ровно тот артефакт метрики, который
// разобран на GAZP: у КАЖДОЙ конфигурации с гейтом первый фолд вырождается (17.146 при базе 10 и
// 17.117 при базе 5 на 19 сделках), и калибратор, ранжирующий по profit factor, предпочитает
// вырождение честной строке. В литерал гейт не вошёл. Трейл тоже отвергнут замером: 0.3 — 1.802,
// 0.5 — 2.165 против 2.823 без него, а с погашенным RSI-выходом — 1.544 при win rate 40.2%.
//
// # Замеры принятой конфигурации
//
// Точечный walk-forward (data/params/rsi_pullback/nvtk/plateau_point.json): pooled PF 2.823 на 93
// сделках, фолды 3.493 / 2.935 / 1.893 / 3.414 — все четыре выше планки, вырожденных нет,
// минимальный фолд 20 сделок. In-sample за 36 месяцев: 121 сделка, PF 2.372, win rate 71.90%,
// просадка 5.98%, CAGR 21.35%, exposure 6.02%. Holdout-полугодие (падение на 22.5%): 23 сделки,
// PF 3.422, просадка 5.95% — на baseline то же окно давало PF 0.574 на 17 сделках. Каждый
// календарный год прибылен: 1.010 / 1.639 / 2.793 / 2.792. Выходы делятся как RSI 68.6% (медиана
// 14 баров), SL 24.8% (12), TP 6.6% (14); медиана удержания по всем сделкам 13 баров, максимум
// 103, на бары выходных приходится 14.0% выходов. Плато по шестнадцати соседям 1.825-2.873 (без
// оси дневного гейта, где разброс задан отсевом сделок), и единственный обрыв — глубокая сторона
// входа: RSILower 30 роняет результат до 1.229.
//
// ГРАНИЦА ПРИЁМА: для фиксированной точки перечисленные числа НЕ являются out-of-sample.
// Конфигурацию собрал человек, видевший всю историю, включая тестовые окна, поэтому сравнивать
// 2.823 с планкой 1.5 нельзя, и штатный протокол §8 этот тикер НЕ подтверждает — его вердикт
// записан выше: одна тема из девяти. Наличие литерала снимало техническую блокировку, но правом
// ставить NVTK в RSI_PULLBACK_TICKERS не было: это отдельное решение владельца, как было с domrf,
// fesh, wush и lent.
//
// РЕШЕНИЕ О ВСЕЛЕННОЙ: 2026-08-17 владелец завёл NVTK в RSI_PULLBACK_TICKERS — вместе с reni и
// lsngp. За это решение говорило то, чего не было ни у одного соседа: падающий режим в обоих
// окнах (результат не куплен рынком), 2475 млн ₽ дневного оборота — самый ликвидный тикер
// вселенной, то есть риск исполнения снят, — и стоп, который реально срабатывает в четверти
// сделок. Против говорило главное, и заведение этого не отменяет: девять слепых тем дали медиану
// 1.17, и вся разница между ними и принятой точкой — работа человека, смотревшего на OOS-числа.
// Условия пересмотра — docs/rsi_pullback/live.md §10, риск 12.
//
// Файлы сеток и полный разбор каждой темы — data/params/rsi_pullback/nvtk/, отчёты лежат
// локально (каталог reports/ в .gitignore).
