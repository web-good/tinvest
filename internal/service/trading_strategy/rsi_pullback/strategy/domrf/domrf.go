// ПЕРЕКАЛИБРОВАН 2026-08-14 на расширенных сетках (прежний литерал от 2026-08-10 заменён).
// Тикер торгуется в проде по решению владельца от 2026-08-10; замена литерала — продолжение
// того же решения, а не новое подтверждение edge. Штатный протокол §8 docs/rsi_pullback/strategy.md
// этот тикер по-прежнему НЕ подтверждает, и причина не в параметрах, а в длине истории.
//
// # Почему протокол здесь другой
//
// Кэш DOMRF_Minutes30.json на 2026-08-14 — 8515 баров (6221 будний) за 8.8 месяца с 2025-11-20,
// дневной кэш 239 баров (187 будних). Штатные -months 36 -train-months 12 -test-months 6 не
// запускаются в принципе: одного фолда не хватает на окно. Прогоны шли по
// -months 9 -train-months 3 -test-months 2 -min-trades 15 -metric profit_factor, это 3 фолда с
// OOS-окнами 2026-02-14—04-14, 04-14—06-14, 06-14—08-14. Порог -min-trades подобран замером, а
// не на глаз: при 8 калибратор в двух фолдах из трёх выбирал комбинации с нулём убыточных сделок
// (in-sample PF 6800+), при 20 квалифицированных комбинаций не оставалось вовсе и вырождение
// возвращалось; 15 — единственный порог, на котором ни один фолд не выродился.
//
// Прогоны велись от baseline core.DefaultParams(), а не от прежнего литерала DOMRF: свип поверх
// точки, уже подогнанной к этой же истории, мерил бы улучшение поверх подгонки.
//
// # Что известно об инструменте (замеры по кэшу на 2026-08-14, правилами ядра)
//
//   - РЕЖИМ БОЛЬШЕ НЕ ОДНОФАЗНЫЙ, и это главное изменение против разбора 2026-08-10. Тогда вся
//     история была пост-IPO аптрендом; теперь в ней есть падающий участок: пик 2567.20 пройден,
//     текущая цена 2121.00 (−17.4% от пика), максимальная просадка цены за историю 29.1%.
//     По месяцам: 2025-11 −1.7% · 12 +7.5% · 2026-01 +12.6% · 02 +7.6% · 03 −3.6% · 04 +2.3% ·
//     05 +7.3% · 06 −5.4% · 07 −2.1% · 08 −5.3%. Первый фолд протокола обучается на растущем
//     окне и тестируется на падающем — именно поэтому он убыточен почти во всех темах.
//   - Дневной ATR(14) идёт медианой 2.02% цены (среднее 2.24%, p10 1.64 · p25 1.81 · p75 2.54 ·
//     p90 3.36, n=173) — самый узкий инструмент вселенной, вдвое уже lent (3.16%) и wush (4.25%).
//   - ОТСЮДА САМЫЕ ДОРОГИЕ ИЗДЕРЖКИ: круг комиссии 0.049 дневного ATR против 0.032 у lent и
//     0.023 у fesh. На стопе 0.3 ATR комиссия съедает 16.3% риска, на 0.5 — 9.8%, на 0.7 — 7.0%.
//     Нижние строки cal_risk.json читать только вместе с этим числом.
//   - Полный дневной размах медианой 0.99 ATR предыдущего дня (p10 0.53 · p25 0.71 · p75 1.27 ·
//     p90 1.91). Стоп переживается целиком в 24.4% дней при 0.7, в 53.5% при 1.0 и в 83.7% при
//     1.3 — то есть широкий стоп на этом тикере перестаёт быть выходом.
//   - День раскрывается рано: медиана пройденной доли ATR 0.32 к 07:00, 0.44 к 09:00, 0.55 к
//     10:00, 0.96 к 19:00. Порог FreshDayATR 0.3 оставляет ветке «день только начался» 9.5%
//     будних баров, 0.4 — 17.2%, 0.25 — 6.8%.
//   - Трендовый фильтр открыт 57-63% времени во всех 35 парах сетки — шире, чем у lent (52-53%)
//     и намного шире wush (41-43%). Вырожденных углов в сетке тренда нет, но и отсекает она
//     меньше: в растущей половине истории пара EMA почти всегда открыта.
//   - ЛИКВИДНОСТЬ — сильная сторона: 535 млн ₽/день средним при медиане будних дней 424 млн
//     (минимум по месяцам — 288 млн в декабре 2025). Это второй по ёмкости инструмент вселенной
//     после wush и на порядок выше lent (38 млн медианой).
//   - Кроссы RSI вниз (будние, за всю историю): RSI(4) 155/244/351/446/570 на уровнях
//     15/20/25/30/35, RSI(6) 60/114/183/291/394, RSI(7) 36/85/142/232/345. Уровень 10 убран из
//     сетки входа: 9 будних кроссов у RSI(7) и 19 у RSI(6) — мертвее, чем у reni (23).
//
// # Результат прогонов 2026-08-14: планка НЕ взята, и с большим отрывом
//
// Девять тем, pooled OOS PF и счёт сделок: screen 1.264/32, entry 1.112/25, trend 1.358/33,
// day 1.607/28, day_spent 1.212/39, volume 1.085/26, risk 1.354/30, exit 1.080/33, trail
// 0.850/32. Выше 1.5 поднялась ОДНА тема из девяти — day. Для сравнения, у lsngp все девять были
// выше 1.5, у lent — четыре. Ведущие оси: RSILower 35/30/30, EMASlow 100/50/170.
//
// Ещё нагляднее общий рисунок: первый фолд убыточен в ВОСЬМИ темах из девяти (OOS PF 0.58-0.73),
// прибылен только у day (1.623). Тикер в феврале-апреле 2026 терял на любых параметрах, кроме
// тех, что фильтруют состояние дня. Никакой набор чисел этого не чинит — это свойство окна.
//
// Расширение сетки входа, как и на двух предыдущих тикерах, теме не помогло: широкая редакция
// (224 комбинации, RSIUpper x RSIPeriod x RSILower) дала pooled 1.112 на 25 сделках, узкая 4x4 —
// 1.254 на 13 сделках при 5 фолдах и 1.394 на 20 при 3. Это третий подряд замер того же эффекта
// (wush 2.000 -> 1.674, lent 1.935 -> 1.355), и здесь он сопровождается вырождением: на широкой
// сетке фолды 3-5 показывали in-sample PF 6800+ при 0-1 сделке в тесте.
//
// # Литерал, выбранный 2026-08-14
//
//   - RSILower 35 — тема entry выбрала 35/30/30. Взят край, а не большинство: на 35 выборка
//     вырастает с 28 до 42 OOS-сделок (in-sample 65 против 47) при pooled 2.921 против 3.344,
//     а на тикере с 8.8 месяца истории счёт сделок стоит дороже десятых долей PF. Соседняя
//     ступень 40 уже размывает: 2.259 на 46 сделках.
//   - RSIUpper 70 — тема exit выбрала 65/65/80, но мерила полосу при RSILower 30. На принятом
//     входе 35 точечная проверка даёт 2.921 против 2.864 у 65 и 2.537 у 75, и главное — у 70
//     ровнее фолды (6.748/2.401/2.514 против 5.596/3.798/1.640).
//   - EMA 20/100 — тема trend устойчивости не дала (EMASlow 100/50/170), медленная оставлена на
//     baseline 100 как единственное значение, выбранное больше одного раза; быстрая поднята с 10
//     до 20 точечной проверкой (2.921 против 2.510).
//   - FreshDayATR 0.3 — ветка «день только начался» включается для DOMRF ВПЕРВЫЕ. Тема day —
//     единственная, взявшая планку, и единственная с тремя прибыльными фолдами; выбор 0.5/0.3/0.3.
//     Цена включения видна в счёте сделок: без неё остаётся 18 OOS-сделок вместо 42, а третий фолд
//     схлопывается до одной сделки.
//   - SpentDayATR 1.0 — выбор темы day (1.25/1.0/1.0). Порог 0.8 даёт больше сделок (60), но
//     роняет первый фолд до 0.865 и pooled до 1.743.
//   - StopDailyATR 0.7 — НЕ победитель темы risk (там 1.3/1.3/0.7). Взят осознанно: pooled PF
//     растёт со стопом монотонно (0.5 -> 1.892, 0.7 -> 2.921, 1.0 -> 2.360 на этой точке, а на
//     соседней 1.3 -> 4.160), но доля стоп-выходов падает — 14.6% сделок при 0.5, 4.3% при 0.7,
//     2.1% при 1.0. Стоп 1.3 переживается целиком в 83.7% дней и выходом быть перестаёт.
//   - TPDailyATR 1.0 — ось почти инертна (0.5 -> 2.881, 1.5 -> 2.917), цель срабатывает в 2-3
//     сделках из 65. Оставлена на 1.0 как середина плато; выборкой не проверена.
//   - UseVolume 0 и UseTrail 0 — темы volume (1.085) и trail (0.850) обе ниже единицы или около;
//     трейл прямо вредит, объёмный гейт срезает выборку до 16 OOS-сделок.
//
// Замеры принятой конфигурации. Rolling walk-forward сеткой из ОДНОЙ точки (калибратор не
// выбирает ничего, profit factor принадлежит конфигурации): pooled PF 2.921 на 42 сделках, фолды
// 6.748 / 2.401 / 2.514 — все три прибыльны, ни один не вырожден. In-sample за 8.8 месяца: 65
// сделок, PF 4.213, win rate 84.62%, просадка 3.86%, чистый PnL 28.51% при fraction=1, exposure
// 7.42%. Структура выходов: RSI 60 сделок (92.3%), стоп 3 (4.6%), цель 2 (3.1%), медиана
// удержания 9 баров.
//
// Плато проверено 19 соседями по семи осям: RSILower 30 -> 3.344, 40 -> 2.259; RSIUpper 65 ->
// 2.864, 75 -> 2.537; EMAFast 10 -> 2.510; EMASlow 150 -> 2.648, 50 -> 1.880; FreshDayATR 0.25 ->
// 2.196, 0.4 -> 1.579; SpentDayATR 0.8 -> 1.743, 1.25 -> 2.962; StopDailyATR 0.5 -> 1.892, 1.0 ->
// 2.360; TPDailyATR 0.5 -> 2.881, 1.5 -> 2.917; RSIPeriod 5 -> 1.856, 6 -> 1.865. Разброс
// 1.579-3.344 без единого провала ниже 1.5 — точка на пологом плато.
//
// # Что изменилось против прежнего литерала (RSI 25/70, EMA 5/150, день 0/1.0, стоп 1.0, цель 1.5)
//
// На одинаковых фолдах прежний литерал даёт pooled PF 3.935, но на 14 сделках, из которых первый
// фолд вырожден (OOS PF 2792 при пяти сделках без единого убытка), а третий — ноль (одна сделка,
// убыточная). Новый даёт 2.921 на 42 сделках без вырожденных фолдов. Решающее не PF, а вот что:
// ПРЕЖНИЙ ЛИТЕРАЛ ПЕРЕСТАЛ ТОРГОВАТЬ. Его последний вход в бэктесте — 24 июня 2026; июль и август
// пусты, потому что EMA(150) на падающем участке закрывает трендовый фильтр наглухо. Новая
// конфигурация в те же месяцы отработала 47 сделок из 65 в плюс и дала прибыль в каждом месяце
// истории. Отчёт-основание прежнего решения
// (reports/DOMRF/DOMRF_rsi_pullback_Minutes30_20260810_131435.md) описывает прод до 2026-08-14 и
// с этой даты историческим документом и остаётся.
//
// ГРАНИЦА ПРИЁМА: 2.921 — НЕ out-of-sample. Точку собрал человек, видевший всю историю, включая
// тестовые окна. Планка §8 (pooled OOS PF >= 1.5 на entry и trend одновременно) НЕ взята: 1.112 и
// 1.358. Тикер торгуется решением владельца; условия пересмотра — docs/rsi_pullback/live.md §10,
// риск 6. Следующий честный пересмотр возможен, когда истории накопится 18-24 месяца, то есть не
// раньше мая 2027. Литерал прибит domrf_test.go.
