// # Окно и схема
//
// Расчётное окно 2023-09-05 .. 2026-09-05 (36 месяцев), без обрезки: структурного разрыва у бумаги
// нет — число акций не менялось, редомициляции и остановок торгов не было. Схема 36/12/6 (train 12
// месяцев, OOS 6, четыре фолда) плюс ОБЯЗАТЕЛЬНЫЙ контроль 24/12/3: торговая сессия внутри окна
// расширялась дважды, медиана баров в буднем дне по полугодиям 19 -> 29 -> 34 -> 35 -> 35 -> 35.
// Процедура каноническая, все одиннадцать тем считаются поверх дефолтов ядра: baseline торгует
// прибыльно и даёт сопоставимый с каталогом объём выборки, поэтому якорь не нужен.
//
// # Baseline (дефолты ядра, 36 месяцев, комиссия 0.0005)
//
// 142 сделки, PF 1.313, net +22 085.26 руб (+22.09%), win rate 66.20%, max DD 16 170.49 руб
// (11.70%), exposure 4.34%, expectancy 155.53 руб = 0.156% капитала. Выходы: RSI 86 (60.6%) /
// SL 38 (26.8%) / TP 18 (12.7%). Удержание: медиана 9 баров, p90 19, максимум 32. Ночёвок 47.2%.
// Входов в выходную сессию 0, выходов 4.9%.
//
// Полугодия baseline: 0.850 (24 сделки, -1 744 руб), 2.407 (23, +9 670), 1.846 (36, +14 849),
// 2.789 (24, +12 981), 1.105 (15, +724), 0.289 (20, -14 395). Прибыльны четыре из шести, и ХУДШЕЕ
// полугодие — ПОСЛЕДНЕЕ, вплотную к сегодняшнему дню.
//
// Walk-forward дефолтов: 36/12/6 -> pooled OOS PF 1.354 на 95 сделках (пофолдово 1.846/36,
// 2.793/24, 1.105/15, 0.289/20); контроль 24/12/3 -> pooled OOS PF 0.530 на 35 сделках.
// ДЕФОЛТЫ ЯДРА ПРОВАЛИВАЮТ ПУНКТ 3 СТОП-УСЛОВИЯ, поэтому запасной маршрут «дефолты ядра»
// (прецедент TGKA) на этой бумаге НЕДОСТУПЕН: точка обязана быть лучше дефолтов, а не «не хуже».
//
// # Издержки — главная особенность бумаги
//
// Шаг цены 0.05 руб в обеих ценовых полосах (0-50 и 50-100 руб). Круг из двух шагов: 0.165% при
// медианной цене окна (60.75 руб), 0.172% при медиане последних 12 месяцев (58.25 руб) и 0.234%
// при текущей цене 42.75 руб — против 0.1%, которые считает модель издержек. МОДЕЛЬ ОПТИМИСТИЧНА
// ВДВОЕ НА СЕГОДНЯШНЕЙ ЦЕНЕ. Чувствительность baseline: 0.1% -> 1.313, 0.2% -> 1.085,
// 0.24% -> 1.002, 0.3% -> 0.885, 0.4% -> 0.712. Средняя сделка baseline приносит 0.156% капитала
// при настоящем круге 0.165-0.234%: у дефолтов запаса над издержками НЕТ ВОВСЕ.
//
// # Стоп-условие из ПЯТИ пунктов (объявлено до прогонов)
//
// Работа останавливается, если принятая точка даёт: (1) pooled OOS PF < 1.0 на 36/12/6, либо
// (2) меньше 20 сделок в пуле OOS, либо (3) pooled OOS PF < 1.0 на контроле 24/12/3, либо
// (4) то же при -commission 0.001 (круг 0.2%), либо (5) то же при -commission 0.0012 (круг 0.24% —
// настоящие два шага 0.05 руб на цене 42.75 руб). Пункт 5 — отличие RTKMP от каталога.
//
// # Риск-гейты
//
// Гейт A (выживаемость эффективной защиты min(StopDailyATR, TrailDailyATR при UseTrail=1)):
// принимается только защита, достижимая не менее чем в 30% будних дней окна. Таблица (n = 764):
// 0.3 — 99.5%, 0.5 — 90.8%, 0.7 — 73.8%, 0.8 — 63.7%, 1.0 — 47.1%, 1.3 — 25.5%, 1.5 — 17.7%,
// 2.0 — 5.6%. ПОТОЛОК 1.0. Гейт нужен: ось стопа показывает капкан широкого стопа (пул сделок
// стоит с узла 0.6, 140 -> 138, а PF растёт с 1.313 до 1.886), причём просадка при этом ПАДАЕТ, то
// есть гейт B капкан не ловит.
//
// Гейт B (просадка точки): max DD на полном окне не выше 1.3 x 11.70% = 15.21% — каталожная норма.
// Жёсткий вариант «не выше baseline» здесь не применяется: просадка baseline RTKMP одна из самых
// низких в каталоге, и требовать от точки быть не хуже неё значило бы запрещать любой размен
// просадки на доходность там, где он ещё безопасен. Плюс правило разрешения ничьих: при разнице
// pooled OOS менее 0.05 в точку идёт вариант с меньшей просадкой.
//
// # Априор скринера и свойства бумаги
//
// pullback_screen 2026-09-05: оборот 107 млн руб, дневной ATR 2.79%, TradesMed 39, PFmed 1.35,
