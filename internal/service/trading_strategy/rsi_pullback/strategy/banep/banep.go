// Package banep supplies the ticker and rsi_pullback Params for BANEP (Башнефть,
// привилегированные акции, лот 1).
//
// СОСТОЯНИЕ: КАЛИБРОВКА НЕ ПРОВОДИЛАСЬ. Пакет возвращает core.DefaultParams() — baseline ядра, не
// подобранный под этот инструмент. Так и должно быть до конца калибровки: пакет заведён заранее,
// чтобы прогоны шли через тот же реестр, что и у остальных семнадцати тикеров, а не через
// generic-ветку. Состояние держит banep_test.go.
//
// СХЕМА ПРОГОНОВ КАНОНИЧЕСКАЯ: -months 36 -train-months 12 -test-months 6 -min-trades 20
// -metric profit_factor, четыре фолда встык. Расчётное окно — 2023-08-28 … 2026-08-28 (34 069
// получасовых баров, из них 24 039 будних; дневная серия 1129 свечей, в окне 764 будних). Числа
// BANEP сравнимы с каталогом напрямую, в отличие от IVAT (25/9/4), DIAS (30/10/5) и YDEX (25/9/4).
//
// ЗАПАС ИСТОРИИ ПО ПОЛУЧАСОВОЙ СЕРИИ НУЛЕВОЙ: первый бар кэша совпадает с левой границей
// расчётного окна. -refresh во время калибровки НЕ запускать — он сдвинет обе границы. Дневная
// серия имеет запас 12 месяцев, его хватает на прогрев ATR(14).
//
// АПРИОР, записанный ДО прогонов. Скринер (pullback_screen_Minutes30_20260804_232456.md, строка 15
// из 99 прошедших вселенную): оборот 201 млн ₽, дневной ATR 2.97%, TradesMed 34, PFmed 1.51,
// Capped 0/24, SilentCfg 0/24, плато 67%, PFmed HO 0.65 на 15 сделках. Контрольный прогон дефолтов
// ядра на расчётных 36 месяцах: 134 сделки, PF 1.336, net +20 387 ₽ — середина ряда baseline
// каталога (YDEX 1.778, LSNGP 1.554, ELFV 1.546, IVAT 1.432, LENT 1.417, SVAV 1.368, BANEP 1.336,
// BSPB 1.114, SIBN 1.027, NVTK 0.984). Веса априору не придаётся: вопрос «предсказывают ли колонки
// скринера исход протокола» каталог закрыл пять раз подряд (SIBN, ELFV, DIAS, BSPB, YDEX) — не
// предсказывают ни снизу, ни сверху.
//
// ПРОЦЕДУРА ТЕМ КАНОНИЧЕСКАЯ. Дефолты ядра стоят ВНУТРИ рабочей зоны, поэтому все десять тем идут
// поверх них, якоря нет, и вердикт сравним с каталогом по построению.
//
// ЧТО ЗНАЕМ ОБ ИНСТРУМЕНТЕ ДО ПРОГОНОВ (замеры на расчётном окне):
//
//   - Режим ТЯЖЕЛО МЕДВЕЖИЙ: растёт ОДНО полугодие из шести, и оно первое (+48.3%); дальше −28.6%,
//     −8.2%, −25.5%, −11.6%, −15.9%. Итог окна −46.4%, максимальная просадка −69.6%, активная на
//     правой границе окна. Читается в обе стороны: лонговый edge получен ПРОТИВ режима, но весь
//     положительный net может принадлежать первому полугодию — разбивка точки по полугодиям
//     обязательна.
//   - ИЗДЕРЖКИ — УЗКОЕ МЕСТО. Шаг цены 0.5 ₽ при медианной цене 1148 ₽ = 0.0436%, реальный круг
//     0.187% против моделируемых 0.1%. Baseline: PF 1.336 -> 1.087 (круг 0.2%) -> 0.877 (0.3%),
//     то есть при реальном круге бумага почти безубыточна. Широкий стоп резко устойчивее: при
//     круге 0.2% стоп 0.5 даёт 1.087, 0.7 — 1.287, 1.0 — 1.369.
//   - ДИВИДЕНДНАЯ ОТСЕЧКА — ВЕДУЩИЙ РИСК: середина июля каждый год, гэп −12.74% (2024-07-12),
//     −10.67% (2025-07-14), −5.28% (2026-07-13). Тяжелее полугодового цикла BSPB (худший −8.44%).
//     За 36 месяцев позиция была открыта в 176 календарных днях из 781 буднего (23%) и НИ РАЗУ не
//     совпала с отсечкой — это совпадение, а не механизм: при такой занятости ожидание попадания
//     около единицы, а одно попадание стоит около −10% капитала при fraction 1.0.
//   - Ликвидность СРЕДНЯЯ, на границе вселенной: медиана оборота 149 млн ₽/день, p10 49 млн —
//     ровно гейт скринера (50 млн). Дней короче 20 баров — 18.4% (144 из 781), уровень ELFV
//     (18.9%), поэтому тема vol_window значима.
//   - Дневной ATR(14) 2.86% медианой (p10 1.82, p90 4.36) — практически как у YDEX (2.84%). День
//     проходит своё ATR быстро: медиана размаха дня к бару 0.67 ATR.
//   - Дневной гейт несёт ВЕСЬ edge: без него 485 сделок при PF 0.973 против 134 при 1.336.
//     RSI-выход тоже: без него 126 сделок при 0.861.
//   - Edge концентрируется в пересечении «быстрый RSI x исчерпанный день»: RSI(3) при
//     SpentDayATR 1.0 даёт 129 сделок при PF 1.862 — сильнейший замер окна. Зона вдвое тоньше
//     дефолтной по выборке, и это главный риск калибровки.
