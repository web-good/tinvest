// СОСТОЯНИЕ: ОТКАЛИБРОВАН 2026-08-28. Литерал ниже собран из пофолдовых победителей десяти тем
// каталога data/params/rsi_pullback/banep/ и прибит снимком в banep_test.go.
//
// ВЕРДИКТ ПО ПЛАНКЕ: НЕ ВЗЯТА, обеими ключевыми темами и по обоим критериям. Тема entry дала
// pooled OOS PF 1.004 на 74 сделках при требуемых 1.5, ведущая ось RSILower выбрана как 45/25/30/25
// — два фолда из четырёх. Тема trend дала 1.258 на 81 сделке, ведущая ось EMASlow — 50/40/50/70,
// тоже два из четырёх. Вырожденных фолдов нет, скидок не делалось. Форма провала повторяет ELFV и
// YDEX с одним отличием: там обе темы брали критерий PF и валили устойчивость, здесь тема entry не
// взяла даже PF.
//
// ЛИТЕРАЛ ПРИ НЕПРОЙДЕННОЙ ПЛАНКЕ — решение владельца 2026-08-28 («литерал ставится и тикер
// заводится независимо от того, взята планка или нет»), то же правило, что у IVAT, SIBN, ELFV,
// DIAS, BSPB и YDEX. Наличие литерала здесь НЕ означает подтверждённый протоколом edge.
//
// СЕТКИ ЭТОГО ТИКЕРА ДЕРЖАТСЯ МАКСИМАЛЬНО ШИРОКИМИ — отдельное решение владельца 2026-08-28.
// Первый вариант каталога обрезал шесть краёв по замерам (стоп 0.3 по издержкам, стоп 1.5 по
// выживаемости, SpentDayATR 1.5 по выборке, RSIPeriod выше 6, RSIUpper выше 80, EMASlow выше 120);
// все обрезки сняты, обоснования сохранены в _comment сеток как предупреждения. Сторожевой тест
// TestBANEPGridsStayWide переписан наоборот: он запрещает УРЕЗАТЬ ось, а не расширять её.
//
// ЧТО ИЗМЕНИЛО РАСШИРЕНИЕ. Ровно одну ось — риск. На узких сетках стоп выбирался 1.0/1.3/1.0/1.3 и
// в точку шёл 1.0; на широких три фолда из четырёх выбрали САМЫЙ ШИРОКИЙ край 1.5. Обрезка
// скрывала направление отбора, а не защищала от него. Остальные восемь тем на широких осях либо
// повторили прежний ответ побайтово (trend, day_spent, trail), либо улучшились без смены
// победителя (day 1.330 -> 1.452, exit 1.105 -> 1.192), либо ухудшили разброс, уйдя на края
// (volume: множитель гулял 1.5/3.0/4.0/1.0 против 1.5/2.5/2.0/1.0 на узкой оси).
//
// СХЕМА ПРОГОНОВ КАНОНИЧЕСКАЯ: -months 36 -train-months 12 -test-months 6 -min-trades 20
// -metric profit_factor, четыре фолда встык. Расчётное окно — 2023-08-28 … 2026-08-28 (34 069
// получасовых баров, из них 24 039 будних; дневная серия 1129 свечей, в окне 764 будних). Числа
// BANEP сравнимы с каталогом напрямую, в отличие от IVAT (25/9/4), DIAS (30/10/5) и YDEX (25/9/4).
//
// ЗАПАС ИСТОРИИ ПО ПОЛУЧАСОВОЙ СЕРИИ НУЛЕВОЙ: первый бар кэша совпадает с левой границей
// расчётного окна. -refresh во время калибровки НЕ запускать — он сдвинет обе границы. Дневная
// серия имеет запас 12 месяцев, его хватает на прогрев ATR(14).
//
// АПРИОР, записанный ДО прогонов. Скринер (pullback_screen_Minutes30_20260804_232456.md, строка 15
// из 99 прошедших вселенную): оборот 201 млн ₽, дневной ATR 2.97%, TradesMed 34, PFmed 1.51,
// Capped 0/24, SilentCfg 0/24, плато 67%, PFmed HO 0.65 на 15 сделках. Контрольный прогон дефолтов
// ядра на расчётных 36 месяцах: 134 сделки, PF 1.336, net +20 387 ₽ — середина ряда baseline
// каталога (YDEX 1.778, LSNGP 1.554, ELFV 1.546, IVAT 1.432, LENT 1.417, SVAV 1.368, BANEP 1.336,
// BSPB 1.114, SIBN 1.027, NVTK 0.984). Веса априору не придаётся: вопрос «предсказывают ли колонки
// скринера исход протокола» каталог закрыл пять раз подряд (SIBN, ELFV, DIAS, BSPB, YDEX) — не
// предсказывают ни снизу, ни сверху.
//
// ПРОЦЕДУРА ТЕМ КАНОНИЧЕСКАЯ. Дефолты ядра стоят ВНУТРИ рабочей зоны, поэтому все десять тем идут
// поверх них, якоря нет, и вердикт сравним с каталогом по построению.
//
// ЧТО ЗНАЕМ ОБ ИНСТРУМЕНТЕ ДО ПРОГОНОВ (замеры на расчётном окне):
//
//   - Режим ТЯЖЕЛО МЕДВЕЖИЙ: растёт ОДНО полугодие из шести, и оно первое (+48.3%); дальше −28.6%,
//     −8.2%, −25.5%, −11.6%, −15.9%. Итог окна −46.4%, максимальная просадка −69.6%, активная на
//     правой границе окна. Читается в обе стороны: лонговый edge получен ПРОТИВ режима, но весь
//     положительный net может принадлежать первому полугодию — разбивка точки по полугодиям
//     обязательна.
//   - ИЗДЕРЖКИ — УЗКОЕ МЕСТО. Шаг цены 0.5 ₽ при медианной цене 1148 ₽ = 0.0436%, реальный круг
//     0.187% против моделируемых 0.1%. Baseline: PF 1.336 -> 1.087 (круг 0.2%) -> 0.877 (0.3%),
//     то есть при реальном круге бумага почти безубыточна. Широкий стоп резко устойчивее: при
//     круге 0.2% стоп 0.5 даёт 1.087, 0.7 — 1.287, 1.0 — 1.369.
//   - ДИВИДЕНДНАЯ ОТСЕЧКА — ВЕДУЩИЙ РИСК: середина июля каждый год, гэп −12.74% (2024-07-12),
//     −10.67% (2025-07-14), −5.28% (2026-07-13). Тяжелее полугодового цикла BSPB (худший −8.44%).
//     За 36 месяцев позиция была открыта в 176 календарных днях из 781 буднего (23%) и НИ РАЗУ не
//     совпала с отсечкой — это совпадение, а не механизм: при такой занятости ожидание попадания
//     около единицы, а одно попадание стоит около −10% капитала при fraction 1.0.
//   - Ликвидность СРЕДНЯЯ, на границе вселенной: медиана оборота 149 млн ₽/день, p10 49 млн —
//     ровно гейт скринера (50 млн). Дней короче 20 баров — 18.4% (144 из 781), уровень ELFV
//     (18.9%), поэтому тема vol_window значима.
//   - Дневной ATR(14) 2.86% медианой (p10 1.82, p90 4.36) — практически как у YDEX (2.84%). День
//     проходит своё ATR быстро: медиана размаха дня к бару 0.67 ATR.
//   - Дневной гейт несёт ВЕСЬ edge: без него 485 сделок при PF 0.973 против 134 при 1.336.
//     RSI-выход тоже: без него 126 сделок при 0.861.
//   - Edge концентрируется в пересечении «быстрый RSI x исчерпанный день»: RSI(3) при
//     SpentDayATR 1.0 даёт 129 сделок при PF 1.862 — сильнейший замер окна. Зона вдвое тоньше
//     дефолтной по выборке, и это главный риск калибровки.
//
// ПРИНЯТАЯ ТОЧКА (data/params/rsi_pullback/banep/plateau_point.json): pooled OOS PF 1.799 на
// 67 сделках, compounded +19.89%, три фолда из четырёх прибыльны (10.685 / 1.209 / 1.344 / 0.658).
// На полной истории — 96 сделок, PF 1.590, net +25 390 ₽; под удвоенными издержками 1.317, под
// утроенными 1.080. Все три пункта стоп-условия плана пройдены. Пять полугодий из шести прибыльны,
// но 91% net принадлежит третьему (2024-08-26 … 2025-02-24), а последнее убыточно (PF 0.658) —
// концентрация результата в одном отрезке истории снята лишь частично.
//
// ЧЕМ ТОЧКА ОТЛИЧАЕТСЯ ОТ ДЕФОЛТОВ ЯДРА и почему каждое поле такое:
//
//   - EMAFast 5 вместо 10 — три фолда из четырёх. Самая быстрая EMA оси.
//   - EMASlow 50 вместо 100 — единодушный сдвиг вниз: все четыре фолда выбрали 70 или меньше, даже
//     когда верх оси до 200 был доступен. Верхняя половина каталожной оси не выбрана ни разу.
//   - SpentDayATR 0.9 вместо 0.8 — три фолда в теме day и три в day_spent, самый устойчивый выбор
//     каталога BANEP.
//   - StopDailyATR 1.5 вместо 0.5 — три фолда из четырёх. ЭТО КАПКАН, И ОН ПРИНЯТ ОСОЗНАННО: стоп
//     1.5 ATR это 4.29% цены при выживаемости 11.6% (доля будних дней, чей размах достаёт уровня),
//     и на самой точке доля выходов по SL — 6.2% (6 сделок из 96) против 76.0% по RSI-выходу и
//     17.7% по цели. Стоп здесь не защита, а рамка; защиту несёт RSI-выход. Обратная сторона
//     измерена: широкий стоп вдвое устойчивее к издержкам (точка держит PF 1.317 под удвоенным
//     кругом, тогда как baseline со стопом 0.5 падает до 1.087).
//   - RSIPeriod 4, RSILower 30, RSIUpper 70, TPDailyATR 0.6 — большинства не набрала ни одна ось
//     (период 8/5/8/3, уровень 45/25/30/25, полоса выхода 70/55/55/85, цель 1.0/0.8/0.4/0.6),
//     поэтому по правилу сборки они остались на дефолтах ядра.
//   - UseVolume 0 и UseTrail 0 — обе темы отвергнуты пофолдово, несмотря на положительный точечный
//     замер объёмного гейта на полной истории (VolMult 1.5 -> PF 1.400 против 1.336).
//
// ЭКСПЛУАТАЦИЯ. Дивидендная отсечка середины июля — ведущий риск бумаги, и точка его НЕ снимает:
// стоп 1.5 ATR (4.29%) втрое уже гэпа −12.74%, а гэп проскакивает стоп по определению. За 36
// месяцев позиция точки не пересекла ни одной июльской отсечки (143 календарных дня с открытой
// позицией), но 2024-06-13 (обвал рынка, гэп −6.13%) пережила внутри позиции: худшая сделка
// −5892 ₽, то есть −5.9% капитала при fraction 1.0. Календарь отсечек для живого раннера —
// необходимость, а не профилактика.
