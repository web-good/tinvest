// Package tbank supplies the ticker and calibrated rsi_pullback Params for T (T-Bank).
//
// ВАЖНО: этот литерал — снимок ПОСЛЕДНЕГО прогона калибровки. Если следующий прогон даст другую
// выигрышную комбинацию, литерал обязан быть ЗАМЕНЁН: оставить старые числа после нового прогона
// значит торговать конфигурацией, которую свежие данные не подтверждали.
//
// Пакет называется tbank, а не t: однобуквенное имя читается как t.DefaultParams() на месте
// вызова и сталкивается с идиомой t *testing.T. Биржевой тикер остаётся "T".
//
// # Калибровка 2026-08-16 — первая полная у этого тикера
//
// До неё T торговал литералом одиночного in-sample прогона от 2026-07-31 (67 сделок, PF 1.312),
// у которого walk-forward не было ВООБЩЕ, а сетки под него никогда не прибивались тестом.
// Каталог data/params/rsi_pullback/t/ переписан в расширенную редакцию по форме gazp/ и nvtk/
// (вход 252 комбинации, тренд 35, обе ветки дневного гейта 24, риск 30), каждая ось пересажена
// на замеры самого T. Данные: 34 997 30-минутных баров, из них 25 031 будний, 757 будних
// дневок, 36.0 месяца с 2023-08-16 по 2026-08-16.
//
// # Как ходит цена (без этого литерал не читается)
//
// T — самый ликвидный инструмент каталога и единственный, у которого все четыре календарных
// года дают разный режим: 2023 −8.2%, 2024 −16.2%, 2025 +18.7%, 2026 −22.2%. Окна протокола
// разошлись так же: train почти плоский (347.8 -> 338.5, −2.7%), holdout падает на 24.5%,
// вся история −26.5%, пик-минимум −42.6%. Оборот 4961 млн ₽ медианой будних дней при среднем
// 6828 (NVTK 2475, GAZP 587, LENT 38) — риска исполнения нет вовсе.
//
// Две вещи меняют чтение любого лидерборда по этому тикеру. Первая: дневной ATR схлопнулся
// вдвое к концу окна (медианы по годам 2.64% / 3.02% / 2.57% / 1.76% цены), поэтому круг
// комиссии, стоящий 0.038 дневного ATR в среднем по истории, на последнем фолде стоит уже
// 0.057 — четвёртый фолд дороже остальных для ЛЮБОЙ конфигурации. Вторая: трендовая ось на T
// плоская до вырождения — доля баров с EMAFast > EMASlow равна 47-48% во всех тридцати пяти
// парах сетки, разброс ОДИН процентный пункт против четырёх у GAZP и NVTK. Разница в profit
// factor между парами EMA здесь — разница в выборке, а не в фильтре.
//
// # Планка не взята — седьмой тикер подряд
//
// Требование то же, что объявлялось для WUSH, LENT, LSNGP, GAZP и NVTK: pooled OOS PF >= 1.5
// при >= 20 сделках одновременно на темах entry и trend плюс устойчивость выбора ведущей оси в
// 3 фолдах из 4. Вышло: entry 0.864 на 55 сделках (RSILower 40/25/30/20 — четыре разных
// значения, ни порога, ни устойчивости), trend 1.536 на 33 (EMASlow 170/50/150/150 —
// порог взят, устойчивость 2 фолда из 4). Остальные восемь тем: risk 5.331/34, volume 3.539/22,
// exit 2.579/34, trail 1.789/35, screen 1.653/70, day_spent 1.387/58, entry_narrow 1.357/46,
// day 1.268/71. Шесть тем из десяти выше 1.5, но обязательная пара планку не взяла, и лидер
// списка засчитан быть не может: тема risk выиграла стопом 1.0-1.3 ATR, то есть ровно тем
// вытеснением убытков, против которого её собственный файл предупреждает (см. ниже).
//
// # На T сам сигнал не несёт края — и это замерено, а не выведено
//
// Прямой ход цены после нисходящего кросса RSI (медиана изменения через 26 баров ≈ 2 торговых
// дня, будние бары): RSI(4) через уровень 20 — −0.10% при доле роста 46%, через 30 — −0.10%/45%,
// через 40 — −0.12%/44%, через 50 — −0.06%/46%; та же картина у RSI(5) и RSI(6) на всех
// уровнях. Безусловного откат-эффекта на этом инструменте нет ни в одном из двенадцати
// замеренных сочетаний. Отсюда провал темы entry (0.864) — он не аномалия лидерборда, а прямое
// следствие: расширять полосу входа на тикере без края значит покупать сделки без ожидания.
// Всё, что стратегия здесь зарабатывает, делают ГЕЙТ и ВЫХОД, а не сигнал.
//
// Дневной гейт это подтверждает напрямую: с UseDayATRGate=0 принятая конфигурация даёт pooled
// PF 1.145 на 173 сделках против 3.412 на 35. Работать обязана ровно одна ветка — «день
// исчерпан»: включение ветки «день только начался» с порогом 0.3 роняет результат до 1.665 на
// 68 сделках. Порог 0.9 сохранён от прежнего литерала и подтверждён соседями (0.8 — 2.150 на 47
// сделках, 1.0 — 3.743, но со вторым фолдом 8731 на семи сделках, то есть вырожденным).
//
// # Единственное изменение против прежнего боевого литерала — трейл
//
// Принятая точка отличается от того, чем T торгует сейчас, РОВНО двумя полями: UseTrail 0 -> 1
// и TrailDailyATR 0 -> 0.5. Это изменение не ослабляет защиту ни в одной точке, и вот почему:
// DesiredStop берёт НАИБОЛЬШИЙ из активных уровней, а трейл при maxFav, равном цене входа,
// стоит ровно там же, где фиксированный стоп 0.5 ATR. Конфигурация стартует в точности как
// прежняя и подтягивается вверх только после благоприятных ЗАКРЫТИЙ. Фиксированный стоп при
// этом не становится мёртвым числом: он остаётся полом для сделок, которые ни разу не закрылись
// выше входа, — таких на полной истории 4 из 44.
//
// Замер по оси: 0.2 — 1.091, 0.3 — 1.573, 0.4 — 1.976, 0.5 — 3.412, 0.6 — 3.101 pooled. Нижняя
// половина оси — это НЕ трейл, а ужесточение стартового стопа (уровень с первого бара ближе
// фиксированных 0.5 ATR), и она проигрывает; максимум внутренний. Трейл при этом реально
// работает, а не числится: на полной истории он закрывает 8 сделок из 44 (18.2%), и суммарный
// убыток стоп-стороны падает с 14 931 (10 выходов по стопу у прежнего литерала) до 11 252
// (4 стопа + 8 трейлов). Пара стоп/цель 0.5/1.5 и полоса RSI 20/65 при этом сохранены: их
// соседи на принятой точке дают меньше (цель 1.0 — 3.200, 2.0 — 2.930; RSIUpper 60 — 3.286,
// 70 — 2.448; RSILower 15 — 1.680, 25 — 0.873).
//
// # Стоп 1.0 отвергнут, хотя его pooled вдвое выше
//
// StopDailyATR=1.0 при прочих равных даёт pooled 6.020 — лучшее число всего набора. Это капкан,
// который cal_risk.json описывает заранее: доля выходов по стопу падает с 23.3% до 9.3%, убытки
// не исчезают, а вытесняются в RSI-выход (суммарный PnL RSI-выходов падает с 18 761 до 16 316).
// Проверка годами показывает цену: 2024-й на широком стопе теряет 6338 против 1204 у принятой
// точки, а второй фолд у него вырожден (10 902 на девяти сделках). Широкий стоп на инструменте,
// который держат через ночи и выходные, обменивает частые мелкие убытки на редкие крупные —
// такой обмен нельзя принимать по метрике, которая редкие крупные ещё не увидела.
//
// # Объёмный гейт отвергнут по цене, а не по числу
//
// Единственный по-настоящему близкий конкурент принятой точки: гейт при множителе 2.0 и базе
// 10 дней даёт 3.729 на 26 сделках, фолды 9.910 / 4.788 / 1.637 / 2.106 — вырожденных нет.
// Отвергнут по трём причинам. Гейт срезает четверть сделок на тикере, где связывающее
// ограничение — счёт сделок, а не profit factor. Гейт существует, чтобы отсекать тонкую ленту,
// а на инструменте с оборотом 4961 млн ₽ её не бывает: «оживление объёма» здесь означает уже
// случившееся новостное движение. И соседние настройки того же гейта вырождаются мгновенно
// (множитель 2.5 — pooled 10.316 при втором фолде 7201 на четырёх сделках), то есть плато под
// ним нет. Без трейла тот же гейт даёт 2.856 с вырожденным четвёртым фолдом — то есть работает
// здесь трейл, а не он.
//
// # Замеры принятой конфигурации
//
// Точечный walk-forward (data/params/rsi_pullback/t/plateau_point.json): pooled PF 3.412 на 35
// сделках, фолды 2.014 / 6.113 / 3.971 / 1.385 на 11 / 9 / 8 / 7 сделках — вырожденных нет.
// Четвёртый фолд ниже планки, и это самый честный минус точки; он же самый дорогой по
// издержкам (ATR в 2026-м вдвое уже). Прежний литерал на том же прогоне: 2.552 на 34 сделках,
// фолды 0.836 / 3.887 / 5.258 / 7.807 — первый под единицей, четвёртый держится на семи
// сделках. In-sample за 36 месяцев: 44 сделки, PF 2.010, win rate 70.45%, чистый PnL +11.58%,
// максимальная просадка 5.23%, CAGR 3.72%, exposure 1.65% (прежний литерал на том же окне:
// 43 сделки, PF 1.500, win rate 74.42%, +7.57%, просадка 7.17%, CAGR 2.46%). По годам:
// 2023 −405 на 2 сделках, 2024 −1204 на 14, 2025 +12 335 на 20, 2026 +850 на 8 — два года из
// четырёх убыточны, и это против 2952 и 405 убытка у прежнего литерала в те же годы. Выходы
// делятся как RSI 70.5% (медиана 12 баров), TRAIL 18.2% (10), SL 9.1% (1), TP 2.3% (1);
// медиана удержания по всем сделкам 11 баров, максимум 57.
//
// ОГОВОРКА ОБ ИСПОЛНЕНИИ: движок закрывает сделку ПО УРОВНЮ стопа или трейла, даже когда бар
// прошёл его насквозь. На принятой точке 7 из 12 выходов стоп-стороны — такие проколы (low
// ниже уровня более чем на 0.1%), у прежнего литерала 7 из 10. Обе конфигурации оценены
// одинаково оптимистично, поэтому сравнение между ними честное, а вот абсолютные числа
// завышены у обеих.
//
// ГРАНИЦА ПРИЁМА: перечисленные числа принятой точки НЕ являются out-of-sample. Конфигурацию
// собрал человек, видевший всю историю, включая тестовые окна, поэтому сравнивать 3.412 с
// планкой 1.5 нельзя, и штатный протокол §8 этот тикер НЕ подтверждает — его вердикт записан
// выше: обязательная пара тем планку не взяла, тема entry ушла под единицу.
//
// Особенность T против остальных пакетов каталога: этот тикер УЖЕ в RSI_PULLBACK_TICKERS и
// торгует живыми деньгами с 2026-08-05 — не по итогам протокола, а решением владельца поверх
// одиночного in-sample прогона. Поэтому вопрос здесь стоит не «заводить ли», а «чем торговать
// дальше», и принятая точка отвечает на него единственным изменением, которое может закрыть
// позицию только РАНЬШЕ, никогда не позже. Если менять литерал не хочется, честная
// альтернатива — не откат к прежнему, а вывод тикера из вселенной: слепые темы за него не
// говорят.
//
// Файлы сеток и полный разбор каждой темы — data/params/rsi_pullback/t/, отчёты лежат локально
// (каталог reports/ в .gitignore).
package tbank

import "tinvest/internal/service/trading_strategy/rsi_pullback/strategy/core"

// Ticker is the instrument this package configures.
const Ticker = "T"

// DefaultParams returns T's calibrated rsi_pullback parameters — the point pinned by
// data/params/rsi_pullback/t/plateau_point.json. Not a copy of core.DefaultParams() and not
// tracking it: a change to the baseline must not reach this ticker silently.
func DefaultParams() core.Params {
	return core.Params{
		RSIPeriod:       5,
		RSILower:        20,
		RSIUpper:        65,
		EMAFast:         20,
		EMASlow:         100,
		DailyATRPeriod:  14,
		UseDayATRGate:   1,
		FreshDayATR:     0,
		SpentDayATR:     0.9,
		StopDailyATR:    0.5,
		TPDailyATR:      1.5,
		UseVolume:       0,
		VolBaseDays:     5,
		VolLookbackBars: 3,
		VolMult:         1.2,
		UseRSIExit:      1,
		UseTrail:        1,
		TrailDailyATR:   0.5,
	}
}
