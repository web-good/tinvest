// будних, 36.0 месяца с 2023-08-21):
//
//   - ИСТОРИИ РОВНО 36.0 МЕСЯЦА, поэтому штатный протокол §8 docs/rsi_pullback/strategy.md
//     (-months 36 -train-months 12 -test-months 6) исполним встык, и числа SVAV сопоставимы
//     построчно с остальным каталогом — в отличие от ivat (26 мес) и domrf (8.8 мес). Запаса
//     сверх 36 месяцев нет ни одного дня.
//   - ТРЕНДОВЫЙ ДОПУСК НЕ ЗАВИСИТ ОТ ПАРЫ: доля баров с EMAFast > EMASlow укладывается в
//     42.4-43.6% на всех 35 парах сетки, размах 1.2 процентного пункта. У IVAT тот же замер
//     даёт 29.4-36.0% с монотонной зависимостью от EMASlow, у LSNGP — 54-60%. Практическое
//     следствие: на SVAV выбор пары меняет не объём допуска, а то, какие именно бары в него
//     попадают, поэтому дефицит выборки из-за медленной пары здесь невозможен, а разница PF
//     между парами — это качество фильтра, а не размер выборки.
//   - ВОЛАТИЛЬНОСТЬ ВЫСОКАЯ: дневной ATR(14) медианой 4.38% цены (p10 2.73, p90 6.93) — второй
//     в каталоге после FESH (4.42). Круг издержек 0.1% оборота стоит 0.023 ATR, то есть на
//     стопе 0.3 ATR комиссия съедает 7.6% риска (черта, по которой строку 0.3 вырезали из
//     domrf/, — 17%). Стоп 0.5 ATR это 2.2% цены: при Fraction=1 одна сделка двигает счёт
//     заметно сильнее, чем на LSNGP с его ATR 2.64%.
//   - РЕЖИМ: падают ОБА окна протокола (train −38.5%, holdout −33.2%), вся история −58.9%,
//     пик-минимум −83.4%, и из шести полугодий растущее одно (+0.8%). Завысить лонговый
//     результат режимом здесь нечем, но и на растущем рынке конфигурация не проверена ни разу.
//   - ЛИКВИДНОСТЬ: оборот медианой 68 млн ₽/день при p10 = 18 млн — лучше IVAT (43), LENT (38)
//     и LSNGP (41): больше половины дней проходят гейт отбора скринера в 50 млн самостоятельно.
//   - Контрольный прогон baseline на 36 месяцах: 146 сделок, PF 1.368 — инструмент торгует,
//     дефицита сделок уровня «стратегия молчит» здесь нет.
//
// РЕЗУЛЬТАТ ДЕВЯТИ ТЕМ КАЛИБРОВКИ (pooled OOS PF / сделок, walk-forward 36/12/6):
//
//	screen 1.810/120, entry 2.139/47, trend 2.343/104, day 3.206/56, day_spent 2.738/93,
//	volume 1.902/74, risk 1.730/105, exit 2.742/128, trail 1.629/102
//
// ВСЕ ДЕВЯТЬ ВЫШЕ 1.5 — второй такой случай в каталоге после LSNGP (там все девять тоже были
// выше 1.5, но ведущая ось держалась лишь 2 из 4).
//
// ВЕРДИКТ ПО ПЛАНКЕ, пункт за пунктом (планка объявлена ДО прогонов: темы entry и trend обе
// дают pooled OOS PF ≥ 1.5 при ≥ 20 сделках, ведущая ось выбрана одинаково в ≥ 3 фолдах из 4;
// вырожденный фолд, то есть фолд без единой убыточной сделки, не засчитывается; условие
// «≥5 сделок в каждом фолде» из плана IVAT здесь СНЯТО сознательно — оно было костылём под
// 25-месячную схему IVAT):
//
//   - entry — ВЗЯТА: pooled OOS PF 2.139 на 47 сделках (compounded 29.07%), фолды
//     4.659 / 6.771 / 0.568 / 1.409 при 22 / 10 / 4 / 11 сделках. Ведущая ось RSILower выбрана
//     25 / 20 / 20 / 20 — устойчивость 3 из 4. Вырожденных фолдов нет. ОГОВОРКА, которую эта
//     дока обязана нести честно: фолд 3 — in-sample PF 7.893 против OOS PF 0.568 на тонкой
//     выборке в 4 сделки (разрыв ×13.9) — явный признак переобучения темы; фолд 4 на грани
//     (in-sample 3.799 / OOS 1.409, ×2.70). Планку это не рушит только потому, что условие
//     «≥5 сделок в фолде» план снял сознательно; 2.139 нельзя читать как ровный результат.
//   - trend — ВЗЯТА: pooled OOS PF 2.343 на 104 сделках (compounded 78.12%), фолды
//     2.369 / 2.666 / 2.751 / 1.930 при 33 / 31 / 21 / 19. Ведущая ось EMASlow выбрана
//     170 / 100 / 100 / 100 — устойчивость 3 из 4. Ни один фолд не разошёлся втрое,
//     вырожденных нет. EMAFast (10/40/5/5) не сошёлся ни в одной паре фолдов — согласуется с
//     замером плоского трендового допуска выше.
//   - ИТОГ: планка ВЗЯТА целиком, впервые в каталоге (у девяти предыдущих тикеров — GAZP,
//     NVTK, UGLD, FESH, WUSH, LENT, RENI, LSNGP, IVAT — она не бралась ни разу).
//
// ЧТО ЕЩЁ ОБЯЗАНЫ НЕСТИ ДОКИ:
//
//   - exit — единственная тема каталога svav/ с устойчивостью ведущей оси 4 из 4 (RSIUpper=55
//     во всех четырёх фолдах).
//   - volume — устойчивости 3 из 4 нет вовсе (VolMult/VolBaseDays по фолдам 1.0/14, 1.5/14,
//     1.5/10, 2.5/3), и фолд 4 вырожден; расширенный край оси 2.5, добавленный по замеру (порог
//     2.0 пропускает ещё 27.3% баров), победил только в этом вырожденном фолде.
//   - risk — ось стопа поймана в капкан вытеснения убытка в RSI-выход: счёт сделок не меняется
//     на всей оси стопа (обычные прогоны, база 4/25/55+spent0.8+vol1.5/14: 0.3 ATR -> 91 сделка
//     PF 1.959; 0.5 -> 90 PF 2.577; 0.7 -> 90 PF 3.624; 1.0 -> 90 PF 6.700; 1.3 -> 90 PF 6.159),
//     поэтому литерал берёт узкий стоп 0.5, а не «лучший PF».
//   - Полоса RSIUpper=55 делает стратегию преимущественно ВНУТРИДНЕВНОЙ, а не многодневной:
//     на принятой точке выходы RSI 91.7% / SL 6.2% / TP 2.1%; медиана удержания 5 баров при
//     торговом дне 16-17 баров; многодневных сделок 14.6% — цель практически инертна.
//
// ПРИНЯТАЯ ТОЧКА: pooled OOS PF 3.457 на 103 сделках (фактический прогон через
// data/params/rsi_pullback/svav/plateau_point.json, 2026-08-21), win rate 85.44%, compounded
// 67.78%, фолды 3.175(31)/4.512(29)/4.171(24)/2.675(19) — убыточных и вырожденных нет. ГРАНИЦА
// ПРИЁМА: для фиксированной точки это НЕ out-of-sample — её собрал человек, видевший всю
// историю (в том числе точечные прогоны сверх сеток тем), поэтому сравнивать 3.457 с планкой
// 1.5 нельзя как проверку протокола; вердикт протокола дают тематические файлы выше (entry и
// trend уже отдельно взяли планку).
//
// РАЗБОР ПОЛЕЙ ЛИТЕРАЛА (от core.DefaultParams() литерал отличается РОВНО ДВУМЯ полями:
// RSIUpper 70->55 и UseVolume 0->1; остальные шестнадцать совпадают с baseline):
//
//   - RSIUpper 55 — выбор темы exit, устойчивость 4 из 4 фолдов. Полоса 55 поднимает всю
//     решётку входа целиком (обычные прогоны на всей истории, не walk-forward): при RSIUpper=55
//     4/20 -> 83 сделки PF 2.358; 4/25 -> 125 PF 2.238; 4/30 -> 175 PF 1.798; те же точки при
//     RSIUpper=70: 4/20 -> 77 PF 1.701; 4/25 -> 110 PF 1.318; 4/30 -> 146 PF 1.368 (baseline).
//   - RSILower 30 — РАСХОДИТСЯ с прямым выбором темы entry (20, устойчивость 3/4): под
//     включённым объёмным гейтом выбор темы не выживает (walk-forward кандидата 5/20/55 даёт
//     фолды без единой убыточной сделки — по правилу плана такие фолды не засчитываются).
//     Точечная проверка соседей вокруг базы 4/25/55+spent0.8+vol1.5/14+stop0.5 даёт:
//     RSILower 20 -> 2.456/46; RSIPeriod 5 -> 2.595/46; RSIUpper 60 -> 1.976/63; RSILower 30 ->
//     3.229/95, фолды 2.915/4.391/3.803/2.502, compounded 59.55% — лучше по всем показателям
//     сразу (сделок больше, PF выше, слабого фолда нет), поэтому центр точки перенесён на 30.
//   - EMAFast 10, EMASlow 100 — плато, а не пик: обычные прогоны на базе 4/25/55/stop 0.7 дают
//     EMAFast 5 -> 83 сделки PF 3.952; 10 -> 90 PF 3.624; 20 -> 94 PF 3.711; 30 -> 101 PF 3.120;
//     40 -> 103 PF 3.190 — ось плоская (3.12-3.95), что совпадает с замером допуска выше
//     (доля баров EMAFast > EMASlow держится 42.4-43.6% на всех 35 парах).
//   - UseDayATRGate 1, FreshDayATR 0, SpentDayATR 0.8 — ветка «день только начался» держится на
//     нуле: тема day сама выбрала его в 3 фолдах из 4, а точечная проверка на полной истории
//     показывает обвал качества при включении: на комбо фолда 1 темы day (SpentDayATR=1.25)
//     включение FreshDayATR=0.3 роняет PF 2.087 -> 1.538 при росте сделок 55 -> 116. SpentDayATR
//     остаётся на дефолте 0.8: у темы day_spent устойчивости 3 из 4 нет вовсе (по фолдам
//     0.6/1/1/1.25, мода около 1.0), и неустойчивый выбор в литерал сознательно не перенесён.
//   - StopDailyATR 0.5 — против «лучшего PF» на изолированной оси (см. таблицу выше в разделе
//     risk): счёт сделок не меняется на всей оси стопа, то есть стоп перестаёт связывать —
//     капкан вытеснения убытка в RSI-выход, разобранный на WUSH, LENT, LSNGP и IVAT. Опорный
//     замер выживаемости SVAV (доля дней, чей размах не достаёт до уровня): 0.3 ATR — 97.4%,
//     0.5 — 81.8%, 0.7 — 60.2%, 1.0 — 37.0%, 1.3 — 19.7%.
//   - TPDailyATR 0.6 — выбор темы risk; на принятой точке цель ШИРЕ стопа (0.6 против 0.5) —
//     асимметрия, обратная WUSH, LENT и LSNGP, где цель уже стопа. Инертной цель не становится:
//     доля TP-выходов принятой точки 2.1% ненулевая (в отличие, например, от пары
//     Stop=1.3/TP=2.5 темы risk, где цель не сработала ни разу из 137 сделок).
//   - UseVolume 1, VolBaseDays 14, VolLookbackBars 3, VolMult 1.2 — объёмный гейт ВКЛЮЧЁН, в
//     отличие от IVAT. Тема volume мерила ось при RSIUpper=70 и давала pooled OOS PF 1.902/74 с
//     выбором VolMult=1.5; на принятой полосе RSIUpper=55 ось имеет внутренний максимум, не
//     совпадающий с выбором темы (walk-forward, pooled/сделок): гейт выключен -> 2.755/129;
//     VolMult 1.0 -> 2.896/109; 1.2 -> 3.454/103; 1.5 -> 3.229/95; 2.0 -> 2.867/81 — гейт
//     работает как отбор качества, а не как «чем меньше сделок, тем лучше», поэтому взят
//     внутренний пик 1.2, а не край 1.5 из темы.
//   - UseRSIExit 1 — обязателен для всех тикеров реестра живого раннера; на принятой точке
//     закрывает 91.7% сделок (SL — 6.2%, TP — 2.1%), плата за полосу RSIUpper=55.
//   - UseTrail 0, TrailDailyATR 0 — тема trail не дала устойчивого ответа (TrailDailyATR по
//     фолдам 0.5/0/0.7/0, выключенный трейл победил лишь в 2 фолдах из 4), а единственный фолд,
//     где трейл включился первым (0.5), оказался ЕДИНСТВЕННЫМ убыточным фолдом темы (OOS PF
//     0.817, просадка 8.88% — худшая из четырёх).
//
// ЧЕГО ЖДАТЬ В ЖИВОЙ ТОРГОВЛЕ: примерно 2.9 сделки в месяц (103 за 36 месяцев), win rate около
// 85%, медиана удержания около 5 баров (порядка 2.5 часа, стратегия в основном внутридневная
// несмотря на многодневную конструкцию), выходы RSI ~92% / стоп ~6% / цель ~2%, все четыре
// фолда положительны без вырожденных. Проверка «результат не держится одной неделей» (прогон
// -params на OOS-окне 24 мес, 96 сделок, net 53 282 ₽): лучшая неделя 9.2% итога (2025-W42),
// лучший месяц 18.0% (2025-02), топ-1 сделка 13.9% итога, топ-5 сделок 30.6%, результат
// размазан по 46 неделям и 22 месяцам (убыточных месяцев 3 из 22), по полугодиям
// 11.2 / 29.7 / 28.9 / 13.7 / 16.5% — это ПРОТИВОПОЛОЖНОСТЬ случаю IVAT, где 85% результата
// делает одна неделя июля 2026.
//
// Сетки калибровки лежат в data/params/rsi_pullback/svav/, их оси прибиты
// internal/service/backtest/rsi_pullback_svav_grid_test.go.
