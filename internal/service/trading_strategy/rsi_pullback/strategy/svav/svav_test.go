// Литерал прибит снимком 2026-08-21: SVAV — первый тикер каталога, взявший обе половины
// объявленной заранее планки (entry pooled OOS PF 2.139/47 сделок, trend pooled OOS PF
// 2.343/104 сделок, обе оси устойчивости 3 из 4). От core.DefaultParams() литерал отличается
// РОВНО ДВУМЯ полями: RSIUpper 70->55 и UseVolume 0->1. Два поля собраны ПРОТИВ прямого выбора
// соответствующих тем: RSILower=30 расходится с темой entry (20, устойчивость 3/4) — под
// включённым объёмным гейтом выбор темы разваливается на шум (walk-forward кандидата 5/20/55
// даёт фолды без единой убыточной сделки), а точка 30 выигрывает у соседей по всем метрикам
// сразу (pooled 3.229/95, фолды 2.915/4.391/3.803/2.502, compounded 59.55%, слабого фолда нет);
// VolMult=1.2 расходится с темой volume (1.5) — та мерила ось при RSIUpper=70, а на принятой
// полосе 55 ось имеет ВНУТРЕННИЙ максимум (walk-forward, pooled/сделок): гейт выключен ->
// 2.755/129; 1.0 -> 2.896/109; 1.2 -> 3.454/103; 1.5 -> 3.229/95; 2.0 -> 2.867/81. Замер
// принятой точки (walk-forward 36/12/6, фактический прогон через
// data/params/rsi_pullback/svav/plateau_point.json): pooled OOS PF 3.457 на 103 сделках,
// win rate 85.44%, compounded 67.78%, фолды 3.175(31)/4.512(29)/4.171(24)/2.675(19) —
// убыточных и вырожденных нет. ГРАНИЦА ПРИЁМА: для фиксированной точки это НЕ out-of-sample —
// точку собрал человек, видевший всю историю, поэтому сравнивать 3.457 с планкой 1.5 нельзя как
// проверку протокола; вердикт протокола дают тематические файлы (entry и trend уже отдельно
// прошли планку). Разбор каждого поля — в доке пакета (svav.go).
func TestCalibratedLiteralIsPinned(t *testing.T) {
	want := core.Params{
		RSIPeriod:       4,
		RSILower:        30,
		RSIUpper:        55,
		EMAFast:         10,
		EMASlow:         100,
		DailyATRPeriod:  14,
		UseDayATRGate:   1,
		FreshDayATR:     0,
		SpentDayATR:     0.8,
		StopDailyATR:    0.5,
		TPDailyATR:      0.6,
		UseVolume:       1,
		VolBaseDays:     14,
		VolLookbackBars: 3,
		VolMult:         1.2,
		UseRSIExit:      1,
		UseTrail:        0,
		TrailDailyATR:   0,
	}
	if got := DefaultParams(); got != want {
		t.Fatalf("откалиброванный литерал SVAV изменился:\n got: %+v\nwant: %+v", got, want)
	}
}

