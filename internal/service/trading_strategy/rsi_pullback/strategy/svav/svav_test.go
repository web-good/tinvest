// Стоп — единственное, что ограничивает убыток: RSI-выход закрывает и в плюс, и в минус. Ширина
// 0.5 — НЕ точка максимального PF на изолированной оси: обычные прогоны на базе 4/25/55 +
// spent 0.8 + vol 1.5/14 дают 0.3 -> 91 сделка PF 1.959; 0.5 -> 90 PF 2.577; 0.7 -> 90 PF 3.624;
// 1.0 -> 90 PF 6.700; 1.3 -> 90 PF 6.159 — счёт сделок не меняется вовсе на всей оси, то есть
// стоп перестаёт связывать: это капкан вытеснения убытка в RSI-выход, разобранный на WUSH,
// LENT, LSNGP и IVAT. Узкий край 0.5 взят сознательно, а не «лучший PF». Опорный замер
// выживаемости SVAV (доля дней, чей размах не достаёт до уровня): 0.3 ATR — 97.4%, 0.5 — 81.8%,
// 0.7 — 60.2%, 1.0 — 37.0%, 1.3 — 19.7%.
func TestStopIsArmed(t *testing.T) {
	if p := DefaultParams(); p.StopDailyATR <= 0 {
		t.Fatalf("StopDailyATR = %v, want > 0", p.StopDailyATR)
	}
}

// RSI-выход закрывает подавляющее большинство сделок принятой точки: 91.7% (SL — 6.2%,
// TP — 2.1%), плата за нижнюю полосу RSIUpper=55, выбранную темой exit с устойчивостью 4 из 4
// фолдов — единственная тема каталога svav/ с такой полной устойчивостью. Живой раннер держит
// RSI-выход обязательным для всех тикеров реестра независимо от того, что показала бы его
// отключённая ветка на конкретном тикере.
func TestRSIExitIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseRSIExit != 1 {
		t.Fatalf("UseRSIExit = %d, want 1 — RSI-выход закрывает 91.7%% сделок принятой точки", p.UseRSIExit)
	}
	if p.RSIUpper <= p.RSILower {
		t.Fatalf("полоса RSI вырождена: RSIUpper = %v, RSILower = %v", p.RSIUpper, p.RSILower)
	}
}

// Дневной гейт взведён на единственной ветке «день исчерпан»: ветка «день только начался»
// (FreshDayATR) держится на нуле, потому что тема day сама выбрала 0 в 3 фолдах из 4, а
// точечная проверка на полной истории показывает обвал качества при её включении:
// FreshDayATR=0/SpentDayATR=0.8 -> 146 сделок PF 1.368, а FreshDayATR=0.3/SpentDayATR=0.8 ->
// 205 сделок PF 1.371 (почти нейтрально), но на комбо фолда 1 темы day включение ветки роняет
// PF 2.087 -> 1.538 при удвоении сделок (55 -> 116) — количество куплено ценой качества.
// SpentDayATR остаётся на дефолте 0.8: у темы day_spent устойчивости 3 из 4 нет вовсе (по
// фолдам 0.6/1/1/1.25, мода около 1.0), и Task 10 сознательно не стал переносить неустойчивый
// выбор в литерал.
func TestOnlySpentDayBranchIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseDayATRGate != 1 {
		t.Fatalf("UseDayATRGate = %d, want 1", p.UseDayATRGate)
	}
	if p.FreshDayATR != 0 {
		t.Fatalf("FreshDayATR = %v, want 0 — ветка «день только начался» на SVAV вредна (2.087->1.538 PF при включении)", p.FreshDayATR)
	}
	if p.SpentDayATR <= 0 {
		t.Fatalf("SpentDayATR = %v, want > 0 — иначе гейт взведён и не отсекает ничего", p.SpentDayATR)
	}
}

// Объёмный гейт ВКЛЮЧЁН — в отличие от IVAT, где он остался выключенным. На теме volume
// (измеренной при RSIUpper=70) он давал pooled OOS PF 1.902/74, а на принятой полосе
// RSIUpper=55 ось VolMult имеет внутренний максимум, не совпадающий с выбором темы: гейт
// выключен -> 2.755/129; VolMult 1.0 -> 2.896/109; 1.2 -> 3.454/103; 1.5 -> 3.229/95;
// 2.0 -> 2.867/81 (walk-forward, pooled/сделок). Гейт работает как отбор качества, а не как
// «чем меньше сделок, тем лучше», поэтому взят внутренний пик 1.2, а не край 1.5 из темы.
func TestVolumeGateIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseVolume != 1 {
		t.Fatalf("UseVolume = %d, want 1 — на полосе RSIUpper=55 гейт двигает pooled OOS PF с 2.755/129 до 3.454/103 на VolMult=1.2", p.UseVolume)
	}
	if p.VolMult <= 0 || p.VolBaseDays <= 0 || p.VolLookbackBars <= 0 {
		t.Fatalf("объёмный гейт взведён (UseVolume=1), но его оси невзведены: VolMult=%v VolBaseDays=%d VolLookbackBars=%d",
			p.VolMult, p.VolBaseDays, p.VolLookbackBars)
	}
}

