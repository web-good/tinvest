// Package wush supplies the ticker and calibrated rsi_pullback Params for WUSH (Whoosh).
//
// Пакет заведён 2026-08-13 ДО калибровки — как место, куда ляжет литерал, и как носитель
// замеров инструмента. Спека: docs/superpowers/specs/2026-08-13-wush-rsi-pullback-prep-design.md,
// сетки: data/params/rsi_pullback/wush/. Литерал поставлен 2026-08-14 решением владельца, уже
// ПОСЛЕ того, как тикер не взял объявленную планку (см. ниже) — связь с baseline разорвана,
// снимок литерала держит wush_test.go.
//
// Что известно об инструменте (замеры по кэшу WUSH_Minutes30.json и WUSH_Day1.json,
// правилами ядра: будние дни MSK как weekdayDaily, сглаживание Уайлдера как в pkg/indicators):
//
//   - Истории достаточно: 33 823 30-минутных бара (23 901 будний) за 36.0 месяца с 2023-08-04.
//     Штатный протокол walk-forward §8 docs/rsi_pullback/strategy.md исполним целиком — как у
//     reni и fesh и в отличие от domrf.
//   - ПАДАЮТ ОБА ОКНА ПРОТОКОЛА, и это главное отличие WUSH от предшественников: обучающее окно
//     2023-08-04—2026-02-03 — падение 226.50 → 92.99 (−58.9%), holdout 2026-02-04—2026-08-03 —
//     падение 93.41 → 48.61 (−48.0%). Пик 337.48 (2024-03-25) → минимум 30.30 (2026-07-17), то
//     есть −91.0%; пять полугодий из семи отрицательные. У fesh holdout РОС на 13.1% и завышал
//     long-only механически, поэтому подтверждением служить не мог; здесь завысить результат
//     нечем — это самая честная проверка, какую ставил репозиторий. Обратная сторона: трендовый
//     фильтр в таком режиме держит EMAFast > EMASlow лишь 41–43% времени, вход закрыт большую
//     часть истории, и СЧЁТ СДЕЛОК надо читать раньше profit factor — красивый PF на шести
//     сделках здесь самый вероятный способ обмануться.
//   - Дневной ATR(14) идёт медианой 4.25% цены (среднее 4.52% — колонка скринера печатает
//     именно среднее, распределение скошено вправо хвостом до 13.41%). По ширине рядом с fesh
//     (4.42%) и ugld (4.28%), заметно выше reni (3.36%) и domrf (1.94%). Поэтому сетки в
//     data/params/rsi_pullback/wush/ пересчитаны от fesh/, а сужения domrf в них намеренно НЕ
//     перенесены.
//   - Круг издержек 0.024 дневного ATR; он лицензирует узкую строку стопа 0.3 ATR. Но тот же
//     стоп переживает целиком лишь 2.4% дней, то есть сидит внутри обычного внутридневного шума.
//   - День раскрывается БЫСТРЕЕ, чем у fesh: медиана доли ATR ко второму бару 0.33 против 0.28.
//     Отсюда единственное расхождение сеток с fesh/ — ось FreshDayATR [0, 0.3, 0.4] вместо
//     [0, 0.25, 0.35].
//   - Оборот 356 млн ₽/день при лоте 1 — вторая ликвидность из заведённых после domrf и
//     единственный тикер с лотом 1, то есть самая тонкая гранулярность позиции. На размер
//     позиции не давит.
//   - Слабое место, заявленное до прогонов: в отчёте скринера у WUSH Plateau 58% и Capped 4/24
//     против 83% и 2/24 у fesh. Рабочая зона узкая, и это прямо повышает шанс, что калибровка
//     сядет на случайный пик. Планка объявлена в спеке ДО первого прогона именно поэтому.
//
// # Результат прогонов 2026-08-14: планка НЕ взята
//
// Девять тем прогнаны rolling walk-forward (train 12 мес / OOS 6 мес встык, 4 фолда, ранжирование
// по profit_factor) на освежённом кэше — 34 068 баров, пул 2023-08-14—2026-08-14. Pooled OOS PF и
// счёт сделок по темам: screen 1.458/82, entry 2.000/59, trend 1.317/83, exit 1.502/106,
// day 1.348/80, day_spent 1.090/101, volume 1.442/63, risk 1.911/95, trail 1.272/98.
//
// Планка требовала pooled OOS PF ≥ 1.5 при ≥ 20 сделках ОДНОВРЕМЕННО на entry и trend плюс
// устойчивость ведущей оси в 3 фолдах из 4. Устойчивость есть на обеих темах — RSILower выбран
// 20/20/20/25, EMASlow 50/100/50/50, — и по этому критерию WUSH заметно лучше fesh, у которого
// оси гуляли 15/25/10/15 и 100/50/150/100. Но trend даёт pooled OOS PF 1.317 при пороге 1.5, то
// есть первое условие выполнено только на одной теме из двух. Планка составная — НЕ ВЗЯТА; всё,
// что стоит ниже в этом комментарии, живёт под этим фактом.
//
// Тему risk с её pooled PF 1.911 засчитывать нельзя: фолд 1 дал OOS PF 11.439, а в фолде 2
// in-sample PF 17.296 схлопнулся до OOS 1.107 — широкий стоп 1.3 ATR почти не оставляет убыточных
// сделок внутри обучающего окна. Ровно ради таких случаев вердикт и был заранее привязан к двум
// названным темам, а не к лучшей из девяти.
//
// Ось TPDailyATR на этом инструменте, в отличие от fesh, ЖИВАЯ: на baseline-прогоне за 36 месяцев
// (139 сделок, PF 1.502) цель дала 19 выходов из 139 — 13.7% против 2 из 60 у fesh, — RSI-выход
// 85 (61.2%), стоп 35 (25.2%), медиана удержания 9 баров. Подтверждает это и тема risk, где выбор
// осел на самой узкой строке TPDailyATR=0.5 в трёх фолдах из четырёх.
//
// Восемь тем из девяти дали pooled OOS PF выше 1.0 на пулах 59–106 сделок, то есть инструмент не
// пустой — он не дотянул до объявленного порога. Разбор: reports/WUSH_calib/VERDICT.md (каталог
// reports/ в .gitignore, поэтому числа продублированы здесь).
//
// # Вторая попытка взять планку 2026-08-14: тоже не взята
//
// Прогон выше выбирал RSILower из оси [10, 15, 20, 25] и упирался в её ВЕРХНИЙ край в трёх
// фолдах из четырёх (20, 20, 20, 25). Это выглядело как обрезанная ось — признак того, что
// оптимум лежит за границей, — и ось расширили до [10 … 50] (обоснование потолка и замеры
// кроссов: data/params/rsi_pullback/wush/cal_entry.json). Догадка ОПРОВЕРГНУТА замером:
// на девяти уровнях калибратор выбрал 40, 20, 20, 25, то есть три фолда из четырёх остались в
// прежней глубокой зоне, а pooled OOS PF УПАЛ с 2.000 (59 сделок) до 1.674 (88). Упор в край
// был артефактом оси из четырёх значений; пофолдовый отбор на train-окне действительно
// предпочитает глубокие пороги.
//
// Отдельно стоит записать ошибку в постановке этой второй попытки, чтобы её не повторяли:
// планку заваливает тема trend, а она RSILower не свипует вовсе и держит его на baseline при
// любой ширине оси в cal_entry.json. Расширение этой оси не могло починить trend в принципе.
// Повторный прогон trend дал 1.377 против 1.317 — вся разница объясняется семью новыми барами
// в кэше.
//
// Что действительно двигает результат — КОНТЕКСТ несвипуемых осей: калибратор берёт их из
// DefaultParams() этого пакета, поэтому числа тем зависят от того, что лежало в литерале на
// момент запуска. В контексте принятого литерала (ниже) обе темы берут порог: entry 1.930 на 93
// сделках, trend 1.914 на 143. Засчитывать это НЕЛЬЗЯ — контекст выбран рукой уже после
// просмотра результатов, это ровно та циклическая логика, от которой планка и защищает, — но
// сравнивая числа тем между прогонами, всегда проверять, каким был литерал.
//
// # Литерал, принятый 2026-08-14 решением владельца
//
// Владелец подобрал конфигурацию вручную и распорядился зафиксировать её несмотря на
// непройденную планку — то же решение, что раньше принималось по domrf и fesh, и с той же
// природой: это принятый риск, а не подтверждение тикера.
//
// Замеры конфигурации. За 36 месяцев in-sample: 219 сделок, PF 2.157, win rate 75.80%,
// просадка 14.85%, чистый PnL 208.43% при fraction=1. Rolling walk-forward сеткой из ОДНОЙ
// точки, где калибратор ничего не выбирает и результат принадлежит конфигурации, а не
// процедуре: pooled PF 2.030 на 144 сделках, фолды 1.330 / 1.997 / 2.451 / 3.018 — все четыре
// выше единицы и растут во времени, худший maxDD по фолду 16.44%. Каждый календарный год
// прибылен отдельно: PF 1.886 (20 сделок) / 1.768 (84) / 1.929 (73) / 3.078 (42). На
// holdout-полугодии 2026-02-04—2026-08-14, где бумага упала на 48%, PF 2.633 на 34 сделках.
// Плато проверено соседями по шести осям: RSILower 40 → 1.988, 50 → 1.777, RSIUpper 70 → 1.985,
// 80 → 1.617, StopDailyATR 0.5 → 1.956, 1.0 → 2.560. Разброс 1.617-2.560 без провалов — точка
// на пологом плато, а не на одиночном пике; при Plateau 58% в отчёте скринера это была главная
// опасность, и она не подтвердилась.
//
// ГРАНИЦА ПРИЁМА: для фиксированной точки это НЕ out-of-sample. Конфигурацию подобрал человек,
// видевший всю историю, включая тестовые окна, поэтому 2.030 нельзя сравнивать с планкой 1.5 и
// объявлять её взятой задним числом. Штатный протокол §8 этот тикер НЕ подтверждает: его
// вердикт — тематические прогоны выше, и они дали 1.674 по входу и 1.377 по тренду.
//
// Структура выходов НА ЭТОМ ЛИТЕРАЛЕ за 36 месяцев (219 сделок): RSI-выход 129 сделок (58.9%,
// медиана 11 баров), цель 57 (26.0%, медиана 5 баров), стоп 33 (15.1%, медиана 8 баров),
// медиана удержания по всем сделкам 9 баров. Стоп здесь РАБОЧИЙ выход, и это главное отличие
// от конфигурации со стопом 1.0, где он срабатывал 16 раз из 216 (7.4%) и давал формально
// лучший pooled PF 2.560: тот прирост берётся не из логики, а из вычищения убыточных сделок в
// RSI-выход. Дальше по оси это вырождается совсем — на 1.3 дневной размах не достаёт до стопа
// в 81.9% дней, и цена решения всплывает одним гэпом, которого в 36 месяцах может не оказаться.
// Тикер живёт в режиме, где падают ОБА окна протокола, так что проверить такую цену историей
// нечем; за это и заплачено просадкой 14.85% вместо 9.08%.
//
// Полоса RSI 45/75 широкая осознанно: медиана RSI(4) на входе 38.8, то есть порог 45 пропускает
// и неглубокие откаты, а отбор делают трендовый фильтр EMA 5/50 и дневной гейт SpentDayATR=0.8.
// Двигать один край полосы, не перемеряя второй, нельзя — она меряется целиком.
//
// # Боевая вселенная
//
// Владелец завёл WUSH в RSI_PULLBACK_TICKERS 2026-08-14, зная всё перечисленное выше: планка не
// взята дважды, числа литерала не out-of-sample, режим инструмента падающий на обоих окнах.
// Это принятый риск, зафиксированный сознательно, а не следствие того, что литерал технически
// разблокировал ввод. Пересматривать при первом же расхождении живых сделок с бэктестом
// (сверка — cmd/pullparity) и при выходе просадки за 15%, которую дала история.
