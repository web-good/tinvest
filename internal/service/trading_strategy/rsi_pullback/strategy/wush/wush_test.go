package wush

import (
	"testing"

	"tinvest/internal/service/trading_strategy/rsi_pullback/strategy/core"
)

// Литерал WUSH принят владельцем 2026-08-14 и в тот же день заведён в боевую вселенную ПОСЛЕ
// того, как тикер не взял планку, объявленную в спеке до прогонов: нужны были pooled OOS PF ≥ 1.5
// при ≥ 20 сделках одновременно на темах entry и trend, а trend дал 1.317 на 83 сделках. Планку
// пробовали взять дважды — второй раз с расширенной осью RSILower, — и оба раза не взяли; разбор
// в доке пакета. Числа ниже принадлежат конфигурации, а не процедуре отбора: каждое измерено
// сеткой из одной точки, где калибратор ничего не выбирает.
//
// Что даёт эта конфигурация. За 36 месяцев in-sample: 219 сделок, PF 2.157, win rate 75.80%,
// просадка 14.85%. Rolling walk-forward (train 12 / OOS 6, 4 фолда): pooled PF 2.030 на 144
// сделках, фолды 1.330 / 1.997 / 2.451 / 3.018 — все четыре выше единицы и растут во времени,
// худший maxDD по фолду 16.44%. Каждый календарный год прибылен отдельно (PF 1.886 / 1.768 /
// 1.929 / 3.078), на holdout-полугодии, где бумага упала на 48%, PF 2.633 на 34 сделках.
//
// ГРАНИЦА ПРИЁМА, которую нельзя терять при чтении этих чисел: для фиксированной точки это НЕ
// out-of-sample. Конфигурацию подобрал человек, видевший всю историю, включая тестовые окна,
// поэтому 2.030 нельзя ставить рядом с планкой 1.5 и объявлять её взятой задним числом — планка
// меряла принципиально другое, и вердикт по ней остаётся отрицательным.
//
// Снимок держит литерал равным ИМЕННО той конфигурации, которую мерили: параметры задаются
// литералом core.Params, поэтому забытое или «улучшенное на глаз» поле не ломает компиляцию и
// молча меняет то, чем торгует раннер. Три поля здесь особенно уязвимы, и все три прибиты
// сознательно.
//
// StopDailyATR=0.7. Ось меряли соседями по walk-forward: 0.5 → 2.030 (так же), 1.0 → 2.560. То
// есть более широкий стоп даёт формально лучший PF — и взят он всё-таки не был. Причина в том,
// откуда берётся прирост: на 0.7 стоп срабатывает 33 раза из 219 сделок (15.1%) и остаётся
// рабочим выходом, а на 1.0 — 16 раз из 216 (7.4%), и прирост PF получается вычищением убыточных
// сделок в RSI-выход, а не улучшением логики. Дальше по оси это вырождается совсем: на 1.3
// дневной размах не достаёт до стопа в 81.9% дней, и цена такого решения всплывает одним гэпом,
// которого в 36 месяцах может просто не оказаться. Сужать ниже 0.5 тоже нельзя — круг издержек
// 0.024 дневного ATR лицензирует узкий стоп формально, но 0.3 ATR переживает целиком лишь 2.4%
// дней, то есть такой стоп сидит внутри обычного внутридневного шума.
//
// RSILower=45 при RSIUpper=75. Полоса широкая и это осознанно: медиана RSI(4) на входе 38.8,
// то есть порог 45 пропускает и неглубокие откаты, а отбор в этой конфигурации делают трендовый
// фильтр EMA 5/50 и дневной гейт SpentDayATR=0.8. Соседи по walk-forward: RSILower 40 → 1.988,
// 50 → 1.777, RSIUpper 70 → 1.985, 80 → 1.617. Шесть соседей по шести осям укладываются в
// 1.617-2.560, то есть точка лежит на пологом плато, а не на одиночном пике; при Plateau 58% в
// отчёте скринера это была главная опасность, и она не подтвердилась. Правка «сделаем откат
// глубже, 45 — это же не перепроданность» разрушает конфигурацию не потому, что глубина плоха
// сама по себе, а потому, что вместе с ней придётся двигать и RSIUpper: полоса меряется целиком.
//
// TPDailyATR=0.5. Цель на WUSH живая, в отличие от fesh: 57 выходов из 219 (26.0%) против 2 из 60
// у fesh. Медиана удержания до цели 5 баров против 11 у RSI-выхода, то есть цель снимает быстрые
// сделки и тем держит просадку.
func TestCalibratedLiteralIsPinned(t *testing.T) {
	want := core.Params{
		RSIPeriod:       4,
		RSILower:        45,
		RSIUpper:        75,
		EMAFast:         5,
		EMASlow:         50,
		DailyATRPeriod:  14,
		UseDayATRGate:   1,
		FreshDayATR:     0,
		SpentDayATR:     0.8,
		StopDailyATR:    0.7,
		TPDailyATR:      0.5,
		UseVolume:       0,
		VolBaseDays:     14,
		VolLookbackBars: 3,
		VolMult:         1.2,
		UseRSIExit:      1,
		UseTrail:        0,
		TrailDailyATR:   0,
	}
	if got := DefaultParams(); got != want {
		t.Fatalf("DefaultParams() = %+v, want %+v", got, want)
	}
}

// Связь с baseline разорвана осознанно: правка core.DefaultParams() не должна доходить до
// откалиброванного тикера. Проверка не тавтологична: литерал WUSH отличается от baseline шестью
// полями (RSILower 45 против 30, RSIUpper 75 против 70, EMAFast 5 против 10, EMASlow 50 против
// 100, StopDailyATR 0.7 против 0.5, TPDailyATR 0.5 против 0.6), и достаточно откатить их «к
// дефолту», чтобы литерал незаметно схлопнулся в baseline.
func TestParamsDoNotTrackTheBaseline(t *testing.T) {
	if DefaultParams() == core.DefaultParams() {
		t.Fatal("WUSH вернул baseline: откалиброванный тикер обязан иметь собственный литерал")
	}
}

// Ловушка нулевого значения: забытое поле даёт StopDailyATR=0, то есть позицию без стопа, а эта
// стратегия держит позицию через ночи и выходные. На WUSH цена такой ошибки выше средней: тикер
// прошёл путь от пика 337.48 до минимума 30.30, то есть −91.0%.
func TestStopIsArmed(t *testing.T) {
	if got := DefaultParams().StopDailyATR; got <= 0 {
		t.Fatalf("StopDailyATR = %v, want > 0 — позиция без стопа", got)
	}
}

// Та же ловушка для основного выхода: на этом литерале RSI-выход даёт 58.9% всех выходов.
func TestRSIExitIsArmed(t *testing.T) {
	if got := DefaultParams().UseRSIExit; got != 1 {
		t.Fatalf("UseRSIExit = %d, want 1", got)
	}
}
