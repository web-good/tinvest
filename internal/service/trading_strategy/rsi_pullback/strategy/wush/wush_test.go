package wush

import (
	"testing"

	"tinvest/internal/service/trading_strategy/rsi_pullback/strategy/core"
)

// Литерал WUSH принят 2026-08-14 по решению владельца ПОСЛЕ того, как тикер не взял планку,
// объявленную в спеке до прогонов (нужны были pooled OOS PF ≥ 1.5 при ≥ 20 сделках
// одновременно на темах entry и trend; entry дал 2.000 на 59 сделках, trend — 1.317 на 83).
// Конфигурация ниже отобрана отдельным сканом: 972 комбинации при пороге частоты 100 сделок за
// 36 месяцев, топ-10 лидерборда перепроверен точечным walk-forward, и эта точка выиграла —
// pooled PF 2.999 на 81 сделке, все четыре фолда прибыльные (7.783 / 4.362 / 1.377 / 3.063),
// худший maxDD по фолду 6.12%, вырожденных фолдов нет.
//
// ГРАНИЦА ПРИЁМА, которую нельзя терять при чтении этих чисел: для фиксированной точки это НЕ
// out-of-sample. Конфигурацию выбрал скан, видевший всю историю, включая тестовые окна, поэтому
// 2.999 нельзя ставить рядом с планкой 1.5 и объявлять её взятой задним числом — планка меряла
// принципиально другое.
//
// Снимок держит литерал равным ИМЕННО той конфигурации, которую мерили: параметры задаются
// литералом core.Params, поэтому забытое или «улучшенное на глаз» поле не ломает компиляцию и
// молча меняет то, чем торгует раннер. Три поля здесь особенно уязвимы, и все три прибиты
// сознательно.
//
// StopDailyATR=1.0. Ось меряли соседями: 0.7 даёт pooled PF 2.016, 1.0 — 2.999, 1.3 — 3.123.
// Рост PF с шириной стопа означает, что часть сделок, снимавшихся стопом, дотягивает до
// RSI-выхода в плюс, — и на 1.3 это перестаёт быть стопом: на всей истории дневной размах
// меньше 1.3 ATR у 81.9% дней, то есть стоп почти перестаёт срабатывать, а его цена всплывает
// одним крупным гэпом. Взято 1.0 — середина оси, а не её край, при том что 1.3 давал бы +0.12
// к PF. Сужать до 0.7 тоже нельзя: минус 0.98 PF. На самом литерале стоп срабатывает 5 раз из
// 116 сделок (4.3%), то есть это страховка от гэпа, а не рабочий выход, — и «подтянуть» его
// вниз ради красоты означает вернуть в статистику убыточные сделки, которые ось и убирала.
//
// RSILower=30 против 25 и 20. Скан по profit_factor БЕЗ порога частоты вытаскивал 20 и 25 —
// и давал конфигурации на 21–34 сделки за три года, где отдельные фолды содержали по две сделки
// при PF 1181. Порог 100 сделок эти артефакты убрал, и на нём выигрывает 30. Правка «сделаем
// откат глубже» вернёт ровно ту вырожденность.
//
// TPDailyATR=0.5. Цель на WUSH живая, в отличие от fesh: на baseline-прогоне она дала 13.7%
// выходов против 3% у fesh. Соседи: 0.6 → 2.751, 1.0 → 2.827, то есть плато пологое, и 0.5 —
// его вершина, а не одиночный пик.
func TestCalibratedLiteralIsPinned(t *testing.T) {
	want := core.Params{
		RSIPeriod:       4,
		RSILower:        30,
		RSIUpper:        60,
		EMAFast:         5,
		EMASlow:         50,
		DailyATRPeriod:  14,
		UseDayATRGate:   1,
		FreshDayATR:     0,
		SpentDayATR:     0.8,
		StopDailyATR:    1.0,
		TPDailyATR:      0.5,
		UseVolume:       0,
		VolBaseDays:     14,
		VolLookbackBars: 3,
		VolMult:         1.2,
		UseRSIExit:      1,
		UseTrail:        0,
		TrailDailyATR:   0,
	}
	if got := DefaultParams(); got != want {
		t.Fatalf("DefaultParams() = %+v, want %+v", got, want)
	}
}

// Связь с baseline разорвана осознанно: правка core.DefaultParams() не должна доходить до
// откалиброванного тикера. Проверка не тавтологична: литерал WUSH отличается от baseline всего
// четырьмя полями (RSIUpper 60 против 70, EMAFast 5 против 10, EMASlow 50 против 100,
// StopDailyATR 1.0 против 0.5, TPDailyATR 0.5 против 0.6), и достаточно откатить их «к
// дефолту», чтобы литерал незаметно схлопнулся в baseline.
func TestParamsDoNotTrackTheBaseline(t *testing.T) {
	if DefaultParams() == core.DefaultParams() {
		t.Fatal("WUSH вернул baseline: откалиброванный тикер обязан иметь собственный литерал")
	}
}

// Ловушка нулевого значения: забытое поле даёт StopDailyATR=0, то есть позицию без стопа, а эта
// стратегия держит позицию через ночи и выходные.
func TestStopIsArmed(t *testing.T) {
	if got := DefaultParams().StopDailyATR; got <= 0 {
		t.Fatalf("StopDailyATR = %v, want > 0 — позиция без стопа", got)
	}
}

// Та же ловушка для основного выхода: на WUSH RSI-выход даёт 61% всех выходов.
func TestRSIExitIsArmed(t *testing.T) {
	if got := DefaultParams().UseRSIExit; got != 1 {
		t.Fatalf("UseRSIExit = %d, want 1", got)
	}
}
