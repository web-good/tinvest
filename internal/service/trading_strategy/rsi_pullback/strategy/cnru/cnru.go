// Package cnru supplies the ticker and rsi_pullback Params for CNRU (МКПАО «ЦИАН», обыкновенные
// акции, лот 1; до редомициляции — CIAN).
//
// СОСТОЯНИЕ: ДО КАЛИБРОВКИ, заведён в реестр бэктеста 2026-09-08 как кандидат на двадцать седьмой
// тикер боевой вселенной. DefaultParams() обязан возвращать ровно core.DefaultParams(), пока
// калибровка не проведена: пакет существует, чтобы прогоны шли через общий реестр, а не через
// generic-ветку.
//
// # Окно и схема
//
// Расчётное окно 2023-09-08 .. 2026-09-08 (36 месяцев), интервал Minutes30, без обрезки:
// получасовой ряд начинается 2023-08-04, окно помещается с запасом в один месяц, расширять назад
// некуда. Внутри окна — остановка торгов 2025-02-05 -> 2025-04-03 (57 дней), редомициляция
// CIAN -> МКПАО «ЦИАН»: закрытие до остановки 575.0 руб, закрытие в день возобновления 580.0 руб —
// сплита, консолидации и обмена с коэффициентом в ряду нет, ряд корректировать не нужно. Дыра в два
// месяца остаётся риском (см. ниже). Сессия внутри окна расширялась один раз, вдвое: медиана баров
// в буднем дне по полугодиям 19 -> 19 -> 34 -> 34 -> 35 -> 35 -> 35, вечерняя сессия появилась в
// 2024H2. Схема 36/12/6 (train 12 месяцев, OOS 6, четыре фолда) плюс обязательный контроль 24/12/3.
//
// # Baseline (дефолты ядра, 36 месяцев)
//
// 164 сделки, PF 1.814, net +82 716.98 руб (+82.72%), win rate 75.00%, max DD 12 081.22 руб
// (9.15%), exposure 5.72%, CAGR 22.23%, expectancy 504.37 руб на сделку (0.504% капитала). Выходы:
// RSI 109 (66.5%) / SL 35 (21.3%) / TP 20 (12.2%). Удержание: медиана 9 баров, p90 20, максимум 35.
// Ночёвок 48.8%, выходов в выходную сессию 6.1%.
//
// Walk-forward дефолтов: 36/12/6 -> pooled OOS PF 1.989 на 122 сделках (compounded +84.21%, win
// rate 78.69%, expectancy 552.11, Sortino 0.385), пофолдово 1.863/29, 2.535/37, 3.180/21, 1.214/35
// — НИ ОДНОГО УБЫТОЧНОГО ФОЛДА. Контроль 24/12/3 -> pooled OOS PF 1.705 (compounded +21.74%).
//
// Календарные годы baseline: 2023 (с 09-08) +2 528 руб / PF 1.880 / 6 сделок; 2024 +22 942 /
// 1.701 / 56; 2025 +45 937 / 2.219 / 60; 2026 (до 09-08) +11 310 / 1.399 / 42. Каждый год окна
// прибылен.
//
// Это ПЕРВЫЙ ТИКЕР КАТАЛОГА, у которого дефолты ядра уже проходят все пять пунктов стоп-условия
// плана до единого прогона калибровки: маршрут «завести на дефолтах ядра» по прецеденту TGKA здесь
// доступен уже сейчас. Задача калибровки — не найти edge, а не испортить уже найденный.
//
// # Издержки
//
// Шаг цены 0.2 руб. Круг из двух шагов: 0.064% при последней цене 627 руб, против 0.1%, которые
// считает модель издержек, — МОДЕЛЬ ПЕССИМИСТИЧНА В 1.6 РАЗА (первый такой случай в каталоге; ранее
// модель была оптимистична у всех тикеров, где это проверялось). Чувствительность walk-forward
// дефолтов (36/12/6) к кругу: 0.1% -> 1.989, 0.2% -> 1.705, 0.3% -> 1.448. Реальный круг 0.064%
// лежит ниже модельного, поэтому все три строки — запас, а не риск.
//
// Спека: docs/superpowers/specs/2026-09-08-cnru-rsi-pullback-prep-design.md, план:
// docs/superpowers/plans/2026-09-08-cnru-rsi-pullback-prep.md, протокол замеров:
// reports/_analysis/cnru_pullback_prep_measurements.md.
