// Package trnfp supplies the ticker and rsi_pullback Params for TRNFP (ПАО «Транснефть»,
// привилегированные акции, лот 1).
//
// СОСТОЯНИЕ: ДО КАЛИБРОВКИ, заведён в реестр бэктеста 2026-09-05 как кандидат на двадцать шестой
// тикер боевой вселенной. DefaultParams() обязан возвращать ровно core.DefaultParams(), пока
// калибровка не проведена: пакет существует, чтобы прогоны шли через общий реестр, а не через
// generic-ветку.
//
// # Окно и схема
//
// Расчётное окно 2023-09-05 .. 2026-09-05 (36 месяцев), интервал Minutes30, без обрезки: сплит
// 1:100 внутри окна (остановка торгов 2024-02-14 23:30 -> 2024-02-21 09:30) уже скорректирован в
// ряду и по цене, и по объёму — непрерывность проверена по месячным медианам через границу
// (1 103 700 -> 1 329 200 -> 1 031 490), ступени x100 нет. Иных структурных событий нет. Схема
// 36/12/6 (train 12 месяцев, OOS 6, четыре фолда) плюс обязательный контроль 24/12/3: сессия внутри
// окна расширялась один раз (медиана баров в буднем дне по полугодиям 29 -> 29 -> 34 -> 35 -> 35 ->
// 35).
//
// # Baseline (дефолты ядра, 36 месяцев, комиссия 0.0005)
//
// 155 сделок, PF 1.075, net +3 863.85 руб (+3.86%), win rate 68.39%, max DD 7 596.98 руб (7.30%),
// exposure 4.61%, expectancy 24.93 руб на сделку (0.025% капитала). Выходы: RSI 113 / SL 34
// (21.9%) / TP 8. Удержание: медиана 9 баров, p90 21, максимум 45. Ночёвок 52.3%, выходов в
// выходную сессию 11.0%. Экспозиция в июльский дивидендный гэп — НОЛЬ: ни одну из трёх ночей
// отсечки baseline не пережидал.
//
// Walk-forward дефолтов: 36/12/6 -> pooled OOS PF 1.036 на 107 сделках (пофолдово 0.898/26,
// 1.369/27, 1.097/35, 0.862/19); контроль 24/12/3 -> pooled OOS PF 1.004 на 54 сделках (пофолдово
// 0.748/18, 3.234/17, 1.150/13, 0.648/6). ОБЕ СХЕМЫ СТОЯТ НА НУЛЕ: PF формально не ниже 1.0, но
// expectancy 13.36 руб и 1.12 руб на сделку — запаса над издержками у дефолтов нет. Запасной
// маршрут «завести на дефолтах ядра» по прецеденту TGKA здесь недоступен: заводить в прод
// конфигурацию с нулевым математическим ожиданием нельзя, точка обязана создать запас сама.
//
// # Риск-гейты
//
// Гейт A (выживаемость эффективной защиты min(StopDailyATR, TrailDailyATR при UseTrail=1), потолок
// 1.0 ATR при пороге 30% будних дней): таблица (n = 760) 0.3 — 99.9%, 0.4 — 96.7%, 0.5 — 91.3%,
// 0.6 — 85.4%, 0.7 — 77.5%, 0.8 — 66.7%, 1.0 — 44.2%, 1.2 — 27.8%, 1.3 — 21.8%, 1.5 — 13.8%,
// 2.0 — 4.5%.
//
// Гейт B (просадка точки): max DD на полном окне не выше 1.3 x 7.30% = 9.49%.
//
// # Стоп-условие из четырёх пунктов (объявлено до прогонов)
//
// Работа останавливается, если принятая точка даёт: (1) pooled OOS PF < 1.0 на 36/12/6, либо
// (2) меньше 20 сделок в пуле OOS, либо (3) pooled OOS PF < 1.0 на контроле 24/12/3, либо
// (4) то же при -commission 0.001 (круг 0.2%). Пятого пункта по реальному кругу издержек, как у
// RTKMP и VSMO, здесь НЕТ: настоящий круг TRNFP 0.038% при текущей цене 1062.6 руб (0.030% при
// медиане окна 1352 руб) против 0.1%, которые считает модель издержек — модель здесь консервативна
// втрое, а не оптимистична, и пункт 4 стрессует до 0.2%, пятикратный запас над реальностью.
//
// Дополнительное условие, специфичное для TRNFP: точка с pooled OOS PF ниже 1.10 на 36/12/6 в прод
// не идёт даже при формально непровалившемся стоп-условии — порог объявлен до прогонов, потому что
// дефолты ядра уже дают 1.036 при нулевом ожидании, и точка обязана оторваться от этого уровня.
//
// # Априор скринера (2026-09-05)
//
// pullback_screen: оборот 1010 млн руб, дневной ATR 2.54%, PFmed 1.28, Plateau 25%, зажатых 0/24,
// молчащих 0/24, holdout PFmed 6.02 на 10 сделках, лучшая конфигурация сетки скринера RSI 6/10,
// EMA 20/100, TP 1.0. Априор слабый: PFmed ниже медианы каталога, Plateau 25% означает, что три
// четверти сетки скринера на бумаге не работают, а holdout на десяти сделках — шум, а не сигнал.
//
// # Ликвидность
//
// Медиана оборота будних дней 1008.23 млн руб за 36 месяцев, падение вдвое за окно: по годам
// 1266.05 (2023) -> 1218.85 (2024) -> 943.01 (2025) -> 624.52 (2026). Рекорд каталога — на два
// порядка выше гейта вселенной скринера (50 млн руб/день).
//
// # Режим
//
// Buy&hold за окно -24.1% (1398.6 -> 1062.0 руб). Полугодия baseline (PF): 1.259, 1.489, 0.802,
// 1.370, 1.136, 0.864 — три растущих полугодия из шести.
//
// # Дивидендные отсечки
//
// Три года подряд в середине июля: -10.23% (2024-07-18), -10.61% (2025-07-17), -15.22%
// (2026-07-18) — при 52.3% ночёвок у baseline. Защита — дневной гейт (SpentDayATR): день с гэпом
// сразу проходит порог потраченного дня, и вход закрывается. Это свойство дефолтов, а не заслуга
// конфигурации, и оно обязано быть перепроверено на принятой точке при калибровке.
//
// Спека: docs/superpowers/specs/2026-09-05-trnfp-rsi-pullback-prep-design.md, план:
// docs/superpowers/plans/2026-09-05-trnfp-rsi-pullback-prep.md, протокол замеров:
// reports/_analysis/trnfp_pullback_prep_measurements.md.
