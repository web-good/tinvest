// 2024 +8 803 ₽ / PF 2.546, 2025 +10 807 ₽ / PF 1.688, 2026 (до 11 сентября) +17 288 ₽ / PF 3.364 —
// УБЫТОЧНЫХ ЛЕТ НОЛЬ. Единственный убыточный год дефолтов (2025, PF 0.960) точка вылечила.
