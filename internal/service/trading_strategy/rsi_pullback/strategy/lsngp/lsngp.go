//
// Повод завести тикер — отчёт скринера reports/pullback_screen/pullback_screen_Minutes30_20260804_232456.md,
// где LSNGP занял шестое место из 99 прошедших гейты: PFmed 1.92 на TradesMed 48, Plateau 83%,
// Capped 0/24, SilentCfg 0/24. Строкой выше стоит LENT, и по колонкам устойчивости инструменты
// почти неразличимы. Но одна колонка у LSNGP ХУЖЕ всех в первой шестёрке, и её надо назвать до
// прогонов, а не после: PFmed HO = 0.99 на 12 сделках, тогда как у LENT 3.79, WUSH 4.24,
// FESH 2.84, RENI 5.49, DOMRF 2.46. Holdout-колонка — единственное в скринере, что похоже на
// out-of-sample, и здесь она говорит «ровно ноль преимущества». Рейтинг скринера не
// доказательство edge (docs/rsi_pullback/screener.md говорит это прямо), а основание потратить
// на инструмент калибровочные прогоны; эта же строка — основание отнестись к результатам
// строже обычного.
//
// Что известно об инструменте (замеры по кэшу LSNGP_Minutes30.json и LSNGP_Day1.json на
// 2026-08-14, правилами ядра: будние дни MSK как weekdayDaily, сглаживание Уайлдера как в
// pkg/indicators, слот как slotOf, объёмная база как volumeBaseline):
//
//   - Истории достаточно: 31 120 30-минутных баров (23 045 будних) за 36.2 месяца с 2023-08-07,
//     дневной кэш уходит до 2022-08-04. Штатный протокол walk-forward §8
//     docs/rsi_pullback/strategy.md (-months 36 -train-months 12 -test-months 6, 4 фолда)
//     исполним целиком — как у reni, fesh, wush и lent и в отличие от domrf.
//   - РЕЖИМ: РАСТУТ ОБА ОКНА ПРОТОКОЛА, и это главное, что надо помнить про любые числа по
//     LSNGP. Обучающее окно 2023-08-14—2026-02-14 (634 будних дня) выросло 209.25 → 306.90
//     (+46.7%), holdout 2026-02-14—2026-08-14 (129 дней) вырос ещё 305.95 → 340.15 (+11.2%).
//     Полугодия: 2023H1 +62.5% · 2023H2 −3.1% · 2024H1 +16.9% · 2024H2 −2.0% · 2025H1 +11.0% ·
//     2025H2 +27.7% · 2026H1 +10.7% · 2026H2 +3.0%; максимальная просадка цены за окно 25.7%.
//     Это ХУДШИЙ расклад для проверки лонговой стратегии из всех заведённых тикеров. У LENT
//     обучающее окно росло, зато holdout падал, и падающее полугодие само работало проверкой; у
//     WUSH падали оба окна, и лонговый результат был занижен режимом. Здесь проверочного окна
//     нет вовсе: высокий PF на holdout нельзя отличить от «рынок рос». Отсюда два следствия —
//     вес пофолдовой устойчивости выше веса любого pooled PF, и колонка скринера PFmed HO 0.99
//     при растущем holdout выглядит хуже, чем те же 0.99 выглядели бы на падающем.
//   - Дневной ATR(14) идёт медианой 2.64% цены (среднее 2.78% — колонка скринера печатает
//     именно среднее): p10 1.82 · p25 2.18 · p75 3.17 · p90 3.98 · max 6.08 (n=1010). Это САМЫЙ
//     УЗКИЙ инструмент из кандидатов: lent 3.16%, reni 3.36%, wush 4.25%, fesh 4.42%; шире
//     только domrf (1.94%).
//   - Отсюда САМЫЙ ДОРОГОЙ круг издержек: 0.1% цены = 0.038 дневного ATR против 0.032 у lent,
//     0.030 у reni, 0.024 у wush. На стопе 0.3 ATR комиссия съедает 12.6% риска — ближе к черте
//     17%, по которой строка 0.3 была вырезана из domrf/, чем у любого соседа. Строка 0.3
//     сохранена в cal_risk.json, но читать её только вместе с этим числом и с выживаемостью
//     стопа: полный дневной размах не достаёт до 0.3 ATR лишь в 2.7% дней (0.5 — 15.8%,
//     0.7 — 38.9%, 1.0 — 61.6%, 1.3 — 77.7%).
//   - День раскрывается быстро, вровень с lent: медиана доли ATR ко второму бару 0.35 (бар 3 —
//     0.41, бар 5 — 0.49, бар 8 — 0.61) против 0.33 у wush и 0.28 у fesh. Отсюда ось
//     FreshDayATR [0, 0.3, 0.4, 0.5]: порог 0.3 оставляет ветке 10.4% будних баров, 0.4 — 17.6%,
//     0.5 — 27.7%, а 0.25 — только 7.3%.
//   - Форма дня как у wush: полный дневной размах медианой 0.83 ATR предыдущего дня (p10 0.43,
//     p25 0.58, p75 1.24, p90 1.67, n=1009) против 0.90 у lent. Порог «дня исчерпанного» 0.8
//     отбирает 43.6% будних баров, 1.0 — 30.2%, 1.25 — 18.9%, 1.5 — 10.6%.
//   - Трендовый фильтр открыт 54-60% времени во ВСЕХ тридцати пяти парах EMA — чаще, чем у lent
//     (52-53%) и вдвое ровнее, чем у wush (41-43%). Вырожденных углов в сетке тренда нет, но
//     прямое следствие растущего режима: фильтр почти всегда открыт, и любая пара EMA будет
//     выглядеть работающей.
//   - ЛИКВИДНОСТЬ — второе по тонкости место во вселенной, сразу после lent. Оборот 65 млн ₽/день
//     в среднем по будням при медиане 41 млн (по годам, медианой: 2023 — 39, 2024 — 39,
//     2025 — 38, 2026 — 53). Для сравнения: lent 67/38, reni 91, fesh 287, wush 356, domrf 416.
//     Гейт скринера (50 млн) LSNGP проходит средним, но НЕ медианой — половина дней тоньше
//     порога отбора. Лот 10 при цене около 340 ₽ означает шаг позиции 3 400 ₽: гранулярность
//     заметно грубее, чем у lent (лот 1), и на малом счёте это отдельный источник расхождения
//     живого исполнения с бэктестом.
//   - Слабейший угол сетки входа RSI(7)@10 даёт 29 будних кроссов за 36 месяцев — ровно как у
//     lent и на уровне reni (23), где угол был объявлен мёртвым. Зато основная гипотеза скринера
//     здесь сильна: RSI(4)@10 — 215 будних кроссов. Строки слабого угла в лидерборде читать
//     только со счётом сделок.
//   - Ориентир baseline-прогона за 36 месяцев (RSI(4) 30/70, EMA 10/100, стоп 0.5 ATR, цель
//     0.6 ATR): 208 сделок, PF 1.554 — выборка большая, ни одна тема не упрётся в -min-trades 20.
//
// # Планка, объявленная ДО первого прогона
//
// Тикер считается подтверждённым, если темы entry и trend — те самые две, на которых
// споткнулись fesh (1.029 и 0.953), wush (2.000 и 1.317) и lent (1.355 и 1.777), — ОБЕ дают
// pooled OOS PF ≥ 1.5 при ≥ 20 сделках на объединении тестовых окон, И выбор калибратора
// устойчив: по ведущей оси темы (RSILower для entry, EMASlow для trend) одно и то же значение
// выбрано не менее чем в 3 фолдах из 4. Счёт сделок входит в критерий наравне с PF; фолд без
// единой убыточной сделки (вырожденный, PF в сотнях) не засчитывается в пользу тикера.
//
// Для LSNGP к планке добавлено ОДНО условие, которого не было у соседей, и добавлено оно из-за
// режима: ни один фолд OOS не должен быть убыточным (PF < 1.0). Обоснование — выше, в разделе
// про режим: у этого инструмента растут оба окна протокола, проверочного падающего окна нет
// вовсе, и единственный способ отличить работающую конфигурацию от пассажира растущего рынка —
// требовать, чтобы она не разваливалась ни на одном из четырёх тестовых полугодий. Формулировка
// сохранена дословно в том виде, в каком записана ДО прогонов.
