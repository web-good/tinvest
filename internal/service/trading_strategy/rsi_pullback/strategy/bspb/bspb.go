// ЗАПАС ИСТОРИИ НУЛЕВОЙ, как у SVAV. Поставщик отдаёт 30m ровно за три года, и расчётное окно
// совпадает с физическим. -refresh во время калибровки НЕ запускать: он сдвинет обе границы, а не
// только правую, как это было на DIAS.
