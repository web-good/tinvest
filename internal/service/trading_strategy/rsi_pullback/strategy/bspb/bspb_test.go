// цели точки 0.6): выключенный гейт даёт 2.422/62/23875.53, лучшая из 27 (mult 1.5 / окно 5 / база
// 3) — 2.510/50/19872.84, то есть +0.088 PF ценой 19% выборки и 17% net; вторая и третья
// (2.394/54 и 2.356/60) уже ниже выключенного. НИ ОДНА комбинация не бьёт выключенный гейт по
// совокупности PF+выборка+net. Выключенный гейт — норма каталога: он включён только у SVAV, UGLD,
// SIBN и ELFV.
func TestVolumeGateStaysOff(t *testing.T) {
	if p := DefaultParams(); p.UseVolume != 0 {
		t.Fatalf("UseVolume = %d, want 0 — ни одна из 27 комбинаций решётки не бьёт выключенный гейт (2.422/62 сделок; замер при ЦЕЛИ 0.4, а не при цели точки 0.6, где точка даёт 2.541/61) по совокупности PF+выборка+net", p.UseVolume)
	}
}

// Трейл выключен: собственная сетка темы cal_trail держит UseTrail=1 фиксированным (как во всех
// шестнадцати cal_trail.json каталога) и свипует TrailDailyATR — фолды выбрали трейл 0.3 трижды из
// четырёх, но OOS фолда 1 при этом обвалился до 0.210, а единственный фолд с фактически
// выключенным трейлом дал OOS 1.890; пул темы 1.202/47 против 2.261/47 у той же темы без трейла.
// Точечный прогон под осями точки (reports/BSPB_point_probe10, снят при цели 0.4, а не при цели
// точки 0.6): выключен -> 2.422/62, 0.3 -> 1.612/63, 0.5 -> 2.511/62, 0.7 -> 2.427/62,
// 1.0 -> 2.422/62 (не срабатывает ни разу, буквально равно выключенному). Ось немонотонна и рвана:
// выбранное фолдами значение 0.3 — ХУДШЕЕ на всей оси (-0.810 PF), единственный локальный всплеск
// 0.5 даёт +0.089 PF (3.7%). Что здесь чей вывод: прогон показал форму оси, а решение не взводить
// ручку ради 3.7% на одной точке рваной оси — выбор контроллера. TrailDailyATR обязан быть нулём
// при выключенном трейле, иначе выключенное поле несёт непроверенное значение, которое оживёт при
// первом же переключении флага.
func TestTrailStaysOff(t *testing.T) {
	p := DefaultParams()
	if p.UseTrail != 0 {
		t.Fatalf("UseTrail = %d, want 0 — выбранный фолдами трейл 0.3 худший на всей оси (1.612 против 2.422 у выключенного; замер при ЦЕЛИ 0.4, а не при цели точки 0.6, где точка даёт 2.541/61)", p.UseTrail)
	}
	if p.TrailDailyATR != 0 {
		t.Fatalf("TrailDailyATR = %v при выключенном трейле, want 0", p.TrailDailyATR)
	}
}
