// при сегодняшней цене 391 ₽ = 0.128%; круг из двух шагов 0.20-0.26% против МОДЕЛИРУЕМЫХ 0.1%.
// Модель издержек на NKHP ОПТИМИСТИЧНА, а не консервативна. Чувствительность baseline: круг 0.1%
// -> PF 1.697, 0.2% -> 1.504, 0.3% -> 1.328, 0.4% -> 1.172 (150 сделок во всех строках). Тикер
// линейку проходит — в отличие от KMAZ, где оба зонда были убыточны, — но к трём каталожным
// пунктам стоп-условия добавлены два персональных: PF < 1.0 под тройным кругом и pooled OOS PF <
// 1.0 на контрольном прогоне 24/12/3.
//
// ЧТО ЗНАЕМ ОБ ИНСТРУМЕНТЕ ДО ПРОГОНОВ (замеры на расчётном окне, полностью —
// reports/_analysis/nkhp_pullback_prep_measurements.md):
//
//   - РЕЖИМ: итог окна −84.0% (2290 -> 365.5), максимальная просадка инструмента −87.4%. Пять
//     падающих полугодий из шести (−52.6 / −30.1 / +7.2 / −19.5 / −5.0 / −32.6%). При этом ВСЕ
//     ШЕСТЬ ПОЛУГОДИЙ BASELINE ПРИБЫЛЬНЫ (PF 1.442 / 1.672 / 4.409 / 1.086 / 1.911 / 1.366) —
//     такого в каталоге не было ни разу. Полугодие 3 несёт 41.9% net.
//   - ЛИКВИДНОСТЬ САМАЯ ТОНКАЯ В КАТАЛОГЕ И ПАДАЮЩАЯ: медиана оборота будних дней за 12 месяцев
//     16.3 млн ₽ при гейте вселенной 50 млн. Выходная сессия: 266 дней с барами, медианный оборот
//     1.09 млн ₽; входов baseline в выходные НОЛЬ, но выходов 10.0% (36 мес) — стоп и цель
