//
// ОКНО И СХЕМА КАНОНИЧЕСКИЕ. Расчётное окно — 2023-09-02 … 2026-09-02 (36 месяцев); в окне 27 546
// получасовых баров, из них 21 663 будних. Схема прогонов -months 36 -train-months 12
