// придаётся: вопрос «предсказывают ли колонки скринера исход протокола» каталог закрыл девять раз
// подряд — не предсказывают ни снизу, ни сверху.
//
// ЛИНЕЙКА ИЗДЕРЖЕК (урок KMAZ) ПРИМЕНЕНА ПЕРВЫМ ДЕЙСТВИЕМ, И ОНА ЗДЕСЬ ХУЖЕ ВСЕГО КАТАЛОГА, КРОМЕ
