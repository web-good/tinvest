// ДВЕ СТРУКТУРНЫЕ ГРАНИЦЫ ВНУТРИ ОКНА, из-за которых принятая точка проверяется ДВАЖДЫ:
//   - СЕССИЯ РАСШИРИЛАСЬ 2024-09-26: было 19 получасовых баров в буднем дне (09:30-18:30), стало
//     34 (07:00-23:30). Доля дней короче 20 баров: 100% (2023), 56.5% (2024), 1.5% (2025).
//   - ЛИКВИДНОСТЬ УПАЛА НА ПОРЯДОК: медиана дневного оборота 153.0 млн ₽ (2023) -> 23.4 (2024) ->
