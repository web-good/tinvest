// Пакет заведён 2026-08-14 ДО калибровки — как место, куда ляжет литерал, и как носитель
// замеров инструмента. Сетки: data/params/rsi_pullback/lent/. В тот же день девять тем
// прогнаны, объявленная заранее планка НЕ взята (разбор ниже), и литерал поставлен отдельным
// решением — как это уже делалось по domrf, fesh и wush. Снимок литерала держит lent_test.go.
//
// Повод завести тикер — отчёт скринера reports/pullback_screen/pullback_screen_Minutes30_20260804_232456.md,
// где LENT занял пятое место из 99 прошедших гейты: PFmed 1.93 на TradesMed 54, PFmed HO 3.79
// на 10 сделках. Главное в этой строке не место, а КОЛОНКИ УСТОЙЧИВОСТИ: Plateau 92% и
// Capped 0/24 — лучшие в первой пятёрке (у WUSH 58% и 4/24, у FESH и RENI по 83%). Plateau —
// доля конфигураций с PF ≥ 1.3 при ≥ 10 сделках, то есть ширина рабочей зоны; у LENT она самая
// широкая из кандидатов, и это ровно то место, где WUSH был слаб. Рейтинг скринера не
// доказательство edge (docs/rsi_pullback/screener.md говорит это прямо), а основание потратить
// на инструмент калибровочные прогоны.
//
// Что известно об инструменте (замеры по кэшу LENT_Minutes30.json и LENT_Day1.json на
// 2026-08-14, правилами ядра: будние дни MSK как weekdayDaily, сглаживание Уайлдера как в
// pkg/indicators, слот как slotOf, объёмная база как volumeBaseline):
//
//   - Истории достаточно: 32 287 30-минутных баров (23 241 будний) за 36.0 месяца с 2023-08-14,
//     дневной кэш уходит до 2022-08-15. Штатный протокол walk-forward §8
//     docs/rsi_pullback/strategy.md (-months 36 -train-months 12 -test-months 6, 4 фолда)
//     исполним целиком — как у reni, fesh и wush и в отличие от domrf.
//   - РЕЖИМ ОБРАТЕН WUSH, и это главное, что надо помнить про любые числа по LENT. Обучающее
//     окно 2023-08-14—2026-02-13 (649 будних дней) выросло 807.00 → 2100.50 (+160.3%), holdout
//     2026-02-16—2026-08-14 (130 дней) просел 2101.00 → 1934.00 (−7.9%). Полугодия: 2023H2
//     −15.0% · 2024H1 +70.5% · 2024H2 +5.6% · 2025H1 +21.6% · 2025H2 +37.5% · 2026H1 −8.2% ·
//     2026H2 +13.3%; максимальная просадка цены за окно 32.2%. Лонговая стратегия в растущем
//     обучающем окне получает результат ЗАВЫШЕННЫЙ режимом — ровно та беда, из-за которой
//     holdout FESH (+13.1%) не мог служить подтверждением. У WUSH было наоборот: там падали оба
//     окна и in-sample PF был занижен. Поэтому планка PF ≥ 1.5 на train здесь СЛАБЕЕ, чем та же
//     планка на WUSH, а вес holdout-окна и пофолдовой устойчивости — выше.
//   - Дневной ATR(14) идёт медианой 3.16% цены (среднее 3.28% — колонка скринера печатает
//     именно среднее): p10 2.30 · p25 2.53 · p75 3.93 · p90 4.50 · max 5.63 (n=763). Инструмент
//     заметно УЖЕ wush (4.25%) и fesh (4.42%), стоит рядом с reni (3.36%) и вдвое шире
//     domrf (1.94%).
//   - Круг издержек 0.032 дневного ATR — дороже, чем у wush (0.024), fesh (0.023) и reni
//     (0.030). На стопе 0.3 ATR комиссия съедает 10.6% риска; строка сохранена в cal_risk.json,
//     но читать её надо вместе с этим числом и с выживаемостью стопа: полный дневной размах не
//     достаёт до 0.3 ATR лишь в 1.8% дней (0.5 — 11.7%, 0.7 — 29.1%, 1.0 — 59.6%, 1.3 — 78.9%).
//   - День раскрывается БЫСТРЕЕ всех заведённых тикеров: медиана доли ATR ко второму бару 0.35
//     против 0.33 у wush и 0.28 у fesh. Отсюда ось FreshDayATR [0, 0.3, 0.4] (0.3 оставляет
//     ветке 10.1% будних баров, 0.4 — 17.9%), а пороги fesh [0, 0.25, 0.35] сюда не переносятся.
//   - Форма дня шире соседей: полный дневной размах медианой 0.90 ATR предыдущего дня против
//     0.83 у wush и 0.85 у fesh, поэтому одни и те же пороги «дня исчерпанного» отбирают здесь
//     больше баров (0.8 — 45.5% против 35.8% у wush).
//   - Трендовый фильтр открыт 52-53% времени во всех шестнадцати парах EMA — вдвое ровнее, чем
//     у wush (41-43%), вырожденных углов в сетке тренда нет.
//   - САМОЕ СЛАБОЕ МЕСТО — ЛИКВИДНОСТЬ. Оборот 67 млн ₽/день в среднем при медиане будних дней
//     всего 38 млн (2023 — 21, 2024 — 48, 2025 — 64, 2026 — 118). Это самый тонкий инструмент из
//     заведённых: wush 356, domrf 416, fesh 287, reni 91 млн. Гейт скринера (50 млн) LENT
//     проходит средним, но НЕ медианой, то есть половина дней тоньше порога отбора. Лот 1 при
//     цене около 2000 ₽ гранулярность позиции не портит, но размер позиции упирается в стакан
//     раньше, чем у любого другого тикера вселенной.
//   - Второе слабое место, заявленное до прогонов: слабейший угол сетки входа RSI(7)@10 даёт
//     всего 29 будних кроссов за 36 месяцев — уровень reni (23), где угол был объявлен мёртвым,
//     а не wush (60). Строки этого угла в лидерборде читать только со счётом сделок.
//
// # Планка, объявленная ДО первого прогона
//
// Тикер считается подтверждённым, если темы entry и trend — те самые две, на которых
// споткнулись fesh (1.029 и 0.953) и wush (2.000 и 1.317), — ОБЕ дают pooled OOS PF ≥ 1.5 при
// ≥ 20 сделках на объединении тестовых окон, И выбор калибратора устойчив: по ведущей оси темы
// (RSILower для entry, EMASlow для trend) одно и то же значение выбрано не менее чем в 3 фолдах
// из 4. Счёт сделок входит в критерий наравне с PF; фолд без единой убыточной сделки
// (вырожденный, PF в сотнях) не засчитывается в пользу тикера. Формулировка сохранена дословно
// в том виде, в каком была записана ДО прогонов; что из неё вышло — в следующем разделе.
//
// # Результат прогонов 2026-08-14: планка НЕ взята
//
// Девять тем прогнаны rolling walk-forward (train 12 мес / OOS 6 мес встык, 4 фолда,
// ранжирование по profit_factor, -min-trades 20, у screen — 1). Pooled OOS PF и счёт сделок:
// screen 1.677/128, entry 1.355/159, trend 1.777/165, exit 1.775/143, day 1.816/81,
// day_spent 1.550/69, volume 1.641/105, risk 2.861/141, trail 1.526/137. Восемь тем из девяти
// выше 1.0 на пулах 69–165 сделок.
//
// Планка требовала pooled OOS PF ≥ 1.5 при ≥ 20 сделках ОДНОВРЕМЕННО на entry и trend плюс
// устойчивость ведущей оси в 3 фолдах из 4. Не выполнено ни то, ни другое:
//
//   - entry дал 1.355 при пороге 1.5, а ведущая ось RSILower гуляла 35 / 50 / 20 / 25 — четыре
//     разных значения на четырёх фолдах, то есть устойчивости нет вовсе;
//   - trend дал 1.777 — порог по PF взят, — но EMASlow выбран 150 / 100 / 100 / 50, то есть
//     2 совпадения из 4 при требуемых 3.
//
// Тема risk с её pooled 2.861 не засчитывается: фолд 1 дал OOS PF 7.507 при просадке 2.34%, а
// выбранный во ВСЕХ четырёх фолдах стоп 1.3 ATR переживается 78.9% дней целиком — такой стоп
// почти не срабатывает, и высокий profit factor берётся не из логики, а из вытеснения убыточных
// сделок в RSI-выход. Ровно ради таких случаев вердикт и был заранее привязан к двум названным
// темам, а не к лучшей из девяти. Это тот же капкан, что был у wush, где та же тема дала фолд с
// OOS PF 11.439.
//
// # Ширина сетки входа: расширение оси измеримо ухудшило тему
//
// Владелец расширил cal_entry.json перед прогонами: добавил ось RSIUpper [55…85] и поднял
// RSILower до [10…50], получив 224 комбинации вместо 16. Обе редакции прогнаны на одних и тех же
// фолдах, и исходная узкая сетка оказалась ЛУЧШЕ по обоим критериям планки: pooled OOS PF
// 1.935 на 81 сделке против 1.355 на 159, а ведущая ось выбрана 25 / 25 / 20 / 25, то есть 3
// фолда из 4 — устойчивость есть. На широкой сетке выбор разъезжается (35 / 50 / 20 / 25), а
// фолды 3 и 4 схлопываются до 8 и 11 сделок при in-sample PF 4.947 и 4.752 — классический
// перебор степеней свободы. Это второй замер того же эффекта: на wush расширение той же оси
// уронило тему с 2.000 до 1.674. Планку это не спасает — её заваливает trend, который RSILower
// не свипует вовсе, — но при чтении лидерборда entry надо помнить, какой редакцией он получен.
//
// # Литерал, выбранный 2026-08-14 по лидербордам
//
// Каждое поле опирается на то, что показали темы, а не на перебор:
//
//   - RSILower 25 — устойчивый выбор узкой редакции entry (3 фолда из 4);
//   - RSIUpper 75 — тема exit выбрала 80 в 3 фолдах из 4, но она мерила полосу при RSILower 30;
//     при принятом входе 25 оптимум полосы смещается, и 75 меряется лучше 80 (2.487 против
//     2.133 pooled на одинаковых фолдах);
//   - EMA 20/100 — тема trend устойчивости не дала, поэтому медленная EMA оставлена на baseline
//     100 (выбрана в 2 фолдах из 4, чаще прочих), а быстрая поднята с 10 до 20: точечная
//     проверка даёт 2.487 против 2.408 при большем счёте сделок;
//   - SpentDayATR 0.8 — темы day и day_spent обе указывали на 1.25 (3 фолда из 4 каждая), но
//     точечная проверка показала цену этого выбора: сделок остаётся 42 вместо 120, а фолд 1
//     вырождается в OOS PF 28976 при нуле убыточных сделок. Порог 0.8 отбирает 45.5% будних
//     баров и сохраняет выборку;
//   - StopDailyATR 0.7 — НЕ победитель темы risk (там 1.3 в 4 фолдах из 4). Взят осознанно уже:
//     стоп 0.7 переживается целиком в 29.1% дней против 78.9% у 1.3, то есть остаётся рабочим
//     выходом, а не страховкой от гэпа. Проверено в структуре выходов ниже;
//   - TPDailyATR 1.0 — выбор темы risk в 3 фолдах из 4.
//
// Замеры принятой конфигурации. Rolling walk-forward сеткой из ОДНОЙ точки, где калибратор
// ничего не выбирает и profit factor принадлежит конфигурации, а не процедуре отбора: pooled PF
// 2.487 на 120 сделках, фолды 2.515 / 2.406 / 1.498 / 3.949 — все четыре выше 1.5, худший maxDD
// по фолду 7.90%. За 36 месяцев in-sample: 153 сделки, PF 2.083, win rate 71.90%, просадка
// 5.79%, чистый PnL 102.62% при fraction=1, CAGR 26.51%, exposure 7.86%. По годам: 2023 (4.5
// месяца, 8 сделок) PF 0.558 — единственный убыточный отрезок, 2024 — 1.706 на 49 сделках,
// 2025 — 1.860 на 62, 2026 — 4.007 на 34. На holdout-полугодии 2026-02-14—2026-08-14 PF 3.949
// на 27 сделках.
//
// Плато проверено девятью соседями по пяти осям: RSILower 20 → 2.561, 30 → 1.569; RSIUpper 80 →
// 2.133, 85 → 2.024; EMAFast 10 → 2.408; EMASlow 150 → 2.175; StopDailyATR 0.5 → 1.748, 1.0 →
// 2.537; TPDailyATR 1.5 → 2.341. Разброс 1.569–2.561 без провалов ниже единицы — точка на
// пологом плато, что согласуется с колонкой скринера Plateau 92%. Единственное направление, где
// результат заметно проседает, — возврат RSILower к baseline 30 (1.569 при maxDD 20.48%).
//
// Сосед StopDailyATR 1.0 даёт формально лучший pooled PF 2.537, и его НЕ надо путать с
// улучшением: у него фолд 1 показывает OOS PF 15.347, фолд 3 проваливается ниже единицы
// (0.987), а худшая просадка по фолду растёт с 7.90% до 19.39%. Это ровно тот профиль, которым
// широкий стоп покупает profit factor, и та же ловушка, что была разобрана по wush.
//
// Структура выходов на принятом литерале за 36 месяцев (153 сделки): RSI-выход 115 сделок
// (75.2%, медиана 12 баров, PnL +156 195), стоп 29 (19.0%, медиана 10 баров, −89 519), цель 9
// (5.9%, медиана 10 баров, +35 945); медиана удержания по всем сделкам 12 баров. Стоп здесь
// РАБОЧИЙ выход. Ось цели, наоборот, почти инертна: 1.0 дневного ATR цена достаёт лишь в 9
// сделках из 153 — если конфигурацию будут менять, это первое поле, где надо не поверить
// лидерборду, а посмотреть на счёт.
//
// ГРАНИЦА ПРИЁМА: для фиксированной точки это НЕ out-of-sample. Конфигурацию собрал человек,
// видевший всю историю, включая тестовые окна, поэтому 2.487 нельзя сравнивать с планкой 1.5 и
// объявлять её взятой задним числом. Штатный протокол §8 этот тикер НЕ подтверждает: его вердикт
// — тематические прогоны выше, и они дали 1.355 по входу и 1.777 при неустойчивой оси по тренду.
// Наличие литерала снимает техническую блокировку, но не является правом ставить LENT в
// RSI_PULLBACK_TICKERS — это отдельное решение владельца, как было с domrf, fesh и wush. К
// ликвидности это относится в первую очередь: 38 млн ₽ медианного дневного оборота — предел, на
// который стоит смотреть до, а не после ввода в прод.
