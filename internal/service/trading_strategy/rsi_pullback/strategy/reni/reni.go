//
// ВАЖНО: этот литерал — снимок ПОСЛЕДНЕГО прогона калибровки. Если следующий прогон даст другую
// выигрышную комбинацию, литерал обязан быть ЗАМЕНЁН: оставить старые числа после нового прогона
// значит торговать конфигурацией, которую свежие данные не подтверждали.
//
// # Перекалибровка 2026-08-16
//
// Тикер откалиброван 2026-08-12 и перекалиброван 2026-08-16 на расширенных сетках (вход 252
// комбинации против прежних 16, тренд 35 против 16, обе ветки дневного гейта 24, риск 35).
// Против литерала 2026-08-12 изменены ДВА поля: EMASlow 100 -> 200 и TPDailyATR 1.5 -> 0.6.
// Каждая правка закрывает по одной оговорке, которые прошлый пакет вёз с собой как известные.
//
// # Цель 1.5 была декоративной — это замер, а не мнение
//
// Прошлая дока честно писала: walk-forward называл стабильной цель 0.6, а в литерале стоит 1.5,
// и OOS-подтверждение относится к 0.6. Теперь известно, почему так вышло и чего это стоило.
// Цель 1.5 дневного ATR на RENI не срабатывала НИ РАЗУ за 36 месяцев: в смеси выходов прежнего
// литерала 102 сделки делятся как RSI 77% и стоп 23%, доля цели — ноль. Это же видно на
// лидерборде без единой сделки: точки TPDailyATR 1.0 и 1.5 дают побайтово одинаковый результат,
// то есть выше 1.0 ATR поле инертно и стратегия шла фактически без цели. На 0.6 цель оживает —
// 18 срабатываний из 107 сделок (17% выходов, +42 679), и pooled OOS растёт с 2.195 до 2.467
// при прочих принятых полях. Ось цели вокруг принятой точки: 0.5 — 2.403, 0.6 — 2.467,
// 0.7 — 2.456, 1.0 и 1.5 — по 2.123.
//
// Принята 0.6, а не 0.5, хотя у 0.5 есть свойство, которого нет ни у одной другой точки набора:
// ВСЕ четыре фолда выше планки 1.5 (2.047 / 3.586 / 1.539 / 2.402). Причина выбора — 0.6
// единственное значение цели, которое слепая тема risk выбирала независимо от человека: во всех
// четырёх фолдах прогона 2026-08-12 и в трёх из четырёх сегодняшнего. Точка 0.5 записана как
// главный контрдовод и остаётся в сетке cal_risk.json.
//
// # Трендовый фильтр чинит провальный фолд
//
// Прошлая дока называла второй оговоркой фолд 3 (OOS 2025-08-12—2026-02-12): PF 0.337 на 7
// сделках, «режим, в котором стратегия не работает, в окне существует». Режим и правда
// существует — это глубокий нисходящий тренд (пик 141.06 от 2025-03-20 -> минимум 63.72 от
// 2026-07-20, −54.8%), — но дело было не в нём, а в том, что фильтр его не замечал. Ось EMASlow
// при прочих принятых полях: 50 — 2.247, 70 — 2.381, 100 — 2.195, 120 — 2.248, 150 — 2.598,
// 170 — 2.312, 200 — 2.467, а третий фолд по той же оси идёт 0.485 / 0.347 / 0.337 / 0.500 /
// 1.078 / 1.073 / 1.351. Быстрая половина оси разрушена вся, медленная жива вся. Это ровно та
// проверка, которую прошлая дока требовала провести: в падающем режиме трендовый фильтр обязан
// выключать вход, и EMA(100) этого не делала.
//
// EMASlow=200 стоит НА КРАЮ свипуемой оси, и край проверен на обрыв замерами ЗА её пределами:
// 250 — 2.604, 300 — 2.447, 400 — 2.433. За двумя сотнями результат не растёт, то есть 200 —
// точка на широкой полке 150-400, а не артефакт того, где кончилась сетка. Внутри полки выбор
// сделан по слабейшему фолду: у 150 pooled выше (2.598), но третий фолд 1.078 против 1.351 у
// 200, а весь смысл этой перекалибровки — в том самом фолде. Lookback при EMASlow=200 равен
// 2*200+20 = 420 баров против 23 071 будних в кэше, прогрев занимает 1.8% истории.
//
// # Что НЕ изменено и почему
//
// Полоса выхода RSIUpper=70 сохранена, и это единственное место, где промежуточный результат
// вводил в заблуждение. Поверх СТАРОЙ быстрой EMA ранний выход выглядел главным улучшением
// тикера (RSIUpper 55 давал 2.459 против 1.864), но поверх EMA 200 он проигрывает (2.374
// против 2.467), потому что лечил он не выход, а слишком быстрый трендовый фильтр. Цена ошибки
// была бы не только в profit factor: с полосой 55 доля сделок длиннее одного торгового дня
// падает с 29% до 3%, то есть многодневная по замыслу стратегия молча становится внутридневной —
// ровно то, что случилось на LSNGP.
//
// Стоп 0.5 — настоящий внутренний максимум оси (0.3 — 1.901, 0.5 — 2.467, 0.7 — 2.398), и это
// доверия прибавляет: на GAZP, LSNGP и T та же ось была монотонной, и там стоп приходилось
// выбирать против лидерборда. Стоп 1.0 формально даёт больше (2.590), но третий фолд падает до
// 0.818 при четвёртом 6.203 — вытеснение убытков в RSI-выход, разобранное в cal_risk.json.
// Порог дневного гейта 0.8 тоже внутренний максимум (0.6 — 1.812, 0.8 — 2.467, 0.9 — 1.934,
// 1.0 — 2.920 при третьем фолде 0.181 на двух сделках). Глубина входа 20 и период RSI 4
// подтверждены (15 — 2.096, 25 — 1.515; RSI(5) — 2.031 с вырожденным четвёртым фолдом 22.088).
// Оба необязательных гейта остаются выключенными: объём даёт 2.449 ценой одиннадцати сделок,
// трейл — 2.275. RSI-выход обязателен: без него 1.580.
//
// # Что известно об инструменте
//
//   - История: 31 922 30-минутных бара (23 203 будних) за 36.0 месяца с 2023-08-16. Штатный
//     протокол walk-forward §8 docs/rsi_pullback/strategy.md исполним целиком.
//   - Дневной ATR(14) идёт медианой 2.86% цены (p10 1.52, p90 3.94), медианный дневной размах —
//     0.90 ATR предыдущего дня. Круг издержек 0.1% оборота стоит 0.035 ATR.
//   - Трендовый фильтр открыт около 46% времени на всех замеренных парах — RENI режет примерно
//     половину истории, а не подавляющую её часть, как растущие тикеры каталога.
//   - Оборот 91 млн ₽/день — второй снизу в каталоге после LENT (38 млн). Калибровку это не
//     ограничивает, но останется ограничением на размер позиции, если тикер дойдёт до живой
//     вселенной.
//
// # Замеры принятой конфигурации
//
// Точечный walk-forward (data/params/rsi_pullback/reni/plateau_point.json): pooled PF 2.467 на
// 79 сделках, фолды 2.078 / 3.832 / 1.351 / 2.469 — вырожденных нет, провальных нет впервые за
// историю тикера (прежний литерал на том же прогоне: 1.864 на 73 сделках, фолды 2.002 / 2.331 /
// 0.336 / 2.084). In-sample за 36 месяцев: 107 сделок, PF 2.432, win rate 73.83%, чистый PnL
// +62.63%, максимальная просадка 6.08%, CAGR 17.58%, exposure 3.77% (прежний литерал: 102
// сделки, PF 1.715, win rate 68.63%, +30.42%, просадка 7.42%, CAGR 9.25%). Каждый календарный
// год прибылен и каждый лучше прежнего: 2023 +5188 против +1565, 2024 +22 833 против +12 359,
// 2025 +28 979 против +13 107, 2026 +5629 против +3386. Выходы делятся как RSI 64%, стоп 19%,
// цель 17%; медиана удержания 10 баров, p75 — 15, максимум 37, дольше одного торгового дня
// живут 31 сделка из 107 — многодневный характер стратегии сохранён.
//
// ОГОВОРКА ОБ ИСПОЛНЕНИИ: движок закрывает сделку ПО УРОВНЮ стопа, даже когда бар прошёл его
// насквозь. На принятой точке 12 из 20 стоп-выходов — такие проколы, у прежнего литерала 14 из
// 23. Обе конфигурации оценены одинаково оптимистично, поэтому сравнение между ними честное, а
// абсолютные числа завышены у обеих.
//
// ГРАНИЦА ПРИЁМА: числа принятой точки НЕ являются out-of-sample — конфигурацию собрал человек,
// видевший всю историю, включая тестовые окна. Слепые темы того же дня, к истории окна не
// подглядывавшие: risk 2.286/75, volume 2.015/59, exit 1.974/75, entry 1.955/66, trend 1.920/67,
// screen 1.913/70, day_spent 1.441/59, trail 1.434/61, day 1.409/62 — шесть тем из девяти выше
// планки 1.5, и это лучший тематический результат каталога после UGLD. Планку по протоколу §8
// тикер всё же не берёт: обязательная пара тем взята (entry 1.955, trend 1.920), но ведущая ось
// не устойчива ни в одной из них — RSILower гулял 20/15/20/25, EMASlow 120/50/50/70.
//
// РЕШЕНИЕ О ВСЕЛЕННОЙ: 2026-08-17 владелец завёл RENI в RSI_PULLBACK_TICKERS — вместе с nvtk и
// lsngp и тем же порядком, каким до этого заводились domrf, fesh, wush и lent. За это решение
// говорило то, что изменилось против 2026-08-12: расхождение литерала с победителем walk-forward
// по цели закрыто (принята 0.6), провальный фолд вылечен и объяснён механически, каждый
// календарный год прибылен, из троих заведённых в тот день тикеров RENI ближе всех к планке.
// Против него говорило и продолжает говорить: 91 млн ₽ оборота, неустойчивость ведущих осей и то,
// что разница между слепыми темами и принятой точкой — работа человека, смотревшего на OOS-числа.
// Заведение ничего из этого не отменяет; условия пересмотра — docs/rsi_pullback/live.md §10,
// риск 11.
//
// Файлы сеток и полный разбор каждой темы — data/params/rsi_pullback/reni/, отчёты лежат
// локально (каталог reports/ в .gitignore).
