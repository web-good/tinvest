// Package gazp supplies the ticker and starting rsi_pullback Params for GAZP (Gazprom).
//
// Calibration HAS been run for this ticker. The values below are GAZP's own post-grid result,
// copied in as an explicit literal rather than left as core.DefaultParams() — the two consequences
// of that are deliberate. First, this package does NOT track the baseline: a future change to
// core.DefaultParams() must not reach GAZP silently, because these values came from GAZP's own
// calibration, not from the generic starting point. Second, once a fresh -calibrate run picks a
// different winning combination for GAZP, this literal must be REPLACED — leaving the old numbers
// in place after a newer run would ship a config the latest data never endorsed.
//
// # Перекалибровка 2026-08-15
//
// Владелец расширил сетки каталога gazp/ (ось входа до 252 комбинаций, ось тренда до 35, обе
// ветки дневного гейта до 24), и девять тем прогнаны заново на освежённом кэше — 36 770
// 30-минутных баров, из них 25 744 будних, за 36.0 месяца с 2023-08-14. По итогам изменено ОДНО
// поле: StopDailyATR 0.5 -> 0.7. Остальные семнадцать подтверждены точечными замерами и
// оставлены как были.
//
// Режим инструмента — лучший в каталоге для проверки лонговой стратегии: падают ОБА окна
// протокола (train 176.16 -> 127.33, −27.7%; holdout 127.50 -> 84.59, −33.7%), пик-минимум
// −57.3%. Лонговый результат здесь режимом ЗАНИЖЕН, а не завышен (у LENT и LSNGP было наоборот),
// поэтому profit factor читается как нижняя оценка. Дневной ATR 2.71% цены медианой, медианный
// дневной размах 0.86 ATR предыдущего дня, оборот 587 млн ₽/день медианой — самый ликвидный
// инструмент вселенной.
//
// # Планка не взята — пятый тикер подряд
//
// Требование то же, что объявлялось для WUSH, LENT и LSNGP: pooled OOS PF >= 1.5 при >= 20
// сделках одновременно на темах entry и trend плюс устойчивость выбора ведущей оси в 3 фолдах из
// 4. Вышло: entry 2.122 на 61 сделке (порог взят, устойчивости нет — RSILower 30/30/35/50),
// trend 1.481 на 50 (не взят ни порог, ни устойчивость — EMASlow 150/70/120/170, четыре разных
// значения). Остальные семь тем: screen 1.781/81, exit 1.711/44, day_spent 1.694/77, trail
// 1.615/45, risk 1.425/43, day 1.123/60, volume 2.230/40.
//
// Два наблюдения из этих прогонов, которых не было у соседей. Первое: расширение оси входа
// ВПЕРВЫЕ улучшило тему (широкая редакция 2.122/61 против узкой 4x4 1.034/26, у которой четвёртый
// фолд остался вовсе без сделок) — на wush и lent то же расширение тему роняло. Второе: тема
// screen выбрала UseVolume=1 во всех четырёх фолдах, но это артефакт метрики, а не свойство
// гейта — каждая точечная конфигурация с включённым объёмным гейтом даёт вырожденный второй фолд
// (PF 11.8-14.2 на 5-8 сделках), и калибратор, ранжирующий по profit factor, предпочитает его
// честным 2.432 на пяти сделках без гейта.
//
// # Почему стоп 0.7, а не победитель темы
//
// Тема risk выбрала стоп 0.7/1.0/0.3/1.0 — устойчивости нет, и выбирать по profit factor тут
// нельзя: PF растёт монотонно с шириной стопа (0.5 — 2.095, 0.7 — 2.125, 0.8 — 2.417, 1.0 —
// 2.943 pooled) при монотонно падающей доле стоп-выходов (21.9% / 11.0% / 8.2% / 5.5% на 73
// сделках in-sample), то есть метрика меряет вытеснение убытков в RSI-выход. Принят 0.7 по
// механике: это последняя точка, где стоп остаётся заметным выходом (11.0%, у WUSH принимали при
// 15.1%, у LENT при 19.0%), и одновременно 81% медианного дневного размаха — та же доля, по
// которой стоп выбирали на LSNGP (84%). Прежний 0.5 давал 21.9% стоп-выходов при среднем убытке
// 1221 против 1710 на 0.7, но их вдвое больше, так что суммарная цена стоп-выходов на 0.7 НИЖЕ
// (13 680 против 19 536), win rate выше (73.97% против 69.86%), а средний убыток по всем сделкам
// не изменился (928.76 против 927.52). Гэп-риск, которого опасается §9 доки, на 0.5 не
// подтвердился: в первый час дня приходилось лишь 2 стопа из 16.
//
// # Замеры принятой конфигурации
//
// Точечный walk-forward (сетка из одной точки, калибратор ничего не выбирает): pooled PF 2.125 на
// 44 сделках, фолды 1.938 / 4.066 / 1.662 / 1.964 — все четыре выше планки, вырожденных нет,
// худшая просадка фолда 2%. In-sample за 36 месяцев: 73 сделки, PF 2.000, win rate 73.97%,
// просадка 4.24%, CAGR 5.56%, exposure 2.80%. Holdout-полугодие (падение на 33.7%): 16 сделок,
// PF 1.962, просадка 2.81%. Каждый календарный год прибылен: 1.879 / 1.090 / 3.370 / 2.267.
// Выходы делятся как RSI 82.2% / SL 11.0% / TP 6.8%, медиана удержания 12 баров, максимум 57,
// на бары выходных приходится 6.8% выходов. Плато по шестнадцати соседям 1.121-2.417, и
// единственный обрыв — RSILower 30 (1.121): вход это поле меняет качественно, остальные оси
// пологие.
//
// Граница приёма та же, что у WUSH, LENT и LSNGP: для фиксированной точки перечисленные числа
// НЕ являются out-of-sample — конфигурацию довёл до ума человек, видевший всю историю, поэтому
// сравнивать 2.125 с планкой 1.5 нельзя. Прежний литерал (стоп 0.5) остаётся действующей
// альтернативой по одному замеру: на последнем падающем полугодии он давал PF 2.644 против 1.962,
// то есть замена стопа holdout-окном НЕ подтверждена и держится на in-sample выборке втрое
// большего размера.
//
// GAZP торгуется в боевой вселенной с 2026-08-05 решением владельца и БЕЗ walk-forward
// подтверждения — как и T. Перекалибровка этого не меняет: она уточняет одно поле, а не снимает
// оговорку.
//
// Файлы сеток и полный разбор каждой темы — data/params/rsi_pullback/gazp/, отчёты лежат
// локально (каталог reports/ в .gitignore).
