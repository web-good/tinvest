//
// ВЕРДИКТ ПО ПЛАНКЕ — НЕ ВЗЯТА, и это записано пункт за пунктом. Планка требует от ОБЕИХ ключевых
// тем pooled OOS PF >= 1.5 при >= 20 сделках И устойчивость ведущей оси >= 3 фолда из 4.
//
//   - Тема entry (data/params/rsi_pullback/ydex/cal_entry.json): pooled OOS PF 1.916 на 52 сделках
//     — критерий PF ВЗЯТ (1.916 >= 1.5, 52 >= 20); ведущая ось RSILower по фолдам 10, 25, 35, 25 —
//     устойчивость 2 из 4, критерий устойчивости ПРОВАЛЕН.
//   - Тема trend (data/params/rsi_pullback/ydex/cal_trend.json): pooled OOS PF 1.642 на 71 сделке —
//     критерий PF ВЗЯТ (1.642 >= 1.5, 71 >= 20); ведущая ось EMASlow по фолдам 200, 50, 200, 70 —
//     устойчивость 2 из 4, критерий устойчивости ПРОВАЛЕН.
//
// Итого два критерия из четырёх провалены. ФОРМА ПРОВАЛА НЕ НОВАЯ — она ПОВТОРЯЕТ ELFV, и это
// ВТОРОЙ такой случай в каталоге, а не первый: у ELFV тема entry дала pooled OOS PF 1.575 на 106
// сделках при устойчивости RSILower 1 из 4 (30, 20, 25, 35), тема trend — 1.545 на 147 сделках при
// устойчивости EMASlow 0 из 4 (200, 120, 150, 50), то есть обе взяли PF и обе провалили
// устойчивость, ровно как здесь. YDEX отличается от ELFV в лучшую сторону по обеим осям сразу:
// запас по PF больше (1.916 и 1.642 против 1.575 и 1.545) и устойчивость выше (2 из 4 на обеих
// ключевых темах против 1 и 0). Тикер принят по правилу владельца, объявленному ДО прогонов:
// литерал ставится и при непройденной планке, если принятая точка не упирается в стоп-условие
// плана — стоп-условие проверено ниже и НЕ сработало ни по одному из трёх пунктов.
//
// ПРИНЯТАЯ ТОЧКА (data/params/rsi_pullback/ydex/plateau_point.json): pooled OOS PF 3.014 на 77
// сделках (62 выигрышных / 15 проигрышных, win rate 80.52%, gross profit/loss 38829.50/12881.98,
// expectancy 336.98, Sortino 0.753, compounded 28.32%). Фолды (in-sample PF -> OOS PF / OOS сделок
// / OOS NetPnL% / OOS MaxDD%): #1 2.486->2.915/17/+6.72%/1.47%, #2 4.292->1.849/20/+3.61%/2.70%,
// #3 2.371->4.920/26/+11.96%/1.09%, #4 2.766->2.765/14/+3.66%/1.27%. ВСЕ ЧЕТЫРЕ ФОЛДА ПРИБЫЛЬНЫЕ и
// все четыре выше 1.5. Вырожденных фолдов нет: OOS MaxDD ненулевой во всех четырёх (1.09%-2.70%).
// Переобучения втрое ни один фолд не показывает: наибольший разрыв in-sample -> OOS у фолда 2
// (x2.32), фолды 1 и 3 дают OOS выше in-sample, фолд 4 совпадает с точностью до 0.001. На полной
// 25-месячной истории та же точка даёт 110 сделок (87/23, win rate 79.09%), PF 2.866,
// net +38672.27 (+38.67%), максимальную просадку 4030.54 (3.41%), expectancy 351.57, exposure
// 2.56%, CAGR 16.98%; выходы RSI 90 (81.8%) / SL 11 (10.0%) / TP 9 (8.2%).
//
// ГРАНИЦА ПРИЁМА: для фиксированной точки walk-forward — НЕ out-of-sample в строгом смысле: фолды
// честно раскатывают точку по времени, но саму точку собрал человек, видевший всю 25-месячную
// историю, поэтому pooled OOS PF 3.014 нельзя читать как проверку протокола — её числа нельзя
// сравнивать с pooled OOS тем, где отбор шёл только по обучающему окну. Вердикт протокола дают
// темы entry и trend (см. ВЕРДИКТ ПО ПЛАНКЕ выше), и он отрицательный. В отличие от BSPB, второй
// оговорки здесь НЕТ: процедура YDEX каноническая — все десять тем прогонялись поверх дефолтов
// ядра, промежуточного якоря не было.
//
// ОПОРНОЕ СРАВНЕНИЕ С BASELINE, И ОНО НЕ ЛЬСТИТ ТОЧКЕ. Дефолты ядра core.DefaultParams() на том же
// окне: полная история — 108 сделок, PF 1.778, net 28302.07; walk-forward тем же протоколом даёт
// pooled OOS PF 2.471 на 70 сделках (фолды 2.570/13, 2.216/18, 4.551/26, 1.178/13). Точка поднимает
// pooled OOS PF с 2.471 до 3.014 (+22%) и добавляет 7 сделок к пулу, а compounded return почти не
// двигает (27.72% -> 28.32%): три степени свободы куплены не за скачок доходности, а за РОВНОСТЬ
// фолдов — худший фолд baseline даёт OOS PF 1.178, худший фолд точки 1.849. Прирост скромный.
//
// СТОП-УСЛОВИЕ ПЛАНА, три пункта, все проверены числами, НИ ОДИН НЕ СРАБОТАЛ. (1) pooled OOS PF
// 3.014 против порога 1.0 — запас 3.0x. (2) 77 сделок в OOS-пуле (110 на полной истории) против
// порога 20 — запас 3.85x. (3) Под удвоенными издержками (-commission 0.001, круг 0.2%) pooled OOS
// PF 2.167 на тех же 77 сделках (фолды 2.258/17, 1.265/20, 3.460/26, 1.914/14 — все четыре
// по-прежнему выше единицы). Потеря PF от удвоения издержек 28.1% (3.014 -> 2.167) — ХУЖЕ каталога
// (DIAS 19.7%, ELFV 18.1%, BSPB 21.7%): точка ЧУВСТВИТЕЛЬНЕЕ к издержкам, чем дефолты ядра того же
// тикера (20.6% потери), причём не из-за частоты торговли — точка делает 110 сделок против 108 у
// дефолтов при expectancy 351.57 против 262.06, то есть торгует не чаще и зарабатывает на сделку
// больше. Причина повышенной чувствительности задачей не установлена. Реальный круг издержек на
// YDEX ≈ 0.125% (шаг цены 0.5 ₽ при медианной цене 4081 ₽ даёт два тика 0.0246% сверх
// моделируемых 0.1%); удвоение до 0.2% добавляет 0.1% — вчетверо больше неучтённой моделью
// надбавки 0.025%, то есть проверка заведомо строже реальности, но не «вдесятеро», как называл её
// бриф плана.
//
// ЗАМЕР ПЛАТО СОСЕДЯМИ (reports/YDEX_point_nb/, три ведущие оси, каждый сосед прогнан ТОЧЕЧНО на
// полной истории, поэтому числа сравнимы с полноисторичным PF точки 2.866, но не с pooled OOS
// 3.014): точка -> 2.866/110; RSILower 20 -> 2.139/86; RSILower 30 -> 1.826/116; SpentDayATR
// 0.8 -> 2.050/140; SpentDayATR 1.0 -> 4.079/79; TPDailyATR 0.5 -> 2.835/111; TPDailyATR
// 0.8 -> 2.729/109. По оси ЦЕЛИ точка на ПЛАТО (оба соседа в пределах 4.8% при неизменной
// выборке). По оси ВХОДА точка на ПИКЕ, и это риск, записанный прямо, а не скрытый: оба соседа
// падают на 25-36% PF — RSILower=25 вершина, а не край склона, и это ровно та ось, что провалила
// устойчивость планки. По оси ДНЯ точка на СКЛОНЕ: смягчение почти не меняет net, ужесточение
// поднимает PF ценой выборки. Один шаг сетки по RSILower в любую сторону стоит четверть-треть PF —
// самая хрупкая ось точки, живой раннер обязан её воспроизводить бит в бит.
//
// РАЗБИВКА ПО ПОЛУГОДИЯМ (полная 25-месячная история, 110 сделок, net 38672.27; сделка отнесена к
// полугодию по дате выхода): 2024-07-25…2025-01-23 -> 8.6% (20 сделок); 2025-01-23…2025-07-24 ->
// 38.1% (28); 2025-07-24…2026-01-22 -> 24.4% (34); 2026-01-22…2026-07-23 -> 22.3% (25);
// 2026-07-23…2026-08-26 (неполное) -> 6.4% (3). НИ ОДНО полугодие не даёт больше половины net —
// максимум 38.1%, далеко от прецедента IVAT (85% результата за одну неделю июля). Все пять
// полугодий прибыльные. Два растущих полугодия бумаги дают вместе 62.5% net точки — БОЛЬШЕ
// половины результата приходится на растущий режим, и это записывается прямо, — но три падающих
// полугодия дают оставшиеся 37.3% и тоже все прибыльны, включая окно, где бумага упала на 22.7%, а
// точка заработала 22.3% своего net. Стратегия зарабатывает в обоих режимах, в растущем — больше.
//
// СОМНЕНИЯ, записанные честно. (1) Планка не взята по устойчивости обеими ключевыми темами:
// RSILower и EMASlow набрали по 2 фолда из 4 — точка это чинит формально, фиксируя значения, но не
// показывает, что следующее окно выберет те же. (2) Точка стоит на пике по ведущей оси входа: шаг
// сетки по RSILower в любую сторону стоит 25-36% PF — самая хрупкая из трёх осей отличия от
// дефолтов ровно та, что провалила устойчивость. (3) Прирост над baseline скромный: pooled OOS PF
// 3.014 против 2.471 (+22%) при почти том же compounded return (28.32% против 27.72%). (4)
// Чувствительность к издержкам выше, чем у baseline того же тикера (28.1% против 20.6%) и выше,
// чем у DIAS, ELFV и BSPB — причина не установлена. (5) Режимная зависимость: 62.5% net приходится
// на два растущих полугодия из пяти при падении бумаги за окно на 13.7%. (6) RSIPeriod=3 —
// сознательное отступление от каталожного правила «тройка — дыхание цены», удержанное замером
// сделками, хотя лучший по OOS фолд темы entry выбрал шестёрку. (7) Объёмный гейт выключен при
// расколотой оси множителя (VolMult по фолдам 2.0, 2.0, 1.5, 1.5 — моды нет): решение держится на
// net (все двадцать лучших по PF строк решётки отдают деньги относительно точки), а не на том, что
// гейт вредит по PF — walk-forward включённого гейта не прогонялся, вопрос открыт для будущей
// перекалибровки.
//
// Сетки калибровки лежат в data/params/rsi_pullback/ydex/, результаты каждой темы — в _comment её
// файла, принятая точка и все её замеры — в plateau_point.json.
//
// ОКНО ИСКЛЮЧАЕТ ОСТАНОВКУ ТОРГОВ. Торги YNDX (Yandex N.V.) остановлены 2024-06-14, торги YDEX
// (МКПАО «Яндекс») начались 2024-07-24: в получасовой серии это дыра 40 дней с прыжком цены
// 4007 -> 4542. Расчётное окно — 2024-07-25 … 2026-08-25 (25.0 месяца, 27 991 бар, из них 18 864
// будних), то есть вся история нынешней бумаги и ничего до неё. Половина прежнего окна
// принадлежала бумаге с иностранной пропиской и другим режимом ценообразования — она выброшена
// целиком, а не взвешена.
//
// СХЕМА ПРОГОНОВ АДАПТИРОВАННАЯ: -months 25 -train-months 9 -test-months 4 -min-trades 20
// -metric profit_factor, четыре фолда встык (9 + 4x4 = 25). Прецедент — IVAT (25/9/4) и DIAS
// (30/10/5). Числа YDEX сопоставимы по схеме только с IVAT; с 36-месячным каталогом — лишь
// качественно. Пофолдовая устойчивость при этом остаётся измеримой, ради чего схема и выбрана.
//
// ЗАПАС ИСТОРИИ НУЛЕВОЙ: первый бар кэша совпадает с левой границей расчётного окна. -refresh во
// время калибровки НЕ запускать — он сдвинет обе границы.
//
// АПРИОР, записанный ДО прогонов. Скринер (pullback_screen_Minutes30_20260804_232456.md, строка 14
// из 99 прошедших вселенную): оборот 2640 млн ₽, дневной ATR 3.04%, TradesMed 42, PFmed 1.55,
// Capped 0/24, SilentCfg 0/24, плато 62%, PFmed HO 1.76 на 8 сделках. Контрольный прогон дефолтов
// ядра на расчётных 25 месяцах: 108 сделок, PF 1.778, net +28 302 ₽ — САМЫЙ СИЛЬНЫЙ baseline
// каталога (BSPB 1.114, IVAT 1.432). Веса априору не придаётся: вопрос «предсказывают ли колонки
// скринера исход протокола» каталог закрыл четырежды подряд (SIBN, ELFV, DIAS, BSPB) — не
// предсказывают ни снизу, ни сверху.
//
// ПРОЦЕДУРА ТЕМ КАНОНИЧЕСКАЯ. Дефолты ядра стоят ВНУТРИ рабочей зоны, поэтому все десять тем идут
// поверх них, якоря нет, и вердикт сравним с каталогом по построению. Это противоположность BSPB,
// где дефолты стояли почти в мёртвой зоне и темы пришлось делить на ранние и поздние.
//
// ЧТО ЗНАЕМ ОБ ИНСТРУМЕНТЕ ДО ПРОГОНОВ (замеры на расчётном окне):
//
//   - Режим СБАЛАНСИРОВАННЫЙ: два растущих полугодия из пяти (+8.1% и +8.5%), итог окна −13.4%,
//     максимальная просадка −36.2% — самая мягкая в каталоге. Часть лонгового результата
//     принадлежит режиму, поэтому разбивка точки по полугодиям обязательна.
//   - Шаг цены 0.5 ₽ при медианной цене 4081 ₽ = 0.0123%. Реальный круг издержек 0.125% против
//     моделируемых 0.1%. Baseline держит утроенный круг: PF 1.778 -> 1.411 (круг 0.2%) -> 1.098
//     (0.3%) — противоположность BSPB, где удвоение уводило дефолты в убыток.
//   - Ликвидность ВНЕ СРАВНЕНИЯ с каталогом: медиана оборота 2826 млн ₽/день, p10 1500 млн
//     (прежний рекорд — BSPB с 333 млн). Дней короче 20 баров — 0.2% (1 из 542). Исполнительный
//     риск, записанный у ELFV, DIAS и LENT, снят полностью.
//   - Корпоративных гэпов почти нет: за 25 месяцев ОДИН гэп хуже −3% (2024-08-05, −3.30%) и один
//     лучше +3%. Дивидендный риск BSPB здесь не является ведущим. Обратная сторона: бумага моложе
//     двух лет, структурных событий история почти не содержит.
//   - Дневной ATR(14) 2.84% медианой (выше BSPB 2.53%, ниже IVAT 4.37%). День проходит своё ATR
//     быстро: медиана размаха дня к бару 0.62 ATR против 0.34 у BSPB.
//   - Edge усиливается в двух направлениях: быстрый RSI на среднем уровне (RSI(3)@25 — 140 сделок
//     при PF 2.050) и исчерпанный день (SpentDayATR 1.0 — 58 сделок при 3.256). Обе зоны тоньше
//     дефолтной по выборке, и это главный риск калибровки.
