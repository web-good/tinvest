// гейта, а на принятой зоне риска максимум оси переезжает на 70; StopDailyATR = 0.7 против моды
// темы risk (1.3 в двух фолдах), потому что широкий стоп покупает PF вытеснением убытка в
// RSI-выход; VolBaseDays = 14 вопреки теме volume, не выбравшей эту базу ни разу (5/5/3/3), потому
// что поверх точки она даёт pooled 2.863 против 2.321 у базы 10 и 1.882 у базы 5. ГРАНИЦА ПРИЁМА:
// для фиксированной точки это НЕ out-of-sample — точку собрал человек, видевший всю историю,
// поэтому 2.863 нельзя читать как проверку протокола; вердикт протокола дают тематические файлы, и
// он отрицательный. Разбор каждого поля — в доке пакета (elfv.go).
