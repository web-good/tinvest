// Стоп — единственное, что ограничивает убыток: RSI-выход закрывает и в плюс, и в минус. Ширина
// 0.7 выбрана ПРОТИВ моды темы risk (1.3 в двух фолдах из четырёх), потому что на ELFV капкан
// вытеснения убытка в RSI-выход выражен резче, чем на большинстве предшественников. Точечная ось
// на дефолтной базе с целью 0.6: 0.5 -> 181 сделка, PF 1.546, стоп-выходов 23.2%, MaxDD 7.47%;
// 0.7 -> 177, PF 1.894, 12.4%, 9.56%; 1.0 -> 174, PF 2.142, 5.7%, 11.53%; 1.3 -> 174, PF 2.225,
// 3.4%, 13.92%. Счёт сделок на всей оси не меняется (181 -> 174), число TP-выходов постоянно
// (ровно 29 во всех четырёх точках), а доля стоп-выходов падает всемеро — убыточные сделки не
// исчезают, они перестают закрываться стопом и закрываются позже по RSI, и просадка за это растёт
// почти вдвое. 0.7 — самое широкое значение, при котором стоп ещё реально работает: на принятой
// точке им закрывается 12.3% сделок 24-месячного OOS-окна. Опорный замер выживаемости ELFV (доля
// будних дней, чей размах достаёт уровня): 0.5 ATR — 88.5%, 0.7 — 66.4%, 1.0 — 36.3%, 1.3 — 20.2%.
// При медианном дневном ATR 2.98% цены стоп 0.7 ATR — это 2.08% цены.
func TestStopIsArmed(t *testing.T) {
	if p := DefaultParams(); p.StopDailyATR <= 0 {
		t.Fatalf("StopDailyATR = %v, want > 0", p.StopDailyATR)
	}
}

// Специфичный для ELFV инвариант: шаг цены 0.0002 равен 0.039% медианной цены 0.5134, бэктест
// наливает по закрытию бара и спред не моделирует, поэтому реальный круг издержек ближе к 0.2%,
// чем к моделируемым 0.1%. На стопе 0.5 ATR (1.49% цены) это 13.4% риска, на 0.3 ATR (0.89%) —
// 22.4%, и по этой причине строка 0.3 вырезана из cal_risk.json (второй такой случай в каталоге
// после domrf/). Литерал не имеет права оказаться уже 0.5 через правку руками: замер
// чувствительности принятой точки — pooled OOS PF 2.863 при круге 0.1% и 2.346 при 0.2%.
func TestStopStaysWideEnoughForTheSpread(t *testing.T) {
	if p := DefaultParams(); p.StopDailyATR < 0.5 {
		t.Fatalf("StopDailyATR = %v: при шаге цены 0.0002 более узкий стоп отдаёт издержкам больше 13%% риска", p.StopDailyATR)
	}
}

// RSI-выход закрывает большинство сделок принятой точки: 53.8% против 33.8% по цели и 12.3% по
// стопу (24-месячное OOS-окно, 65 сделок). Полоса RSIUpper = 70 оставлена дефолтной ВОПРЕКИ теме
// exit (55/60/60/80, мода 2 из 4): тема мерила ось поверх дефолтного стопа 0.5 и выключенного
// объёмного гейта, и там максимум стоял на 60 (196 сделок, PF 1.749 против 1.546 у 70). На принятой
// зоне риска максимум переезжает на 70: 55 -> PF 2.362; 60 -> 2.566; 65 -> 2.309; 70 -> 2.661;
// 75 -> 2.439, а walk-forward соседей даёт 60 -> 2.425 и 65 -> 2.457 против 2.863 у точки. Второй
// довод именно для этого инструмента: полоса управляет характером сделки (от 55 к 80 медиана
// удержания растёт с 4 до 13 баров, доля сделок длиннее торгового дня — с 23.8% до 61.0%), а каждая
// сделка платит круг издержек, которого бэктест не видит; на низкой полосе удвоение издержек
// съедает больше пятой части PF (55: 1.680 -> 1.306; 60: 1.749 -> 1.384) против 16.7% у полосы 70.
// Живой раннер держит RSI-выход обязательным для всех тикеров реестра; на ELFV он выигрывает и по
// существу: ветка UseRSIExit=0 даёт PF 1.080-1.170 против 1.546 при 165-173 сделках, то есть
// проигрывает качеством, а не выбывает по -min-trades.
func TestRSIExitIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseRSIExit != 1 {
		t.Fatalf("UseRSIExit = %d, want 1 — ветка без RSI-выхода даёт PF 1.080-1.170 против 1.546", p.UseRSIExit)
	}
	if p.RSIUpper <= p.RSILower {
		t.Fatalf("полоса RSI вырождена: RSIUpper = %v, RSILower = %v", p.RSIUpper, p.RSILower)
	}
}

// Дневной гейт взведён на единственной ветке «день исчерпан». Ветка «день только начался»
// (FreshDayATR) держится на нуле: тема day открывала её в двух фолдах из четырёх, но на полной
// истории 0.4 хуже нуля (269 сделок PF 1.494 против 181 и 1.546), а прямое сравнение тем на одних
// и тех же фолдах стоит открытой ветке 0.103 pooled PF (day 1.641 на 128 сделках против day_spent
// 1.744 на 87). Сам гейт отсекает основную массу входов и этим держит качество: без него дефолтная
// конфигурация даёт 437 сделок при PF 1.120, с ним — 181 при 1.546. SpentDayATR = 0.9 выбран не по
// лучшему PF, а по ровности фолдов: с дефолтным 0.8 точка даёт pooled 2.545 на 83 сделках, но
// проваливает третий фолд (0.685), с 0.9 — 2.863 на 68 при минимуме фолда 1.250; дальнейшее
// ужесточение растит PF и убивает выборку (1.0 -> 3.243 на 59 сделках, 1.1 -> 3.394 на 51, в
// четвёртом фолде остаётся 6-7 сделок). Замер ветки на ELFV: порог 0.8 оставляет 40.7% будних
// баров, 0.9 — 32.5%, 1.0 — 26.0%, 1.25 — 15.4%.
func TestOnlySpentDayBranchIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseDayATRGate != 1 {
		t.Fatalf("UseDayATRGate = %d, want 1 — без гейта дефолт даёт 437 сделок при PF 1.120 против 181 при 1.546", p.UseDayATRGate)
	}
	if p.FreshDayATR != 0 {
		t.Fatalf("FreshDayATR = %v, want 0 — открытая ветка свежего дня стоит 0.103 pooled PF", p.FreshDayATR)
	}
	if p.SpentDayATR <= 0 {
		t.Fatalf("SpentDayATR = %v, want > 0 — иначе гейт взведён и не отсекает ничего", p.SpentDayATR)
	}
}

// Объёмный гейт ВКЛЮЧЁН, и на ELFV это самое обоснованное включение в каталоге: на полной истории
// ВСЕ 24 комбинации решётки VolBaseDays x VolMult дают PF выше baseline без гейта (1.546 на 181
// сделке) — прямая противоположность SIBN, где гейт был чистой потерей выборки. Множитель 2.0 —
// локальный максимум поверх принятой точки (walk-forward соседей: 1.5 -> 1.970 на 79 сделках,
// 2.5 -> 2.645 на 60 против 2.863 на 68). База 14 взята ВОПРЕКИ теме volume, не выбравшей её ни в
// одном фолде (5/5/3/3): поверх точки база 14 даёт 2.863 против 2.321 у базы 10 и 1.882 у базы 5.
// Окно VolLookbackBars = 3 — дефолт ядра, ПОДТВЕРЖДЁННЫЙ замером: ELFV стал первым тикером
// каталога, где эта ось свипуется отдельной темой (cal_vol_window.json), и её максимум стоит ровно
// на дефолте — по решётке 5x3 окно 3 лучшее и по PF, и по expectancy, и по net (97 сделок,
// PF 2.003, expectancy 433.1 при множителе 2.0), тогда как широкое окно 8 набирает сделки с более
// низкой expectancy (129 сделок, 363.6), а узкое окно 1 при высоком множителе выбывает по
// -min-trades (55 сделок за 36 месяцев).
func TestVolumeGateIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.UseVolume != 1 {
		t.Fatalf("UseVolume = %d, want 1 — все 24 комбинации решётки гейта выше baseline без него", p.UseVolume)
	}
	if p.VolMult <= 0 || p.VolBaseDays <= 0 || p.VolLookbackBars <= 0 {
		t.Fatalf("объёмный гейт взведён (UseVolume=1), но его оси невзведены: VolMult=%v VolBaseDays=%d VolLookbackBars=%d",
			p.VolMult, p.VolBaseDays, p.VolLookbackBars)
	}
}

// Цель взведена и на принятой точке УЖЕ стопа (0.5 против 0.7) — та же асимметрия, что на WUSH,
// LENT, LSNGP и SIBN. Значение выбрано темой risk (0.5 в первом фолде) и подтверждено точечной
// кривой поверх принятой зоны риска: TPDailyATR 0.5 -> PF 3.030 на 81 сделке; 0.6 -> 2.661 на 79;
// 0.8 -> 2.275 на 76; 1.0 -> 2.198; 1.5 -> 2.173; 2.0 -> 2.090. Выше 0.8 кривая ложится в плато —
// цель почти перестаёт срабатывать и выход отдаётся RSI. В walk-forward 0.5 и 0.6 практически
// неразличимы (2.863 против 2.874 на 66 сделках), то есть ось здесь плоская, и выбор опирается на
// полную историю, а не на третий знак pooled. На принятой точке доля TP-выходов 33.8%.
func TestTargetIsArmed(t *testing.T) {
	p := DefaultParams()
	if p.TPDailyATR <= 0 {
		t.Fatalf("TPDailyATR = %v, want > 0", p.TPDailyATR)
	}
	if p.TPDailyATR >= p.StopDailyATR {
		t.Fatalf("на принятой точке цель уже стопа: TPDailyATR = %v, StopDailyATR = %v", p.TPDailyATR, p.StopDailyATR)
	}
}

// Трейл выключен: тема trail — худшая из десяти (pooled OOS PF 1.389 на 148 сделках), а точечная
// ось поверх живого RSI-выхода показывает, что трейл либо мешает, либо не существует.
// TrailDailyATR 0.5 -> 183 сделки PF 1.442 при 18.6% трейл-выходов; 0.7 -> 181 сделка PF 1.552 при
// 3.9% трейл-выходов — при опорной точке без трейла 181 сделка PF 1.546. То есть узкий трейл
// срезает продолжения, ради которых стратегия и держит позицию (медиана удержания принятой точки 7
// баров, 40.0% сделок длиннее одного торгового дня), а широкий совпадает с выключенным до третьего
// знака. TrailDailyATR обязан быть нулём при выключенном трейле, иначе выключенное поле несёт
// непроверенное значение, которое оживёт при первом же переключении флага.
func TestTrailStaysOff(t *testing.T) {
	p := DefaultParams()
	if p.UseTrail != 0 {
		t.Fatalf("UseTrail = %d, want 0 — любой рабочий уровень трейла на ELFV хуже выключенного", p.UseTrail)
	}
	if p.TrailDailyATR != 0 {
		t.Fatalf("TrailDailyATR = %v при выключенном трейле, want 0", p.TrailDailyATR)
	}
}
