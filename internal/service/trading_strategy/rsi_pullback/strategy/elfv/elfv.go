//   - ДЫРЫ В БАРАХ: медиана 34 бара в буднем дне, p10 = 19, у 147 дней из 778 (18.9%) баров
//     меньше двадцати. Отсутствующий бар — это не пропуск данных, а полчаса без единой сделки.
