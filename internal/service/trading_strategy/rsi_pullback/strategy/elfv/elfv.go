// литерал принятой точки; связь с baseline разорвана, снимок держит elfv_test.go.
//
// ВЕРДИКТ ПО ПЛАНКЕ — НЕ ВЗЯТА, и это записано пункт за пунктом. Планка требовала от ОБЕИХ
// ключевых тем pooled OOS PF >= 1.5 при >= 20 сделках И устойчивость ведущей оси >= 3 фолда из 4.
// Тема entry: pooled OOS PF 1.575 на 106 сделках — порог по PF взят; RSILower по фолдам 30, 20,
// 25, 35 — устойчивость 1 из 4, порог НЕ взят. Тема trend: pooled OOS PF 1.545 на 147 сделках —
// порог по PF взят с запасом в 0.045; EMASlow по фолдам 200, 120, 150, 50 — устойчивость 0 из 4,
// порог НЕ взят. То есть обе темы прошли по качеству и обе провалились по устойчивости: SVAV
// остаётся единственным тикером каталога, взявшим планку целиком. Тикер принят по правилу
// владельца от 2026-08-21, объявленному ДО прогонов, — литерал ставится и при непройденной планке,
// если принятая точка не упирается в стоп-условие (pooled OOS PF < 1.0 либо < 20 сделок за 36
// месяцев). Не упирается с запасом: 2.863 на 68 сделках.
//
// ЧЕМ ЗАКОНЧИЛСЯ САМЫЙ СИЛЬНЫЙ АПРИОР КАТАЛОГА. ELFV взяли в работу с baseline PF 1.546 на 181
// сделке и holdout-колонкой скринера 1.26 — лучшим априором изо всех кандидатов. Планку он не
// смягчил и не заменил: обе ключевые темы провалили устойчивость ровно так же, как на тикерах со
// слабым априором. Симметричный ответ на вопрос, заданный после SIBN (baseline 1.027): колонки
// скринера и контрольный baseline не предсказывают исход протокола НИ СНИЗУ, НИ СВЕРХУ, и тратить
// на них решение о запуске калибровки бессмысленно. Что априор всё-таки дал — принятая точка,
// собранная человеком: 2.863 pooled на четырёх прибыльных фолдах против 2.258 у SIBN.
//
// РЕЗУЛЬТАТ ДЕСЯТИ ТЕМ (pooled OOS PF / сделок): vol_window 2.146/93, risk 1.792/144,
// day_spent 1.744/87, day 1.641/128, volume 1.632/83, entry 1.575/106, exit 1.557/158,
// trend 1.545/147, screen 1.463/132, trail 1.389/148. Все десять выше 1.38, ни одной провальной —
// но ни одна ось не устойчива больше чем на 2 фолда из 4.
//
// ПРИНЯТАЯ ТОЧКА (data/params/rsi_pullback/elfv/plateau_point.json): pooled OOS PF 2.863 на 68
// сделках, win rate 77.94%, expectancy 568.46, Sortino 0.660, compounded +41.60%; фолды
// 4.709(31)/1.884(15)/1.884(11)/1.250(11) — все четыре прибыльные, включая заранее объявленный
// тяжёлым четвёртый (полугодие −30.5%), ни один не вырожден, максимальная просадка фолда 4.84%.
// На полной 36-месячной истории та же точка даёт 81 сделку, PF 3.030, net +50 738, MaxDD 4.24%.
// ГРАНИЦА ПРИЁМА: для фиксированной точки это НЕ out-of-sample — её собрал человек, видевший всю
// историю, поэтому 2.863 нельзя читать как проверку протокола; вердикт протокола дают темы, и он
// отрицательный.
//
// РАЗБОР ПОЛЕЙ ЛИТЕРАЛА. От core.DefaultParams() он отличается пятью полями — SpentDayATR
// 0.8->0.9, StopDailyATR 0.5->0.7, TPDailyATR 0.6->0.5, UseVolume 0->1, VolMult 1.2->2.0.
//
//   - RSIPeriod = 4, RSILower = 30 — дефолты ядра, подтверждённые точечным свипом поверх точки:
//     30 даёт PF 2.566, соседи 25 и 35 — 1.803 и 1.784, период 5 — 2.124, период 6 — 1.588. Тема
//     entry устойчивости не дала, поэтому выбор сделан свипом, а не её лидербордом. Суженный край
//     оси периода (7) темой не выбран ни в одном фолде — решение обрезать ось на 7 не проверялось
//     и не потребовалось.
//   - RSIUpper = 70 — против темы exit (55/60/60/80). Тема мерила ось поверх дефолтного стопа 0.5
//     и выключенного объёмного гейта, там максимум стоял на 60; на принятой зоне риска максимум
//     переезжает на 70 (2.661 против 2.566), а walk-forward соседей даёт 60 -> 2.425, 65 -> 2.457.
//   - EMAFast = 10, EMASlow = 100 — дефолты ядра. Тема trend показала, что фильтр направления на
//     этом инструменте пары не различает вовсе: точечные PF 1.529 / 1.546 / 1.550 на краях и в
//     центре оси при baseline 1.546, размах 0.021. Отсюда и устойчивость 0 из 4 — калибратору
//     нечего выбирать.
//   - UseDayATRGate = 1, FreshDayATR = 0, SpentDayATR = 0.9. Гейт обязателен: без него дефолтная
//     конфигурация даёт 437 сделок при PF 1.120 против 181 при 1.546. Ветка свежего дня выключена
//     — прямое сравнение тем day (1.641/128) и day_spent (1.744/87) стоит ей 0.103 pooled PF.
//     Уровень 0.9 выбран по ровности фолдов, а не по лучшему PF: с 0.8 точка даёт 2.545 на 83
//     сделках, но проваливает третий фолд (0.685); ужесточение до 1.0 и 1.1 растит pooled до 3.243
//     и 3.394, оставляя в четвёртом фолде 6-7 сделок.
//   - StopDailyATR = 0.7 — против моды темы risk (1.3 в двух фолдах). Капкан вытеснения убытка в
//     RSI-выход подтверждён числом: по оси 0.5/0.7/1.0/1.3 счёт сделок не меняется (181/177/174/174),
//     число TP-выходов постоянно (29), доля стоп-выходов падает 23.2 -> 3.4%, а MaxDD растёт
//     7.47 -> 13.92%. 0.7 — самое широкое значение, при котором стоп ещё работает.
//   - TPDailyATR = 0.5 — точечная кривая поверх принятой зоны риска: 0.5 -> 3.030, 0.6 -> 2.661,
//     0.8 -> 2.275, дальше плато. В walk-forward 0.5 и 0.6 неразличимы (2.863 против 2.874).
//   - UseVolume = 1, VolMult = 2.0, VolBaseDays = 14, VolLookbackBars = 3. Гейт включён с самым
//     сильным основанием в каталоге: все 24 комбинации решётки базы и множителя дают PF выше
//     baseline без гейта. База 14 — против темы volume, не выбравшей её ни разу (5/5/3/3): поверх
//     точки она даёт 2.863 против 2.321 у базы 10 и 1.882 у базы 5.
//   - UseRSIExit = 1 — ветка без RSI-выхода проигрывает качеством, а не выбывает по -min-trades:
//     165-173 сделки (55-58 на обучающее окно) при PF 1.080-1.170 против 1.546.
//   - UseTrail = 0, TrailDailyATR = 0 — трейл 0.5 роняет PF до 1.442, трейл 0.7 срабатывает в 3.9%
//     выходов и совпадает с выключенным.
//
// ЧТО ДАЛА ДЕСЯТАЯ ТЕМА (cal_vol_window.json — первый в каталоге свип VolLookbackBars). Ось ЖИВАЯ:
// по решётке 5x3 PF гуляет 1.394-2.003, счёт сделок 55-148, то есть окно меняет результат сильнее,
// чем пара EMA в теме trend. Но её МАКСИМУМ СТОИТ РОВНО НА ДЕФОЛТЕ ЯДРА: окно 3 лучшее и по PF, и
// по expectancy (433.1), и по net (+42 013). Широкое окно 8 набирает сделки с более низкой
// expectancy (129 сделок, 363.6) — то есть добирает, а не отбирает; узкое окно 1 при множителе 2.5
// выбывает по -min-trades (55 сделок за 36 месяцев). ВЫВОД ДЛЯ КАТАЛОГА: заводить эту тему на
// следующих тикерах не нужно — дефолт 3 подтверждён замером, а не принят по умолчанию. Проверять
// ось имеет смысл только там, где дневное покрытие баров рвано так же, как на ELFV (18.9% будних
// дней несут меньше двадцати баров), и только точечными прогонами: walk-forward выбрал здесь окно
// хуже дефолта в двух фолдах из четырёх (8 и 1).
//
// ЗАМЕРЫ ИНСТРУМЕНТА, снятые до прогонов и не устаревающие от них (кэш 2026-08-21, 31 362 30-минутных бара, расчётное
// окно 36.0 месяца с 2023-08-21 — 31 141 бар, 23 714 будних):
//
//   - АПРИОР САМЫЙ СИЛЬНЫЙ ИЗ ВСЕХ КАНДИДАТОВ КАТАЛОГА, и это записано ДО прогонов. Скринер:
//     PFmed 1.62, плато 75%, PFmed HO 1.26 на 7 сделках. Контрольный прогон baseline на 36
//     месяцах: 181 сделка, PF 1.546, net +52 544. Для сравнения, у SIBN было 1.027 на 129
//     сделках. Вес обоих фактов ограничен: колонка PFmed HO в этом каталоге предсказывает плохо
//     в обе стороны (WUSH с 4.24 планку провалил, LSNGP с 0.99 вытянул все девять тем выше 1.5),
//     а baseline считается на полной истории без walk-forward — он показывает лишь, что дефолты
//     ядра стоят не в мёртвой зоне (прецедент NVTK). Планку сильный априор не смягчает.
//   - ЦЕНА КОПЕЕЧНАЯ, ШАГ 0.0002. В окне цена прошла 0.6698 -> 0.3390 при медиане 0.5134, и все
//     котировки кратны 0.0002 — то есть шаг равен 0.039% цены. Бэктест наливает по закрытию бара
//     и НЕ моделирует спред, поэтому реальный круг издержек ближе к 0.2%, чем к моделируемым
//     0.1%. Замер чувствительности (точка VolMult 2.0, 97 сделок): круг 0.1% -> PF 2.003,
//     0.2% -> 1.668, 0.3% -> 1.381. Живой результат будет ниже бэктестового на величину, которую
//     бэктест не показывает. Косвенный признак той же гранулярности: 3.4% будних баров имеют
//     нулевой размах (High == Low).
//   - ЛИКВИДНОСТЬ ХУДШАЯ В КАТАЛОГЕ: оборот медианой 25.1 млн ₽/день при p10 = 6.4 млн (LENT 38,
//     IVAT 43, SVAV 68, SIBN 519). Гейт отбора скринера в 50 млн ELFV проходит ТОЛЬКО средним
//     (70.2 млн), вытянутым толстым правым хвостом: p90 равен 159.8 млн, вшестеро выше медианы.
//   - ДЫРЫ В БАРАХ: медиана 34 бара в буднем дне, p10 = 19, у 147 дней из 778 (18.9%) баров
//     меньше двадцати. Отсутствующий бар — это не пропуск данных, а полчаса без единой сделки.
//     Прямое следствие: ручка VolLookbackBars, задающая окно «последние N будних баров», меряет
//     на этой бумаге не только время, но и ликвидность. Под неё заведена десятая тема каталога
//     cal_vol_window.json — первая в каталоге, свипующая эту ось.
//   - ДИВИДЕНДНЫХ ГЭПОВ ПРАКТИЧЕСКИ НЕТ. За 36 месяцев ровно один гэп хуже −3% (2024-09-03,
//     −3.00%, это −0.95 дневного ATR); глубже 0.5 ATR открывается 5 дней из 764 (0.7%). ЭЛ5-Энерго
//     не платит дивиденды с 2020 года, и данные это подтверждают. Главный незакрываемый риск SIBN
//     (пять гэпов хуже −3%, худший −4.69 ATR) на этом инструменте отсутствует.
//   - ТРЕНДОВЫЙ ДОПУСК ПОЧТИ НЕ ЗАВИСИТ ОТ ПАРЫ: доля баров с EMAFast > EMASlow укладывается в
//     44.0-46.5% на всех 35 парах сетки, размах 2.5 процентных пункта. Тот же случай, что на SVAV
//     (42.4-43.6%) и SIBN (45.1-46.3%), и не такой, как на IVAT (29.4-36.0% с монотонной
//     зависимостью). Практическое следствие: выбор пары меняет не объём допуска, а то, какие
//     именно бары в него попадают, поэтому дефицит выборки из-за медленной пары здесь невозможен,
//     а разница PF между парами — это качество фильтра, а не размер выборки.
//   - РЕЖИМ САМЫЙ ЖЁСТКИЙ В КАТАЛОГЕ: всё окно −49.5%, пик-минимум −65.9%, первые 30 месяцев
//     −24.9%, холдаут −32.5%. Полугодия +2.3% / −14.1% / +0.6% / −9.8% / −4.9% / −30.5%. Это
//     одновременно достоинство — завысить лонговый результат режимом здесь нечем — и риск:
//     четвёртый OOS-фолд заведомо тяжёлый, и если планка не возьмётся именно там, отделить
//     «стратегия не работает» от «полугодие было −30.5%» на четырёх фолдах нельзя.
//   - ИСТОРИИ 36.0 МЕСЯЦА С ЗАПАСОМ В 14 ДНЕЙ, поэтому штатный протокол §8
//     docs/rsi_pullback/strategy.md (-months 36 -train-months 12 -test-months 6) исполним, и
//     числа ELFV сопоставимы построчно с остальным каталогом — в отличие от ivat (26 мес) и
//     domrf (8.8 мес).
//
// Сетки калибровки лежат в data/params/rsi_pullback/elfv/, их оси прибиты
// internal/service/backtest/rsi_pullback_elfv_grid_test.go, результаты каждой темы — в _comment
