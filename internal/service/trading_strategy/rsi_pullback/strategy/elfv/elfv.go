//     PFmed 1.62, плато 75%, PFmed HO 1.26 на 7 сделках. Контрольный прогон baseline на 36
//     месяцах: 181 сделка, PF 1.546, net +52 544. Для сравнения, у SIBN было 1.027 на 129
