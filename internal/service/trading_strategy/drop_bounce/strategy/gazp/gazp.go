//   - Серия выключена (DropSeries 0): одиночный бар на 36 мес — PF 1.060/101.
//   - MinTargetPct 0.5 — главный рычаг: 101 → 61 сделка, PF 1.15–1.27 при любом стопе. Порог 0.4
//     ничего не отсекает (все цели ≥ 0.45%), 0.6 оставляет 18 сделок — шум.
