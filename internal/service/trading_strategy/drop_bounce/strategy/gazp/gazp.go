//   - Точка: 73 сделки, PF 1.282, net +3.9%, win rate 57.5%, просадка 3.7 тыс.; без комиссии
//     PF 2.037, +11.7%.
//   - Walk-forward: pooled OOS PF 1.047 на 65 сделках, фолды 1.384 / 0.550 / 0.629 / 2.743.
//     Как и на 5m, края вне выборки почти нет — литерал отправной, не одобрение для торговли.
