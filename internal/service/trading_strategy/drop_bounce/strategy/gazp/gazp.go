//     1.245 / 0.292 / 4.014 / 5.008. Фолд 2025-04…2025-10 убыточен, MinTargetPct и StopBody гуляют
//     между фолдами. Литерал — лучшая in-sample точка, устойчивость не подтверждена.
//
// # Подтверждение входа (2026-10-09)
//
// ConfirmBar 1 (вход после зелёной свечи, закрывшейся выше close падения) проверен сеткой
