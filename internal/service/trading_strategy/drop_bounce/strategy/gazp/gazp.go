//
// # 15 минут (2026-10-09)
//
// Литерал 5m на 15m-барах убыточен: 107 сделок, PF 0.821. Сетка
// data/params/drop_bounce/gazp/m15_grid.json (144 комбинации, 36 мес) поверх литерала 5m, затем
