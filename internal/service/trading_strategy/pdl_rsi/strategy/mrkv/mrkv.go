// (core.DefaultParams, стохастик %K(14,1), EMA 200): PF 1.295 на 75 сделках.
//
// Режим без стохастика (data/params/pdl_rsi/mrkv/cal_nostoch/), шаги:
//   - signal: RSI 6/30, PF 0.824/275, острый пик, точка остаётся;
//   - trend: EMA 170, PF 1.257/103 (выбор обязателен);
//   - floor: 0, точка остаётся (центр 22 — 1.309, ниже порога 5%);
//   - volume: 0.5, PF 1.041/58 — сдвинута по медиане окрестности, хотя PF самой точки ниже;
//   - room: 0, точка остаётся;
//   - risk: стоп 1 ATR, цель 2R, без потолка, PF 1.357/57;
//   - exits: RSIExit 65, лесенка 40/10/70, PF 1.455/62;
//   - signal2: RSI 6/25, PF 1.849/40;
//   - risk2: без изменений.
