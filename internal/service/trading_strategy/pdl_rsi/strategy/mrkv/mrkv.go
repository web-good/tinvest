// Точка спуска: RSI 6/25 — PF 1.849 на 40 сделках. Лучшая комбинация (шаг signal2) отличается
// только периодом RSI 8: PF 4.508 на 16 сделках, net +3762 ₽.
// Walk-forward (подбор 3 мес, проверка 1 мес): пул OOS PF 1.615 на 49 сделках, net +5528 ₽,
// compounded +5.53%; последние 12 фолдов PF 1.947 на 25 сделках, +4.58% — ГОДЕН. Выборы фолдов:
// HourRSIPeriod 6 ×28 / 8 ×5 (последний 6), RSIArm 30 ×17 / 25 ×16 (последний 25),
// StopATR 0.7 ×21 / 1 ×12 (последний 1), TargetR 1.5 ×29 / 2 ×3 / 3 ×1 (последний 1.5).
//
// Режим со стохастиком (cal/): signal 6/30 (0.860/275, острый пик), trigger %K(14,1) остаётся,
// trend EMA 100 (1.648/61), floor/volume/room выключены, risk стоп 1 ATR / цель 3R / потолок 1.5%
// (1.681/62), exits RSIExit 70 без лесенки, signal2 RSI 8/30 (2.169/27), trigger2 %K(10,1)
// (2.375/26), risk2 без изменений. Лучшая комбинация — %K(9,1), PF 2.375 на 26 сделках.
// Walk-forward: пул OOS PF 1.056 на 58 сделках, последние 12 фолдов PF 1.169 +1.82% — НЕ ГОДЕН.
//
// В литерал — лучшая комбинация режима без стохастика (ГОДЕН против НЕ ГОДЕН). Финал на 36 мес:
// PF 4.508 на 16 сделках (база 1.295/75). За последние 12 мес PF 17.2 на 6 сделках: допуск в прод
// по правилу (PF > 1.2) — да, но выборка в 6 сделок мала. Владелец 2026-10-27 решил торговать:
// MRKV включён в PDL_RSI_TICKERS (env/prod.env).
package mrkv

import "tinvest/internal/service/trading_strategy/pdl_rsi/strategy/core"

// Params returns the SVCB literal.
func Params() core.Params {
	return core.Params{
		// Часовой RSI
		HourRSIPeriod: 8,  // длина часового RSI (Wilder); 0 — входов нет
		RSIArm:        25, // сигнал: час, на котором RSI ниже этого и стохастик проходит гейт (без стохастика — крест вниз)
		RSIFloor:      0,  // нет входа, если RSI часа сигнала ниже этого; 0 — выкл
		RSIExit:       65, // выход: часовой RSI пересёк это вниз (вышел из верхней зоны) — продажа по закрытию часа (выход RSI); 0 — выкл
		// Лесенка RSI: когда RSI позиции дошёл до ступени (от RSITrailFrom до RSITrailTo через RSITrailStep),
		// выход по close при кресте вниз уровня «ступень − RSITrailStep»; RSITrailFrom 0 — выкл
		RSITrailFrom: 40,
		RSITrailTo:   70,
		RSITrailStep: 10,

		// Стохастик: %K — сырой %K за StochK баров, сглаженный за StochSmooth, %D — среднее %K за StochD.
		// Гейт на том же часе, что и RSI ниже RSIArm, — никто никого не ждёт: %K ниже 20 (порог ядра);
		// %D идёт только в причину входа. StochK 0 — без стохастика
		StochK:      0,
		StochSmooth: 1,
		StochD:      3,

		// Объём: объём часа сигнала RSI (час основной сессии) > VolumeMult × среднего объёма VolBars
		// часов основной сессии перед ним; 0 — выключен
		VolumeMult: 0.5,
		VolBars:    20, // сколько часов основной сессии берётся в базу

		// Запас хода дня на часе входа: (лой дня + 1 ATR − close) / ATR ≥ MinRoomATR; 0 — выключен
		MinRoomATR: 0,

		// Стоп: столько дневных ATR ниже цены покупки; 0 — входов нет
		StopATR: 1,
		// Потолок стопа: не дальше этого процента от цены покупки, как бы ни был велик ATR; 0 — выключен
		MaxStopPct: 0,
		// Цель: столько стопов выше цены покупки; 0 — без цели
		TargetR: 2,

		// Тренд: close часа входа строго выше EMA этого периода по часовым закрытиям; 0 — выключен
		TrendEMA: 170,

		DailyATRPeriod: 14, // период дневного ATR (Wilder) по завершённым будним дневкам
	}
}
