//
// 36 мес, Hour1, -risk-pct 1, оба режима входа с открытого старта. База — дефолты ядра
// (стохастик %K(14,1), EMA 200, пол RSI 22): PF 1.002 на 89 сделках.
//
// Режим со стохастиком (data/params/pdl_rsi/moex/cal/) — ушёл в литерал, шаги:
//   - signal: RSI 6/30, PF 0.864/406, острый пик, точка остаётся;
//   - trigger: %K(14,1), точка остаётся, острый пик;
//   - trend: EMA 100, PF 1.022/77 (выбор обязателен);
//   - floor, volume, room: выключены, точка остаётся;
//   - risk: стоп 1 ATR, цель 2R, без потолка — PF 1.108/76, сдвинута, острый пик;
//   - exits: RSIExit 70, лесенка 60/15/70 — PF 1.188/77, сдвинута, острый пик;
//   - signal2: RSI 6/25 — PF 1.745/44, сдвинута;
//   - trigger2: %K(11,3) — PF 3.963/31, сдвинута;
//   - risk2: без изменений.
//
// Точка спуска: PF 3.963 на 31 сделке. Лучшая комбинация (шаг risk2) отличается только целью
// 1.5R: PF 4.037 на 31 сделке (11 за последние 12 мес), net +6408 ₽ — это литерал.
// Walk-forward (подбор 3 мес, проверка 1 мес, 33 фолда): пул OOS PF 1.600 на 42 сделках,
// net +4637 ₽, compounded +4.67%; последние 12 фолдов PF 1.670 на 20 сделках, +2.69% — ГОДЕН.
// Выборы фолдов: HourRSIPeriod 6 ×17 / 5 ×14 / 8 ×2 (последний 6), RSIArm 30 ×22 / 25 ×11
// (последний 30), StochK 10 ×27 / 11 ×6 (последний 10), StopATR 0.7 ×22 / 1 ×11 (последний 0.7),
// TargetR 1.5 ×32 / 2 ×1 (последний 1.5).
// Финал на 36 мес: PF 4.037 на 31 сделке (база 1.002 на 89). Последние 12 мес: PF 2.389 на
// 11 сделках — допуск в прод: да; включён в прод владельцем 2026-10-28.
//
// Режим без стохастика (cal_nostoch/): signal 8/25 (0.937/196, острый пик), trend EMA 200
// (1.643/30), floor/volume/room выключены, risk стоп 0.7 ATR / цель 3R / потолок 1% (2.217/31),
// exits RSIExit 70 без лесенки, второй проход без изменений (signal2 — острый пик). Лучшая
// комбинация — лесенка 50/20/70, PF 2.407 на 32 сделках. Walk-forward: пул OOS PF 0.856 на
// 67 сделках, −5.25%; последние 12 фолдов PF 0.752 на 26, −3.11% — НЕ ГОДЕН.
package moex

import "tinvest/internal/service/trading_strategy/pdl_rsi/strategy/core"

// Params returns the MOEX literal.
func Params() core.Params {
	return core.Params{
		// Часовой RSI
		HourRSIPeriod: 6,  // длина часового RSI (Wilder); 0 — входов нет
		RSIArm:        25, // сигнал: час, на котором RSI ниже этого и стохастик проходит гейт (без стохастика — крест вниз)
		RSIFloor:      0,  // нет входа, если RSI часа сигнала ниже этого; 0 — выкл
		RSIExit:       70, // выход: часовой RSI пересёк это вниз (вышел из верхней зоны) — продажа по закрытию часа (выход RSI); 0 — выкл
		// Лесенка RSI: когда RSI позиции дошёл до ступени (от RSITrailFrom до RSITrailTo через RSITrailStep),
		// выход по close при кресте вниз уровня «ступень − RSITrailStep»; RSITrailFrom 0 — выкл
		RSITrailFrom: 60,
		RSITrailTo:   70,
		RSITrailStep: 15,

		// Стохастик: %K — сырой %K за StochK баров, сглаженный за StochSmooth, %D — среднее %K за StochD.
		// Гейт на том же часе, что и RSI ниже RSIArm, — никто никого не ждёт: %K ниже 20 (порог ядра);
		// %D идёт только в причину входа. StochK 0 — без стохастика
		StochK:      11,
		StochSmooth: 3,
		StochD:      3,

		// Объём: объём часа сигнала RSI (час основной сессии) > VolumeMult × среднего объёма VolBars
		// часов основной сессии перед ним; 0 — выключен
		VolumeMult: 0,
		VolBars:    20, // сколько часов основной сессии берётся в базу

		// Запас хода дня на часе входа: (лой дня + 1 ATR − close) / ATR ≥ MinRoomATR; 0 — выключен
		MinRoomATR: 0,

		// Стоп: столько дневных ATR ниже цены покупки; 0 — входов нет
		StopATR: 1,
		// Потолок стопа: не дальше этого процента от цены покупки, как бы ни был велик ATR; 0 — выключен
		MaxStopPct: 0,
		// Цель: столько стопов выше цены покупки; 0 — без цели
		TargetR: 1.5,

		// Тренд: close часа входа строго выше EMA этого периода по часовым закрытиям; 0 — выключен
		TrendEMA: 100,

		DailyATRPeriod: 14, // период дневного ATR (Wilder) по завершённым будним дневкам
	}
}
