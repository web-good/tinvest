// # 2026-10-27 — пошаговая калибровка (скилл pdl-rsi-calibrate)
//
// 36 мес, Hour1, -risk-pct 1, оба режима входа с открытого старта. История HNFG начинается
// 2023-11-02 (IPO), окно короче 36 мес на несколько дней. База — дефолты ядра (core.DefaultParams,
// стохастик %K(14,1), EMA 200): PF 1.428 на 50 сделках.
//
// Режим со стохастиком (data/params/pdl_rsi/hnfg/cal/), шаги:
//   - signal: RSI 8/35, PF 0.881/307, острый пик, точка сдвинута;
//   - trigger: %K(14,1) остаётся (центр %K(9,3) 0.926 — ниже порога 5%), острый пик;
//   - trend: EMA 200, PF 1.385/51 (выбор обязателен);
//   - floor: 0, точка остаётся (центр 22 — 1.415, ниже порога 5%);
//   - volume: 0, точка остаётся;
//   - room: 0, точка остаётся;
//   - risk: стоп 0.3 ATR, цель 1.5R, потолок 1%, PF 2.505/62;
//   - exits: RSIExit 70, лесенка 40/15/70, PF 2.763/62;
//   - signal2: RSI 6/35, PF 1.870/102;
//   - trigger2: %K(14,1) остаётся (центр %K(10,1) 1.941 — ниже порога 5%);
//   - risk2: без изменений.
//
// Точка спуска: RSI 6/35 — PF 1.870 на 102 сделках. Лучшая комбинация (шаг exits) отличается
// только периодом RSI 8: PF 2.763 на 62 сделках, net +39945 ₽.
// Walk-forward (подбор 3 мес, проверка 1 мес): пул OOS PF 1.522 на 73 сделках, net +15693 ₽,
// compounded +16.42%; последние 12 фолдов PF 1.617 на 23 сделках, +6.44% (в плюсе 4 из 12) — ГОДЕН.
// Выборы фолдов: HourRSIPeriod 6 ×24 / 8 ×9 (последний 8), RSIArm 35 ×21 / 30 ×12 (последний 35),
// StochK 13 ×32 / 14 ×1 (последний 13), StopATR 0.3 ×27 / 0.5 ×6 (последний 0.3),
// TargetR 1.5 ×21 / 2 ×12 (последний 2).
//
// Режим без стохастика (cal_nostoch/): signal 8/35 (0.773/301, острый пик), trend EMA 170
// (1.463/58), floor/volume/room выключены, risk стоп 1 ATR / цель 3R / потолок 1.5% (1.545/58),
// exits RSIExit 70 без лесенки, signal2 RSI 6/25 (1.395/33), risk2 стоп 0.3 ATR / цель 3R /
// потолок 1% (1.544/33). Лучшая комбинация (шаг signal2) — RSI 5/25, стоп 1 ATR, цель 3R, потолок
// 1.5%, EMA 170: PF 1.829 на 56 сделках. Walk-forward: пул OOS PF 1.176 на 75 сделках, последние
// 12 фолдов PF 0.997 −0.10% — НЕ ГОДЕН.
//
// В литерал — лучшая комбинация режима со стохастиком (ГОДЕН против НЕ ГОДЕН). Финал на 36 мес:
// PF 2.763 на 62 сделках (база 1.428/50). За последние 12 мес PF 2.311 на 17 сделках: допуск
// в прод (PF > 1.2) — да. Включает владелец (PDL_RSI_TICKERS).
package hnfg

import "tinvest/internal/service/trading_strategy/pdl_rsi/strategy/core"

// Params returns the HNFG literal.
func Params() core.Params {
	return core.Params{
		// Часовой RSI
		HourRSIPeriod: 8,  // длина часового RSI (Wilder); 0 — входов нет
		RSIArm:        35, // сигнал: час, на котором RSI ниже этого и стохастик проходит гейт (без стохастика — крест вниз)
		RSIFloor:      0,  // нет входа, если RSI часа сигнала ниже этого; 0 — выкл
		RSIExit:       70, // выход: часовой RSI пересёк это вниз (вышел из верхней зоны) — продажа по закрытию часа (выход RSI); 0 — выкл
		// Лесенка RSI: когда RSI позиции дошёл до ступени (от RSITrailFrom до RSITrailTo через RSITrailStep),
		// выход по close при кресте вниз уровня «ступень − RSITrailStep»; RSITrailFrom 0 — выкл
		RSITrailFrom: 40,
		RSITrailTo:   70,
		RSITrailStep: 15,

		// Стохастик: %K — сырой %K за StochK баров, сглаженный за StochSmooth, %D — среднее %K за StochD.
		// Гейт на том же часе, что и RSI ниже RSIArm, — никто никого не ждёт: %K ниже 20 (порог ядра);
		// %D идёт только в причину входа. StochK 0 — без стохастика
		StochK:      14,
		StochSmooth: 1,
		StochD:      3,

		// Объём: объём часа сигнала RSI (час основной сессии) > VolumeMult × среднего объёма VolBars
		// часов основной сессии перед ним; 0 — выключен
		VolumeMult: 0,
		VolBars:    20, // сколько часов основной сессии берётся в базу

		// Запас хода дня на часе входа: (лой дня + 1 ATR − close) / ATR ≥ MinRoomATR; 0 — выключен
		MinRoomATR: 0,

		// Стоп: столько дневных ATR ниже цены покупки; 0 — входов нет
		StopATR: 0.3,
		// Потолок стопа: не дальше этого процента от цены покупки, как бы ни был велик ATR; 0 — выключен
		MaxStopPct: 1,
		// Цель: столько стопов выше цены покупки; 0 — без цели
		TargetR: 1.5,

		// Тренд: close часа входа строго выше EMA этого периода по часовым закрытиям; 0 — выключен
		TrendEMA: 200,

		DailyATRPeriod: 14, // период дневного ATR (Wilder) по завершённым будним дневкам
	}
}
