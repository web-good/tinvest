//   - signal: RSI 6/30, PF 0.789/372, острый пик, точка остаётся;
//   - trend: EMA 100, PF 1.299/91 (выбор обязателен);
//   - floor: 22, PF 1.386/84, сдвинута;
//   - volume: 0.5, PF 1.974/59, сдвинута;
