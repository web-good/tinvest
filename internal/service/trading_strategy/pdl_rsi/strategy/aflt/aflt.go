//
// В литерал — режим без стохастика (ГОДЕН против НЕ ГОДЕН). Финал на 36 мес: PF 2.511 на 60
// сделках (база 1.024/104). За последние 12 мес PF 2.736 на 17 сделках — допуск в прод: да.
