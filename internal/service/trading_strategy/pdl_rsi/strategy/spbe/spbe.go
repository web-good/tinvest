//   - trend: TrendEMA 200, PF 0.994, net -287, сделок 99 (33 за 12 мес), острый пик; выключенное
//     значение запрещено — выбран лучший центр;
//   - floor: RSIFloor 0, PF 0.994, net -287, сделок 99 (33 за 12 мес), острый пик; лучший центр
