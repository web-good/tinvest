// Числа скопированы с литерала NVTK владельца на эту дату (стохастик 10/3/3, окно 4 часа, крест ниже 40,
// RSI на кресте не выше 50, пол RSI 22, объём часа сигнала 0.5, стоп 0.5 дневного ATR с потолком 1% цены,
// цель 2R или крест RSI 70 вверх, EMA 150). Не калиброван; записан литералом, чтобы правка дефолтов ядра
// или литерала NVTK не меняла тикер молча.
//
// # 2026-10-24 — пошаговая калибровка (скилл pdl-rsi-calibrate)
//
// 36 мес, Hour1, -risk-pct 1. Покоординатный спуск по группам параметров от открытого старта (фильтры
// выключены), точка двигается к центру плато шага только при выигрыше медианы окрестности ≥ 5%:
// сигнал — RSI 4 / 35 (PF 1.058/351); триггер — без изменений (StochK 5, окно 4 часа, крест ниже 40);
// EMA и пол RSI — выключены; потолок RSI на кресте 50 (1.199/266, плато); объём 1.2 (1.470/98, плато);
// запас хода — выключен; стоп 1.0 ATR с потолком 1.5%, цель 1.5R (1.647/98, плато); выходы без изменений
// (RSI 70); второй проход: сигнал без изменений, крест ниже 50 (1.826/114, плато), стоп/цель без изменений.
// Острые пики только на первых шагах (сигнал, триггер, EMA). Литерал на тех же 36 мес: PF 0.656 на 24
// сделках. Скользящий walk-forward вокруг точки (3 мес подбор, 1 мес проверка, сетка
// data/params/pdl_rsi/mdmg/cal/wf_rolling.json): пул OOS PF 1.560 на 100 сделках, net +17201 ₽ — годен.
// Шаги и их результаты — data/params/pdl_rsi/mdmg/cal/.
package mdmg

import "tinvest/internal/service/trading_strategy/pdl_rsi/strategy/core"

// Params returns the MDMG literal.
func Params() core.Params {
	return core.Params{
		// Часовой RSI
		HourRSIPeriod: 4,  // длина часового RSI (Wilder); 0 — входов нет
		RSIArm:        35, // сигнал RSI: час, на котором RSI пересёк это сверху вниз (предыдущий час той же даты не ниже)
		RSIFloor:      0,  // нет входа, если RSI опускался ниже этого от часа сигнала до креста стохастика; 0 — выкл
		RSITriggerMax: 50, // на часе креста стохастика RSI не выше этого; 0 — выкл
		RSIExit:       70, // выход: часовой RSI пересёк это вверх — продажа по закрытию часа (выход RSI); 0 — выкл

		// Стохастик (5,3,3): %K — сырой %K за StochK баров, сглаженный за StochSmooth; %D — среднее %K за StochD.
		// Покупка по первому кресту %K над %D вверх в пределах StochBars часов после сигнала RSI
		StochK:      5,
		StochSmooth: 3,
		StochD:      3,
		StochBars:   4,
		// Крест засчитывается, только если %K на часе креста ниже этого; 0 — на любом уровне
		StochCrossMax: 50,
		// Выход по стохастику: %K пересёк %D сверху вниз, %K выше этого — продажа по закрытию часа; 0 — выкл
		StochExitAbove: 0,

		// Объём: объём часа сигнала RSI (час основной сессии) > VolumeMult × среднего объёма VolBars
		// часов основной сессии перед ним; 0 — выключен
		VolumeMult: 1.2,
		VolBars:    20, // сколько часов основной сессии берётся в базу

		// Запас хода дня на кресте стохастика: (лой дня + 1 ATR − close) / ATR ≥ MinRoomATR; 0 — выключен
		MinRoomATR: 0,

		// Стоп: столько дневных ATR ниже цены покупки; 0 — входов нет
		StopATR: 1,
		// Потолок стопа: не дальше этого процента от цены покупки, как бы ни был велик ATR; 0 — выключен
		MaxStopPct: 1.5,
		// Цель: столько стопов выше цены покупки; 0 — без цели
		TargetR: 1.5,

		// Тренд: close часа креста стохастика строго выше EMA этого периода по часовым закрытиям; 0 — выключен
		TrendEMA: 0,

		DailyATRPeriod: 14, // период дневного ATR (Wilder) по завершённым будним дневкам
	}
}
