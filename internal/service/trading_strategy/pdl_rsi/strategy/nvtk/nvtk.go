// дефолтов ядра не меняла тикер молча. Две калибровки скользящим walk-forward (3 мес подбор,
// 1 мес проверка, 24 мес) на прежнем входе по кресту 15m RSI планку не взяли: pooled OOS PF 0.671
// (сетка data/params/pdl_rsi/nvtk/wf_rolling.json) и 1.155 на 58 сделках, держится на одной
