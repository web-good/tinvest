// кресту часового RSI через RSIArm вверх, стоп StopATR от close; 15m и MACD убраны. Позже вход
// перевёрнут: сигнал — крест часового RSI через RSIArm сверху вниз, окно объёма — сам сигнальный час.
// Затем стратегия переделана: после сигнала RSI покупка по первому кресту стохастика (5,3,3) %K над
// %D вверх ниже 40 в пределах 3 часов при RSI не выше 50; стоп 0.5 дневного ATR от цены покупки, цель 2R или
// крест RSI 70 вверх; безубыток и зона вчерашнего лоя убраны. Владелец оставил фильтр EMA, остальные фильтры выключены.
//
// # 2026-10-24 — пошаговая калибровка (скилл pdl-rsi-calibrate)
//
// 36 мес, Hour1, -risk-pct 1. Покоординатный спуск по группам параметров от открытого старта (фильтры
