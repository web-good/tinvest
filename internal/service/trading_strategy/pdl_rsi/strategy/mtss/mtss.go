package mtss

import "tinvest/internal/service/trading_strategy/pdl_rsi/strategy/core"

// Params returns the MTSS literal.
func Params() core.Params {
	return core.Params{
		// Часовой RSI
		HourRSIPeriod: 5,  // длина часового RSI (Wilder); 0 — входов нет
		RSIArm:        25, // сигнал: час, на котором RSI ниже этого и стохастик проходит гейт (без стохастика — крест вниз)
		RSIFloor:      0,  // нет входа, если RSI часа сигнала ниже этого; 0 — выкл
		RSIExit:       75, // выход: часовой RSI пересёк это вниз (вышел из верхней зоны) — продажа по закрытию часа (выход RSI); 0 — выкл
		// Лесенка RSI: когда RSI позиции дошёл до ступени (от RSITrailFrom до RSITrailTo через RSITrailStep),
		// выход по close при кресте вниз уровня «ступень − RSITrailStep»; RSITrailFrom 0 — выкл
		RSITrailFrom: 0,
		RSITrailTo:   70,
		RSITrailStep: 10,

		// Стохастик: %K — сырой %K за StochK баров, сглаженный за StochSmooth, %D — среднее %K за StochD.
		// Гейт на том же часе, что и RSI ниже RSIArm, — никто никого не ждёт: %K ниже 20 (порог ядра);
		// %D идёт только в причину входа. StochK 0 — без стохастика
		StochK:      9,
		StochSmooth: 2,
		StochD:      3,

		// Объём: объём часа сигнала RSI (час основной сессии) > VolumeMult × среднего объёма VolBars
		// часов основной сессии перед ним; 0 — выключен
		VolumeMult: 1.2,
		VolBars:    20, // сколько часов основной сессии берётся в базу

		// Запас хода дня на часе входа: (лой дня + 1 ATR − close) / ATR ≥ MinRoomATR; 0 — выключен
		MinRoomATR: 0,

		// Стоп: столько дневных ATR ниже цены покупки; 0 — входов нет
		StopATR: 1,
		// Потолок стопа: не дальше этого процента от цены покупки, как бы ни был велик ATR; 0 — выключен
		MaxStopPct: 0,
		// Цель: столько стопов выше цены покупки; 0 — без цели
		TargetR: 3,

		// Тренд: close часа входа строго выше EMA этого периода по часовым закрытиям; 0 — выключен
		TrendEMA: 170,

		DailyATRPeriod: 14, // период дневного ATR (Wilder) по завершённым будним дневкам
	}
}
