// Package mgnt supplies the pdl_rsi Params for MGNT (Магнит) on Hour1.
//
// # 2026-10-27 — пошаговая калибровка (скилл pdl-rsi-calibrate)
//
// 36 мес, Hour1, -risk-pct 1, оба режима входа с открытого старта. База — дефолты ядра
// (core.DefaultParams, стохастик %K(14,1), EMA 200): PF 1.057 на 75 сделках.
//
// Режим со стохастиком (data/params/pdl_rsi/mgnt/cal/), шаги:
//   - signal: RSI 6/30, PF 0.625/423, острый пик, точка остаётся;
//   - trigger: %K(14,1), точка остаётся;
//   - trend: EMA 170, PF 1.134/89 (выбор обязателен);
//   - floor: 0, точка остаётся;
//   - volume: 0.5, PF 0.892/68 — сдвинута по медиане окрестности, хотя PF самой точки ниже;
//   - room: 0, точка остаётся;
//   - risk: стоп 1 ATR, цель 1.5R, без потолка, PF 1.178/64;
//   - exits: RSIExit 70 без лесенки, точка остаётся;
//   - signal2: RSI 8/30, PF 1.532/37;
//   - trigger2: %K(8,2), PF 1.972/35;
//   - risk2: без изменений.
//
// Точка спуска: RSI 8/30, %K(8,2), объём 0.5, EMA 170, стоп 1 ATR, цель 1.5R — PF 1.972 на
// 35 сделках. Лучшая комбинация (шаг risk2) отличается только стопом 0.7 ATR: PF 2.103 на 35
// сделках (13 за последние 12 мес), net +11912 ₽.
// Walk-forward (подбор 3 мес, проверка 1 мес): пул OOS PF 0.997 на 47 сделках, net −58 ₽,
// compounded −0.30%; последние 12 фолдов PF 0.398 на 20 сделках, −5.57%, в плюсе 1 из 12 —
// НЕ ГОДЕН. Выборы фолдов: HourRSIPeriod 6 ×22 / 8 ×11 (последний 8), RSIArm 35 ×13 / 30 ×12 /
// 25 ×8 (последний 30), StochK 8 ×29 / 9 ×4 (последний 8), StopATR 0.5 ×19 / 0.7 ×8 / 1 ×6
// (последний 1), TargetR 1.5 ×24 / 2 ×9 (последний 1.5).
//
// Режим без стохастика (cal_nostoch/): signal RSI 4/35 (0.687/632, острый пик), trend EMA 200
// (0.898/212), floor/volume/room выключены, risk стоп 0.7 ATR / цель 2R / потолок 1.5%
// (0.969/211), exits RSIExit 70 без лесенки, signal2 RSI 8/30 (1.299/48), risk2 стоп 1 ATR /
// цель 2R без потолка (1.701/46). Лучшая комбинация — точка спуска, PF 1.701 на 46 сделках.
// Walk-forward: пул OOS PF 0.932 на 60 сделках, −1.51%; последние 12 фолдов PF 0.884 на 20
// сделках, −0.82% — НЕ ГОДЕН.
//
// В литерал — лучшая комбинация режима со стохастиком (оба НЕ ГОДЕН, пул OOS выше: 0.997 против
// 0.932). Острые пики почти на всех шагах обоих режимов. Финал на 36 мес: PF 2.103 на 35 сделках
// (база 1.057/75). За последние 12 мес PF 1.891 на 13 сделках — допуск в прод по правилу
// (PF > 1.2, ≥ 11 сделок): да; но walk-forward провален, свежий год OOS убыточен. Проверка с подбором на 36 мес (-months 48 -train-months 36
// -test-months 1, 12 фолдов): со стохастиком PF 2.06 на 4 сделках, без стохастика 0.95 на 9 —
// выборка мала, ничего не решает. Владелец 2026-10-27 решил торговать: MGNT включён в
// PDL_RSI_TICKERS (env/prod.env).
package mgnt

import "tinvest/internal/service/trading_strategy/pdl_rsi/strategy/core"

// Params returns the MGNT literal.
func Params() core.Params {
	return core.Params{
		// Часовой RSI
		HourRSIPeriod: 8,  // длина часового RSI (Wilder); 0 — входов нет
		RSIArm:        30, // сигнал: час, на котором RSI ниже этого и стохастик проходит гейт (без стохастика — крест вниз)
		RSIFloor:      0,  // нет входа, если RSI часа сигнала ниже этого; 0 — выкл
		RSIExit:       70, // выход: часовой RSI пересёк это вниз (вышел из верхней зоны) — продажа по закрытию часа (выход RSI); 0 — выкл
		// Лесенка RSI: когда RSI позиции дошёл до ступени (от RSITrailFrom до RSITrailTo через RSITrailStep),
		// выход по close при кресте вниз уровня «ступень − RSITrailStep»; RSITrailFrom 0 — выкл
		RSITrailFrom: 0,
		RSITrailTo:   70,
		RSITrailStep: 10,

		// Стохастик: %K — сырой %K за StochK баров, сглаженный за StochSmooth, %D — среднее %K за StochD.
		// Гейт на том же часе, что и RSI ниже RSIArm, — никто никого не ждёт: %K ниже 20 (порог ядра);
		// %D идёт только в причину входа. StochK 0 — без стохастика
		StochK:      8,
		StochSmooth: 2,
		StochD:      3,

		// Объём: объём часа сигнала RSI (час основной сессии) > VolumeMult × среднего объёма VolBars
		// часов основной сессии перед ним; 0 — выключен
		VolumeMult: 0.5,
		VolBars:    20, // сколько часов основной сессии берётся в базу

		// Запас хода дня на часе входа: (лой дня + 1 ATR − close) / ATR ≥ MinRoomATR; 0 — выключен
		MinRoomATR: 0,

		// Стоп: столько дневных ATR ниже цены покупки; 0 — входов нет
		StopATR: 0.7,
		// Потолок стопа: не дальше этого процента от цены покупки, как бы ни был велик ATR; 0 — выключен
		MaxStopPct: 0,
		// Цель: столько стопов выше цены покупки; 0 — без цели
		TargetR: 1.5,

		// Тренд: close часа входа строго выше EMA этого периода по часовым закрытиям; 0 — выключен
		TrendEMA: 170,

		DailyATRPeriod: 14, // период дневного ATR (Wilder) по завершённым будним дневкам
	}
}
