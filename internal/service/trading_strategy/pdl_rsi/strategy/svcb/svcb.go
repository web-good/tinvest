//     свежий плюс walk-forward даёт ежемесячная перекалибровка, а не неподвижный литерал. Выборы фолдов: HourRSIPeriod 5 ×16, 4 ×15 (последний 4); RSIArm 25 ×19, 30 ×12
//     (последний 25); StochBars 0 ×24, 1 ×7 (последний 1); StochBelow 20 ×24, 30 ×7 (последний 20);
//     StopATR 0.7 ×17, 1 ×14 (последний 0.7); TargetR 1.5 ×20, 2 ×11 (последний 1.5).
