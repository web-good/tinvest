// lentGrid читает файл сеток LENT через общий хелпер.
func lentGrid(t *testing.T, file string) map[string][]float64 {
	t.Helper()
	return rsiPullbackTickerGrid(t, "lent", file)
}

// TestLENTSignalGridsPinTheirMeasuredAxes сторожит оси, обоснованные замерами инструмента, а не
// вкусом. Каталог lent/ заводится копированием структуры wush/, и типовая ошибка такой копии —
// притащить вместе с формой чужие обоснования. LENT УЖЕ соседей (медианный дневной ATR 3.16%
// против 4.25% у WUSH и 4.42% у FESH) и стоит ближе к RENI (3.36%), поэтому переносить сюда
// расширенную ось входа WUSH нельзя, а оговорку RENI про мёртвые углы — наоборот, нужно.
func TestLENTSignalGridsPinTheirMeasuredAxes(t *testing.T) {
	screen := lentGrid(t, "cal_screen.json")
	for _, field := range []string{"UseDayATRGate", "UseVolume"} {
		if got := screen[field]; !sameSet(got, 0, 1) {
			t.Errorf("cal_screen.json: %s = %v, want ровно {0,1} — тема меряет цену каждого гейта в сделках, а любая другая пара не даёт сравнить гейт с его отсутствием", field, got)
		}
	}

	entry := lentGrid(t, "cal_entry.json")
	// Потолок поднят с 25 до 50 владельцем 2026-08-14, ДО первого прогона тем. Первая редакция
	// держала 25 и ссылалась на замер (RSI(4) уходит под 30 уже 1690 раз по будням, под 40 —
	// 2671) плюс на опровергнутую догадку WUSH, где расширение той же оси уронило pooled OOS PF
	// с 2.000 до 1.674. Оба довода остаются в силе как ПРЕДУПРЕЖДЕНИЕ при чтении лидерборда, но
	// запретом больше не являются: на WUSH ось расширяли ПОСЛЕ того, как увидели выбор у края,
	// то есть в ответ на результат, а здесь она широка с самого начала — это разные вещи, и
	// вторая не наследует вывод первой. Выше 50 двигать нечего в любом случае: 50 — средняя
	// линия осциллятора, выше которой отката нет по определению.
	for _, v := range entry["RSILower"] {
		if v > 50 {
			t.Errorf("cal_entry.json свипует RSILower=%v: выше 50 отката нет по определению (50 — средняя линия RSI)", v)
		}
	}
	// Ниже 10 выборка истончается быстрее, чем растёт качество сигнала: у RSI(7) на уровне 10
	// остаётся 29 будних кроссов за 36 месяцев, и более глубокий порог режет и их.
	for _, v := range entry["RSILower"] {
		if v < 10 {
			t.Errorf("cal_entry.json свипует RSILower=%v: ниже 10 сигналов почти не остаётся (у RSI(7)@10 их 29 за три года)", v)
		}
	}
	// Уровень 10 обязан остаться: скринер выбрал для LENT лучшей конфигурацией RSI 6/10, и
	// 50 будних кроссов RSI(6)@10 эту точку выдерживают. На DOMRF таких кроссов было 18, и там
	// уровень 10 вырезали — при копировании сеток это сужение легко притащить по ошибке.
	hasDeep := false
	for _, v := range entry["RSILower"] {
		if v == 10 {
			hasDeep = true
		}
	}
	if !hasDeep {
		t.Errorf("cal_entry.json: RSILower = %v, не содержит 10 — основную гипотезу скринера", entry["RSILower"])
	}
	// RSIPeriod короче 4 покупает шум, а не откат: RSI(3) реагирует на любое дрожание цены.
	for _, v := range entry["RSIPeriod"] {
		if v < 4 {
			t.Errorf("cal_entry.json свипует RSIPeriod=%v: короче 4 это шум, а не откат", v)
		}
	}
	// Полоса RSI меряется тут ЦЕЛИКОМ: владелец добавил в тему ось RSIUpper 2026-08-14, тем же
	// решением, каким раньше свёл обе границы в wush/cal_exit.json. Довод за — границы полосы
	// работают в паре, и двигать одну, не перемеряя вторую, значит мерить не полосу, а её
	// половину. Цена — 7 x 4 x 8 = 224 комбинации на четырёх фолдах: тема перестала быть
	// однотемной и стала самой дорогой из девяти, поэтому её лидерборд читать со счётом сделок и
	// помнить, что столько степеней свободы переобучаются заметно легче шестнадцати.
	//
	// Единственное, что здесь остаётся ЗАПРЕТОМ, — вырожденная полоса. Вход требует креста вниз
	// через RSILower, выход — креста вверх через RSIUpper; если верхняя граница не выше нижней,
	// строка сетки означает позицию, которую закрывает любой отскок, а такой профиль в
	// лидерборде выглядит как обычная строка с высоким win rate.
	maxLower := 0.0
	for _, v := range entry["RSILower"] {
		if v > maxLower {
			maxLower = v
		}
	}
	for _, v := range entry["RSIUpper"] {
		if v <= maxLower {
			t.Errorf("cal_entry.json свипует RSIUpper=%v при максимуме RSILower=%.0f: полоса вырождена, выход сработал бы на любом отскоке после входа", v, maxLower)
		}
		if v > 100 {
			t.Errorf("cal_entry.json свипует RSIUpper=%v: шкала RSI кончается на 100", v)
		}
	}

	trend := lentGrid(t, "cal_trend.json")
	// EMASlow=200 исполнима: Lookback при ней равен 2*200+20 = 420 баров против 23 241 будних
	// в кэше, то есть окно прогрева занимает 1.8% истории.
	for _, v := range trend["EMASlow"] {
		if v > 200 {
			t.Errorf("cal_trend.json свипует EMASlow=%v: окно прогрева растёт быстрее, чем польза от сглаживания", v)
		}
	}
	// Быстрая EMA обязана быть быстрее самой быстрой из медленных, иначе строка сетки означает
	// фильтр, который никогда не пропускает вход. Порог берётся из фактического минимума оси
	// EMASlow, а не зашивается константой: понижение оси EMASlow иначе тихо перестало бы
	// совпадать с тем, что здесь проверяется.
	minSlow := math.Inf(1)
	for _, v := range trend["EMASlow"] {
		if v < minSlow {
			minSlow = v
		}
	}
	if !math.IsInf(minSlow, 1) {
		for _, v := range trend["EMAFast"] {
			if v >= minSlow {
				t.Errorf("cal_trend.json свипует EMAFast=%v: минимум оси EMASlow сейчас %.0f, такая пара мертва", v, minSlow)
			}
		}
	}

	exit := lentGrid(t, "cal_exit.json")
	// Это единственное место, где меряется полоса выхода: cal_entry.json её намеренно не свипует.
	if got := exit["RSIUpper"]; !sameSet(got, 55, 60, 65, 70, 75, 80) {
		t.Errorf("cal_exit.json: RSIUpper = %v, want ровно {55,60,65,70,75,80} — cal_entry.json полосу выхода не свипует, а любая точка вне шкалы RSI или пропуск внутри неё сужает единственное место, где эта полоса измеряется", got)
	}
}

// TestLENTRiskGridsPinTheirMeasuredAxes сторожит оси стопа, цели и обоих гейтов. Каждое число
// ниже опирается на замер по кэшу LENT, а не на перенос с соседнего тикера: медианный дневной
// ATR 3.16%, круг издержек 0.032 ATR, медианный дневной размах 0.90 ATR предыдущего дня.
func TestLENTRiskGridsPinTheirMeasuredAxes(t *testing.T) {
	day := lentGrid(t, "cal_day.json")
	if got := day["UseDayATRGate"]; len(got) != 1 || got[0] != 1 {
		t.Errorf("cal_day.json: UseDayATRGate = %v, want ровно [1] — цена отключения гейта меряется в cal_screen.json", got)
	}
	// Тикер-специфичное утверждение этого каталога. День LENT раскрывается быстрее, чем у любого
	// другого заведённого тикера: медиана доли ATR ко второму бару 0.35 против 0.33 у WUSH и 0.28
	// у FESH. Поэтому ветка «день только начался» здесь узкая: порог 0.25 оставляет ей 6.9%
	// будних баров, 0.3 — 10.1%, 0.4 — 17.9%. Ось [0, 0.25, 0.35] из fesh/ подсунула бы
	// калибровке почти мёртвую ветку и дала ложный вывод «ветка не нужна».
	for _, v := range day["FreshDayATR"] {
		if v > 0 && v < 0.3 {
			t.Errorf("cal_day.json свипует FreshDayATR=%v: ко второму бару медианный день LENT прошёл 0.35 ATR, ветке остаётся меньше 7%% баров (порог 0.3 даёт 10.1%%)", v)
		}
	}
	// Порог 0.6 проходят 64.3% будних баров — на этом инструменте он перестаёт быть гейтом. У
	// WUSH та же граница держалась на 56.8%: LENT шире по форме дня (медианный размах 0.90 ATR
	// против 0.83), и потому одни и те же пороги отбирают здесь больше баров.
	for _, v := range day["SpentDayATR"] {
		if v < 0.8 {
			t.Errorf("cal_day.json свипует SpentDayATR=%v: порог достижим для 64%% баров, это не гейт", v)
		}
	}
	// Соотношение двух веток гейта: положительный максимум FreshDayATR обязан быть строго
	// меньше минимума SpentDayATR. dayStateOK пропускает бар, когда день ещё не раскрылся
	// (used <= fresh*ATR) ИЛИ когда он уже исчерпан (used >= spent*ATR); если верх ветки
	// «свежий» дотягивается до низа ветки «исчерпан», обе полосы дают true почти на каждом
	// баре, и UseDayATRGate=1 в лидерборде продолжит формально числиться включённым, хотя
	// фактически не отсекает ничего.
	maxFresh := 0.0
	for _, v := range day["FreshDayATR"] {
		if v > maxFresh {
			maxFresh = v
		}
	}
	minSpent := math.Inf(1)
	for _, v := range day["SpentDayATR"] {
		if v < minSpent {
			minSpent = v
		}
	}
	if maxFresh > 0 && !math.IsInf(minSpent, 1) && maxFresh >= minSpent {
		t.Errorf("cal_day.json: max(FreshDayATR)=%.2f >= min(SpentDayATR)=%.2f — ветки «день начался» и «день исчерпан» перекрываются, dayStateOK почти всегда true, и гейт перестаёт что-либо отсекать несмотря на UseDayATRGate=1", maxFresh, minSpent)
	}
	// RSILower в этой фазе не свипуется: глубина отката принадлежит cal_entry.json. Тема
	// обязана остаться однотемной.
	if got := day["RSILower"]; len(got) != 0 {
		t.Errorf("cal_day.json свипует RSILower=%v: глубина отката принадлежит cal_entry.json", got)
	}

	spent := lentGrid(t, "cal_day_spent.json")
	if got := spent["FreshDayATR"]; len(got) != 1 || got[0] != 0 {
		t.Errorf("cal_day_spent.json: FreshDayATR = %v, want ровно [0] — ветка «день начался» выключена целиком", got)
	}
	// Левый край 0.6 стоит контрольной строкой «гейт почти выключен» (64.3% баров). Точки
	// ниже на LENT не гейтят вовсе и заняли бы прогоны впустую.
	for _, v := range spent["SpentDayATR"] {
		if v < 0.6 {
			t.Errorf("cal_day_spent.json свипует SpentDayATR=%v: ниже 0.6 порог не гейтит (0.6 проходят 64%% баров)", v)
		}
	}

	vol := lentGrid(t, "cal_volume.json")
	if got := vol["UseVolume"]; len(got) != 1 || got[0] != 1 {
		t.Errorf("cal_volume.json: UseVolume = %v, want ровно [1] — точка «гейт выключен» принадлежит cal_screen.json", got)
	}
	// Все четыре точки живые: при базе 5 дней гейт проходят 30.6% баров при 1.2, 24.5% при 1.5,
	// 17.9% при 2.0, 13.9% при 2.5. Выше 2.5 остаётся меньше седьмой части баров, и объёмный
	// гейт начинает резать выборку сильнее, чем несёт информации.
	for _, v := range vol["VolMult"] {
		if v > 2.5 {
			t.Errorf("cal_volume.json свипует VolMult=%v: выше 2.5 гейт проходит меньше 14%% баров", v)
		}
	}
	// Только две базы, 5 и 10: короткая быстрее реагирует на смену активности, длинная
	// устойчивее к одиночному всплеску. База 3 ловит один выброс объёма, база 14 — размывает;
	// на вторичном гейте лишние степени свободы не окупаются.
	for _, v := range vol["VolBaseDays"] {
		if v != 5 && v != 10 {
			t.Errorf("cal_volume.json свипует VolBaseDays=%v: обоснованы только 5 и 10 (3 ловит одиночный всплеск, 14 размывает)", v)
		}
	}

	risk := lentGrid(t, "cal_risk.json")
	// Круг издержек на LENT стоит 0.032 дневного ATR — дороже, чем у WUSH (0.024), FESH (0.023) и
	// RENI (0.030), потому что инструмент уже: медианный дневной ATR 3.16% против 4.25% у WUSH.
	// На стопе 0.3 ATR комиссия съедает 10.6% риска. Строка сохранена, но именно из-за этого
	// числа её присутствие проверяется явно: она стоит ближе к черте 17%, по которой строку 0.3
	// вырезали из domrf/, чем к 8% WUSH, и «оптимизация» каталога легко унесёт её молча.
	hasTightStop := false
	for _, v := range risk["StopDailyATR"] {
		if v == 0.3 {
			hasTightStop = true
		}
	}
	if !hasTightStop {
		t.Errorf("cal_risk.json: StopDailyATR = %v, не содержит 0.3 — строка дорогая (10.6%% риска на издержки), но замеренная, и её удаление обязано быть решением, а не побочным эффектом", risk["StopDailyATR"])
	}
	// Нижняя граница оси: тот же круг издержек, который ещё терпит строку 0.3 (10.6% риска),
	// запрещает идти уже. На 0.2 доля выросла бы до 16%, на 0.15 — до 21%: это уже за чертой, по
	// которой DOMRF отверг свою строку 0.3 при 17%.
	for _, v := range risk["StopDailyATR"] {
		if v > 0 && v < 0.3 {
			t.Errorf("cal_risk.json свипует StopDailyATR=%v: издержки съели бы %.0f%% риска (круг 0.032 ATR) против 11%% на разрешённой строке 0.3; DOMRF отверг свою строку 0.3 при 17%%", v, 0.032/v*100)
		}
	}
	// Верх оси 1.3: медианный день покрывает 0.90 ATR, такой стоп переживает целиком 78.9%
	// дней. Шире — это уже не стоп, а отсутствие стопа, оплаченное размером позиции.
	for _, v := range risk["StopDailyATR"] {
		if v > 1.3 {
			t.Errorf("cal_risk.json свипует StopDailyATR=%v: шире 1.3 ATR стоп перестаёт быть стопом (медианный день 0.90 ATR, стоп 1.3 переживает 79%% дней)", v)
		}
	}

	trail := lentGrid(t, "cal_trail.json")
	if got := trail["UseTrail"]; len(got) != 1 || got[0] != 1 {
		t.Errorf("cal_trail.json: UseTrail = %v, want ровно [1] — тема меряет форму трейла, а не факт включения", got)
	}
	if got := trail["UseRSIExit"]; !sameSet(got, 0, 1) {
		t.Errorf("cal_trail.json: UseRSIExit = %v, want ровно {0,1} — трейл и RSI-выход конкурируют за одну сделку, и посторонняя точка не даёт замерить оба режима", got)
	}
	// Правый край 0.8, а не 0.6 как у ugld/: там потолок задавала цель TPDailyATR=0.6, выше
	// которой трейл не успевал взвестись; здесь ось цели поднята до 2.5, и трейлу нужно
	// пространство для по-настоящему позднего срабатывания.
	hasFarTrail := false
	for _, v := range trail["TrailDailyATR"] {
		if v == 0.8 {
			hasFarTrail = true
		}
	}
	if !hasFarTrail {
		t.Errorf("cal_trail.json: TrailDailyATR = %v, не содержит правый край 0.8 (цель поднята до 2.5)", trail["TrailDailyATR"])
	}
}
