package backtest

import "testing"

// diasGrid читает файл сеток DIAS через общий хелпер.
func diasGrid(t *testing.T, file string) map[string][]float64 {
	t.Helper()
	return rsiPullbackTickerGrid(t, "dias", file)
}

// TestDIASGridsPinTheirMeasuredAxes сторожит оси каталога dias/. Каталог собран 2026-08-22
// копированием формы elfv/ с пересадкой каждой оси на замеры самого DIAS (28 127 30-минутных
// баров в кэше, 27 993 в расчётном окне 30 месяцев с 2024-02-22, из них 20 501 будний; кэш
// ПЕРЕЗАЛИТ целиком, потому что в дневной серии отсутствовало полугодие 2024-06-24…2024-12-23).
// Четыре решения отличают этот каталог от образца, и каждое опирается на замер:
//
//   - RSIPeriod ОБОРВАН на 7. Планка живого угла в каталоге — 29 кроссов (столько дал слабейший
//     угол LSNGP, объявленный мёртвым; у RENI было 23). RSI(7)@10 даёт 31 будний кросс за 30
//     месяцев и проходит впритык, RSI(8)@10 даёт 19 и не проходит. То же решение, что на ELFV,
//     обратное SIBN (там 8@10 давал 34).
//   - VolMult СУЖЕН до 2.5 — обратное тому, что сделали на ELFV. Точечные прогоны: гейт даёт
//     максимум 1.894 на 102 сделках при множителе 1.5, что ЕДВА выше baseline без гейта (1.822
//     на 153 сделках) и стоит трети выборки, а дальше PF падает монотонно (2.0 -> 1.689,
//     2.5 -> 1.410, 3.0 -> 1.313, 4.0 -> 1.065). Значение 3.0 оставляет 65 сделок = 22 на
//     10-месячное обучающее окно при -min-trades 20 и PF ниже baseline: такая строка может
//     победить только процедурным артефактом. На ELFV та же ось расширялась до 3.0, потому что
//     там все 24 комбинации решётки били baseline.
//   - VolLookbackBars РАСШИРЕН до 16 — впервые в каталоге ось уходит далеко за дефолт ядра 3.
//     Точечные прогоны (VolMult 2.0, база 14): 1 -> 69 сделок PF 1.294, 2 -> 80/1.510,
//     3 -> 88/1.689, 5 -> 98/1.867, 8 -> 111/1.819, 12 -> 121/1.915, 16 -> 126/1.810. Рост
//     монотонный до 12, дефолт ядра хуже максимума на 0.23 PF и на 33 сделки. Край 16 нужен,
//     чтобы разворот кривой попал ВНУТРЬ сетки, а не на её границу. Инструментальное основание:
//     11.9% будних дней несут меньше двадцати баров, поэтому окно в 12 баров здесь — треть
//     торгового дня, а не «полтора часа», как на ликвидной бумаге.
//   - Строка StopDailyATR = 0.3 ВОЗВРАЩЕНА, хотя у domrf/ и elfv/ она вырезана. Шаг цены на DIAS
//     равен 0.5 ₽ = 0.0165% медианной цены 3033.5, то есть втрое дешевле, чем на ELFV (0.039%).
//     Реальный круг издержек ≈ 0.13%, и при стопе 0.3 ATR (0.92% цены) он съедает 14.1% риска —
//     под чертой 17%, по которой строку резали. Замер чувствительности: круг 0.1% -> PF 1.822,
//     0.2% -> 1.567, 0.3% -> 1.336.
func TestDIASGridsPinTheirMeasuredAxes(t *testing.T) {
	screen := diasGrid(t, "cal_screen.json")
	for _, field := range []string{"UseDayATRGate", "UseVolume"} {
		if got := screen[field]; !sameSet(got, 0, 1) {
			t.Errorf("cal_screen.json: %s = %v, want ровно {0,1} — тема меряет цену каждого гейта в сделках", field, got)
		}
	}

	entry := diasGrid(t, "cal_entry.json")
	// Выше 50 отката нет по определению: 50 — средняя линия осциллятора.
	for _, v := range entry["RSILower"] {
		if v > 50 {
			t.Errorf("cal_entry.json свипует RSILower=%v: выше 50 отката нет по определению", v)
		}
	}
	// Уровень 10 обязан остаться: на DIAS он живой — RSI(4)@10 даёт 207 будних кроссов за 30
	// месяцев, слабейший угол сетки RSI(7)@10 — 31, выше планки живого угла 29.
	if !containsValue(entry["RSILower"], 10) {
		t.Errorf("cal_entry.json: RSILower = %v, не содержит 10 — на DIAS это живой угол (207 кроссов RSI(4)@10)", entry["RSILower"])
	}
	// RSIPeriod короче 4 покупает шум, а не откат: RSI(3)@10 даёт 460 кроссов против 207 у RSI(4).
	for _, v := range entry["RSIPeriod"] {
		if v < 4 {
			t.Errorf("cal_entry.json свипует RSIPeriod=%v: короче 4 это шум, а не откат", v)
		}
		// Верхний край 7: RSI(8)@10 даёт 19 кроссов за 30 месяцев — ниже планки живого угла 29,
		// по которой угол объявляли мёртвым на LSNGP и RENI.
		if v > 7 {
			t.Errorf("cal_entry.json свипует RSIPeriod=%v: слабейший угол RSI(8)@10 даёт 19 кроссов, ось мертва за 7", v)
		}
	}
	if !containsValue(entry["RSIPeriod"], 7) {
		t.Errorf("cal_entry.json: RSIPeriod = %v, не содержит 7 — это последний живой угол (31 кросс RSI(7)@10)", entry["RSIPeriod"])
	}

	trend := diasGrid(t, "cal_trend.json")
	// Ось тренда режется только вместе с этим тестом. На DIAS доля баров с EMAFast > EMASlow
	// укладывается в 36.7-40.7% на ВСЕХ 35 парах: выбор пары меняет не объём допуска, а то,
	// какие именно бары в него попадают. Уровень ниже всего каталога (у ELFV 44-46%) — прямое
	// следствие того, что бумага падала все 30 месяцев.
	if !containsValue(trend["EMASlow"], 200) {
		t.Errorf("cal_trend.json: EMASlow = %v, не содержит 200 — медленный край оси обязан остаться, допуск у него 36.7-37.3%%", trend["EMASlow"])
	}
	for _, fast := range trend["EMAFast"] {
		for _, slow := range trend["EMASlow"] {
			if fast >= slow {
				t.Errorf("cal_trend.json: пара EMAFast=%v EMASlow=%v вырождена — быстрая обязана быть быстрее медленной", fast, slow)
			}
		}
	}

	risk := diasGrid(t, "cal_risk.json")
	// Строка 0.3 ВОЗВРАЩЕНА в сетку, в отличие от domrf/ и elfv/: шаг цены 0.5 ₽ = 0.0165% цены,
	// реальный круг издержек ≈ 0.13% и съедает на этом стопе 14.1% риска — под чертой 17%.
	if !containsValue(risk["StopDailyATR"], 0.3) {
		t.Errorf("cal_risk.json: StopDailyATR = %v, не содержит 0.3 — на DIAS шаг цены втрое дешевле, чем на ELFV, и строка живая (14.1%% риска)", risk["StopDailyATR"])
	}
	for _, v := range risk["StopDailyATR"] {
		if v < 0.3 {
			t.Errorf("cal_risk.json свипует StopDailyATR=%v: уже 0.3 ATR круг издержек съедает больше 17%% риска даже при дешёвом шаге цены", v)
		}
		// Верхний край 1.3: уровня 1.5 ATR достаёт лишь 12.4% дней, такой стоп перестаёт быть
		// защитой и становится способом вытеснить убыток в RSI-выход.
		if v > 1.3 {
			t.Errorf("cal_risk.json свипует StopDailyATR=%v: до него доходит 12%% дней — это не стоп", v)
		}
	}

	day := diasGrid(t, "cal_day.json")
	// Ветка «свежий день» ловит 10.8% будних баров при пороге 0.3 и 31.3% при 0.5; ноль в оси —
	// это выключенная ветка, и она обязана остаться, потому что на всех прод-тикерах каталога
	// победил именно ноль.
	if !containsValue(day["FreshDayATR"], 0) {
		t.Errorf("cal_day.json: FreshDayATR = %v, не содержит 0 — выключенная ветка обязана быть в сетке", day["FreshDayATR"])
	}
	// Верхний край ветки «день исчерпан» ОСТАВЛЕН на 1.5: через него проходит 9.4% баров —
	// больше, чем на SVAV (7.7%), где край держался, и заметно больше, чем на SIBN (5.3%).
	if !containsValue(day["SpentDayATR"], 1.5) {
		t.Errorf("cal_day.json: SpentDayATR = %v, не содержит 1.5 — на DIAS край живой (9.4%% баров)", day["SpentDayATR"])
	}

	daySpent := diasGrid(t, "cal_day_spent.json")
	if !containsValue(daySpent["SpentDayATR"], 1.5) {
		t.Errorf("cal_day_spent.json: SpentDayATR = %v, не содержит 1.5 — край живой по замеру 9.4%% баров", daySpent["SpentDayATR"])
	}
	// Уплотнение оси живыми уровнями — часть решения, а не случайность.
	for _, want := range []float64{0.7, 1.1} {
		if !containsValue(daySpent["SpentDayATR"], want) {
			t.Errorf("cal_day_spent.json: SpentDayATR = %v, не содержит %v — уровень живой (48.4%% и 21.1%% баров)", daySpent["SpentDayATR"], want)
		}
	}

	volume := diasGrid(t, "cal_volume.json")
	// Край 2.5 — СУЖЕНИЕ против elfv/, где ось доходила до 3.0. Держится на форме кривой и на
	// счёте сделок: 3.0 оставляет 65 сделок (22 на 10-месячное обучающее окно) при PF 1.313,
	// ниже baseline без гейта (1.822).
	for _, v := range volume["VolMult"] {
		if v > 2.5 {
			t.Errorf("cal_volume.json свипует VolMult=%v: при 3.0 остаётся 65 сделок (22 на train) и PF 1.313, ниже baseline 1.822", v)
		}
	}
	// Максимум оси стоит на 1.5 и обязан быть в сетке.
	if !containsValue(volume["VolMult"], 1.5) {
		t.Errorf("cal_volume.json: VolMult = %v, не содержит 1.5 — это максимум оси (102 сделки, PF 1.894)", volume["VolMult"])
	}
	// Верхний край 2.5 обязан остаться: это СУЖЕННЫЙ край оси (у ELFV она доходила до 3.0), и его
	// исчезновение означало бы, что ось молча сузилась ещё сильнее, чем решено замером.
	if !containsValue(volume["VolMult"], 2.5) {
		t.Errorf("cal_volume.json: VolMult = %v, не содержит 2.5 — это верхний край суженной оси (78 сделок, PF 1.410)", volume["VolMult"])
	}

	// Вторая в каталоге тема этой оси (первая — ELFV) и первая, где ось уходит далеко за дефолт
	// ядра: PF растёт монотонно от 1.294 при окне 1 до 1.915 при окне 12, дефолт 3 даёт 1.689.
	volWindow := diasGrid(t, "cal_vol_window.json")
	if !sameSet(volWindow["UseVolume"], 1) {
		t.Errorf("cal_vol_window.json: UseVolume = %v, want ровно {1} — тема меряет ОКНО гейта, а выключенный гейт окна не имеет", volWindow["UseVolume"])
	}
	for _, v := range volWindow["VolLookbackBars"] {
		if v < 1 {
			t.Errorf("cal_vol_window.json свипует VolLookbackBars=%v: окно меньше одного бара выключает гейт молча, а не меряет его", v)
		}
		// Верхний край 16: при 126 сделках из 153 возможных гейт с таким окном почти неотличим
		// от выключенного, дальше тема меряла бы не окно, а отсутствие гейта.
		if v > 16 {
			t.Errorf("cal_vol_window.json свипует VolLookbackBars=%v: гейт с таким окном неотличим от выключенного (126 сделок из 153)", v)
		}
	}
	// Дефолт ядра — опорная точка сравнения, максимум замера — то, ради чего ось расширена.
	for _, want := range []float64{3, 12} {
		if !containsValue(volWindow["VolLookbackBars"], want) {
			t.Errorf("cal_vol_window.json: VolLookbackBars = %v, не содержит %v (дефолт ядра 3 — опорная точка, 12 — максимум замера PF 1.915)", volWindow["VolLookbackBars"], want)
		}
	}
	// Край 16 обязан остаться: он нужен, чтобы разворот кривой PF (максимум 1.915 на окне 12,
	// затем 1.810 на 16) попал ВНУТРЬ сетки, а не остался на её границе.
	if !containsValue(volWindow["VolLookbackBars"], 16) {
		t.Errorf("cal_vol_window.json: VolLookbackBars = %v, не содержит 16 — край нужен, чтобы разворот кривой (1.915 -> 1.810) попал внутрь сетки, а не на границу", volWindow["VolLookbackBars"])
	}

	exit := diasGrid(t, "cal_exit.json")
	// Полоса выхода рабочая на всём диапазоне: кроссов вверх RSI(4) от 2658 (55) до 618 (80).
	for _, v := range exit["RSIUpper"] {
		if v <= 50 {
			t.Errorf("cal_exit.json свипует RSIUpper=%v: выход обязан стоять выше средней линии", v)
		}
	}
}
