// прогоны шли по штатной схеме -months 36 -train-months 12 -test-months 6 и числа сопоставимы
// построчно с каталогом (в отличие от IVAT и DOMRF). Подробности и оговорки (фолд 3 темы entry —
// тонкая выборка с признаком переобучения, тема volume без устойчивости ведущей оси) — в доке
// пакета strategy/svav.
//
// SIBN заведён 2026-08-21 тринадцатым (риск 16) — тикер с САМЫМ СЛАБЫМ АПРИОРОМ каталога, и это
// было записано ДО прогонов: колонка PFmed HO скринера 0.20 на 9 сделках (худшая в первой девятке
// рейтинга), контрольный baseline-прогон на 36 месяцах — PF 1.027 на 129 сделках, то есть на
// дефолтах ядра инструмент торгует ровно в ноль. Планка не взята обеими ключевыми темами и с
// наибольшим отрывом в каталоге: entry pooled OOS PF 1.378 на 50 сделках при устойчивости ведущей
// оси 1 из 4, trend — 0.847 на 94 сделках при устойчивости 0 из 4 (первый нуль в каталоге); ни
