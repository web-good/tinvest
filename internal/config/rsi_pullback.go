package config

// RSIPullbackConfig configures the live rsi_pullback runner. Trade and notify are
// independent: both off = dry-run to log only.
//
// AccountID и Token НЕ помечены `required` намеренно. confita трактует required как
// «непустое значение» и возвращает ошибку загрузки, а она обрывает InitApp — то есть
// приложение не поднимается целиком, вместе с воркерами живого reversion, ведущими
// реальные позиции. Пока у стратегии нет своего счёта, её раннер должен просто не
// запускаться (см. Ready), а не ронять всё остальное.
type RSIPullbackConfig struct {
	AccountID     string   `config:"RSI_PULLBACK_ACCOUNT_ID,backend=env"`
	Token         string   `config:"RSI_PULLBACK_TOKEN,backend=env"`
	Tickers       []string `config:"RSI_PULLBACK_TICKERS,backend=env"`
	BuyPct        float64  `config:"RSI_PULLBACK_BUY_PCT,backend=env"`
	TradeEnabled  bool     `config:"RSI_PULLBACK_TRADE_ENABLED,backend=env"`
	NotifyEnabled bool     `config:"RSI_PULLBACK_NOTIFY_ENABLED,backend=env"`
	Schedule      string   `config:"RSI_PULLBACK_SCHEDULE,backend=env"`
}

// NewRSIPullbackConfig returns the config pre-seeded with safe defaults. confita
// overrides any field whose env var is set; unset fields keep these values.
// TradeEnabled defaults to false so a missing flag never places real orders.
//
// Schedule фиксирует три решения. Раз в полчаса — потому что рабочий таймфрейм
// стратегии 30 минут. Минута :01/:31, а не :00/:30 — запас на то, чтобы закрывшийся бар
// успел прийти из API с IsComplete=true. Все семь дней недели — позиция едет через
// выходные, и бэктест отрабатывает выходы на выходных барах MOEX; входы на выходных
// закрывает само ядро (tradingDay). Ночью 00:00-06:00 MSK торгов нет.
//
// Вселенная по умолчанию — UGLD, T, GAZP, DOMRF, FESH, WUSH, LENT, RENI, NVTK, LSNGP, IVAT и
// SVAV. С 2026-08-17 это ВЕСЬ реестр: решением владельца в неё заведены три последних тикера, у
// которых литерал был, а решения не было; IVAT добавлен одиннадцатым 2026-08-18 сразу после
// калибровки. Walk-forward прошёл только
// UGLD (docs/rsi_pullback/live.md §10, риск 3); остальные торгуются как принятый владельцем
// риск, а не по недосмотру. У DOMRF риск самый крупный: 8.6 месяца истории, вся она — один
// пост-IPO аптренд, out-of-sample по существу один фолд на 8 сделках (подробности и замеры —
// в доке пакета strategy/domrf). FESH заведён 2026-08-13 (риск 7): истории у него как раз
// достаточно, но штатный протокол его НЕ подтверждает — тематические сетки на четырёх фолдах
// дают pooled OOS PF 1.029 по входу и 0.953 по тренду, а хорошие 2.366 принадлежат
// конфигурации, выбранной человеком, видевшим всю историю (док пакета strategy/fesh). WUSH
// LENT заведён 2026-08-14 последним, и у него риск ДРУГОЙ ПРИРОДЫ, чем у остальных: помимо
// непройденной планки (entry 1.355, trend 1.777 при неустойчивой ведущей оси — четыре разных
// значения RSILower на четырёх фолдах) у него самая тонкая ликвидность вселенной — 67 млн ₽
// среднего дневного оборота при медиане будних дней всего 38 млн, тогда как у WUSH медиана
// 253 млн. Это ограничение исполнения, а не статистики: половина торговых дней тоньше гейта
// отбора скринера в 50 млн, и BUY_PCT=5 на крупном счёте упрётся в стакан здесь раньше, чем на
// любом другом тикере. Числа литерала — pooled PF 2.487 на 120 сделках при четырёх фолдах выше
// планки — принадлежат конфигурации, собранной по лидербордам человеком, видевшим всю историю
// (док пакета strategy/lent). WUSH
// заведён 2026-08-14 на тех же основаниях и с тем же типом риска: истории 36 месяцев хватает,
// но объявленную заранее планку тикер не взял ДВАЖДЫ (тема trend дала 1.317, после расширения
// оси входа 1.377 при пороге 1.5), а числа принятого литерала — pooled PF 2.030 на 144 сделках
// с прибыльными четырьмя фолдами — принадлежат конфигурации, подобранной вручную по всей
// истории, то есть не out-of-sample (док пакета strategy/wush). Отдельная особенность WUSH:
// оба окна протокола у него ПАДАЮЩИЕ (train −58.9%, holdout −48.0%), поэтому лонговый результат
// здесь не завышен режимом — но и просадка литерала выше остальных, 14.85% за 36 месяцев.
//
// RENI, NVTK и LSNGP заведены 2026-08-17 одним решением владельца — до этого дня каждый из них
// имел откалиброванный литерал и не имел решения о вселенной. Тип риска у всех трёх тот же, что у
// FESH, WUSH и LENT: истории на штатный протокол хватает, но протокол тикер не подтверждает, а
// числа принятой точки собраны человеком, видевшим тестовые окна. Различия, которые надо знать
// (полный разбор — live.md §10, риски 11, 12 и 13, и доки пакетов):
//   - RENI (риск 11) из троих ближе всех к планке: шесть тем из девяти выше 1.5, обязательная
//     пара взята по PF (entry 1.955, trend 1.920) и провалена только по устойчивости ведущей оси.
//     Перекалибровка 2026-08-16 закрыла обе прежние оговорки тикера. Оборот 91 млн ₽/день —
//     второй снизу в каталоге после LENT.
//   - NVTK (риск 12) — противоположный край: слепые темы дали ХУДШИЙ результат каталога (одна из
//     девяти выше 1.5, entry 1.218, trend 1.044), и весь разрыв с принятой точкой (pooled 2.823
//     на 93 сделках) — работа человека. Взамен это самый ликвидный тикер вселенной, то есть
//     единственный из троих, где риск исполнения не добавляется к статистическому.
//   - LSNGP (риск 13) — единственный, у кого ВСЕ девять тем выше 1.5, и одновременно единственный,
//     у кого в истории НЕТ падающего окна: оба окна протокола растут (+46.7% / +11.2%), так что
//     против падающего рынка конфигурация не проверялась вовсе. Ликвидность вторая снизу после
//     LENT (медиана 41 млн ₽), а RSIUpper 55 делает сделку внутридневной — медиана удержания
//     4 бара против 12 у LENT.
//
// IVAT заведён 2026-08-18 (риск 14) — самая слабая доказательная база вселенной, и риск у него
// тройной. Первое: истории 26.0 месяца (IPO июнь 2024), поэтому прогоны шли по АДАПТИРОВАННОЙ
// схеме (-months 25 -train-months 9 -test-months 4) — штатный протокол §8 на такой истории
// четырёх фолдов не даёт вовсе, и числа IVAT не сопоставимы построчно с остальными десятью.
// Второе: планку не взяли ОБЕ ключевые темы, причём entry ушла ниже единицы (0.979 на 47
// сделках) — первый такой случай в каталоге; trend дала 1.282 при ведущей оси, устойчивой в
// двух фолдах из четырёх и развернувшейся на середине истории. Третье: принятая точка меряет
// pooled OOS PF 1.988 на 55 сделках, но 85% результата делает ОДНА НЕДЕЛЯ (четыре крупнейшие
// сделки всей истории — 21-27 июля 2026), а на OOS первых трёх фолдов, то есть за целый год и
// 42 сделки, та же конфигурация даёт 1.209. Режим — зеркало LSNGP: ни одного растущего
// полугодия за всю историю (train −45.6%, holdout −58.8%), значит против РАСТУЩЕГО рынка
// конфигурация не проверена ни разу, а трендовый фильтр самый закрытый в каталоге (открыт
// 29.4-36.0% баров). К статистическому риску добавляется исполнение: медиана оборота 43 млн
// ₽/день при p10 = 7 млн — половина дней тоньше гейта скринера в 50 млн, уровень LENT.
//
// SVAV заведён 2026-08-21 (риск 15) — единственный тикер вселенной с ДРУГОЙ ПРИРОДОЙ риска:
// это не непройденный протокол, а высокая волатильность инструмента, при том что протокол
// пройден целиком впервые в каталоге (entry pooled OOS PF 2.139/47, trend 2.343/104, обе ведущие
// оси устойчивы 3 из 4 фолдов). Дневной ATR(14) медианой 4.38% цены — второй в каталоге после
// FESH; стоп 0.5 ATR это 2.2% цены, то есть при Fraction=1 одна сделка двигает счёт заметно
// сильнее, чем на большинстве других тикеров вселенной. Режим враждебный: вся история −58.9%,
// пик-минимум −83.4%, из шести полугодий растущее одно (+0.8%) — лонговый результат режимом не
// завышен, но и на растущем рынке конфигурация не проверена. История ровно 36.0 месяца, поэтому
// прогоны шли по штатной схеме -months 36 -train-months 12 -test-months 6 и числа сопоставимы
// построчно с каталогом (в отличие от IVAT и DOMRF). Подробности и оговорки (фолд 3 темы entry —
// тонкая выборка с признаком переобучения, тема volume без устойчивости ведущей оси) — в доке
// пакета strategy/svav.
//
// SIBN заведён 2026-08-21 тринадцатым (риск 16) — тикер с САМЫМ СЛАБЫМ АПРИОРОМ каталога, и это
// было записано ДО прогонов: колонка PFmed HO скринера 0.20 на 9 сделках (худшая в первой девятке
// рейтинга), контрольный baseline-прогон на 36 месяцах — PF 1.027 на 129 сделках, то есть на
// дефолтах ядра инструмент торгует ровно в ноль. Планка не взята обеими ключевыми темами и с
// наибольшим отрывом в каталоге: entry pooled OOS PF 1.378 на 50 сделках при устойчивости ведущей
// оси 1 из 4, trend — 0.847 на 94 сделках при устойчивости 0 из 4 (первый нуль в каталоге); ни
// одна из девяти тем не достала 1.5, три убыточны. Принятая точка при этом даёт pooled OOS PF
// 2.258 на 89 сделках, три фолда выше 3.0, без единого вырожденного фолда, и результат размазан
// (лучшая неделя 17.9%, все пять полугодий положительны — проверка на «одну неделю», провалившая
// IVAT, здесь пройдена), но точка собрана вручную по всей истории и out-of-sample не является.
// Тип риска: волатильность САМАЯ НИЗКАЯ в каталоге — дневной ATR(14) медианой 2.52% цены, стоп
// 0.7 ATR это 1.76% цены при Fraction=1, а круг издержек съедает 5.7% риска (против 2-3% на
// большинстве тикеров вселенной). Дивидендные гэпы — риск, который прогонами не закрывается:
// бумага платит регулярно, стратегия держит через ночь, пять гэпов окна хуже −3% (глубочайший
// −8.49%, это −4.69 дневного ATR), и на таком открытии стоп не пол, а пожелание. Смягчающий
// фактор один, зато сильный: ликвидность лучшая в каталоге с отрывом — медиана оборота 519 млн
// ₽/день при p10 = 206 млн, вчетверо выше гейта скринера даже на десятом перцентиле, поэтому риск
// исполнения к статистическому не добавляется (в отличие от IVAT и LENT). Подробности — в доке
// пакета strategy/sibn.
//
// ELFV заведён 2026-08-22 четырнадцатым. Планка не взята, но в форме, которой в каталоге не было:
// ОБЕ ключевые темы взяли порог 1.5 по profit factor и ОБЕ провалили устойчивость — entry 1.575 на
// 106 сделках при устойчивости RSILower 1 из 4, trend 1.545 на 147 сделках при устойчивости
// EMASlow 0 из 4. Все десять тем выше 1.38, ни одна не убыточна — самая ровная таблица тем в
// каталоге, — но ни одна ось не держится больше чем на 2 фолдах из 4. Принятая точка даёт pooled
// OOS PF 2.863 на 68 сделках, и ВСЕ ЧЕТЫРЕ фолда прибыльные, включая заранее объявленный тяжёлым
// четвёртый (полугодие −30.5%); вырожденных фолдов нет, лучшая неделя даёт 28.3% результата, все
// пять полугодий положительны. Точка собрана вручную по всей истории и out-of-sample не является.
// ТИП РИСКА ЗДЕСЬ НЕ В АПРИОРЕ, А В ИСПОЛНЕНИИ. Априор у ELFV был САМЫЙ СИЛЬНЫЙ в каталоге
// (holdout скринера 1.26, контрольный baseline PF 1.546 на 181 сделке) и не помог: протокол
// провалился так же, как на тикерах со слабым априором — вместе с SIBN (baseline 1.027) это
// закрывает вопрос, предсказывают ли колонки скринера исход протокола, ответом «ни снизу, ни
// сверху». Исполнение же сомнительно по двум причинам сразу. Шаг цены 0.0002 ₽ равен 0.039%
// медианной цены 0.5134, а бэктест наливает по закрытию бара и спред не моделирует: при удвоении
// круга издержек до 0.2% принятая точка падает с pooled OOS PF 2.863 до 2.346, а её четвёртый
// фолд уходит под единицу (1.250 -> 0.944). Ликвидность — ХУДШАЯ в каталоге: медиана оборота 25.1
// млн ₽/день при p10 = 6.4 млн, то есть каждый десятый будний день бумага оборачивает меньше семи
// миллионов, и размер живой позиции обязан соотноситься с p10, а не с медианой. Плюс самый жёсткий
// режим каталога: окно −49.5%, холдаут −32.5%, растущих полугодий два из шести. Риск, которого у
// этого тикера НЕТ, — дивидендные гэпы: ЭЛ5-Энерго не платит с 2020 года, за 36 месяцев ровно один
// гэп хуже −3% против пяти у SIBN, и это единственный тикер вселенной, где ночное удержание не
// несёт риска отсечки. Подробности — в доке пакета strategy/elfv.
//
// DIAS заведён 2026-08-24 пятнадцатым. Планка не взята в форме, промежуточной между ELFV и SIBN:
// тема entry провалила ОБА критерия, как у SIBN (pooled OOS PF 1.213 при устойчивости RSILower 2
// из 4), тема trend взяла profit factor и провалила устойчивость, как обе темы ELFV (1.848 при
// EMASlow 2 из 4). Априор был ВТОРЫМ ПО СИЛЕ в каталоге и записан до прогонов (скринер PFmed 1.62,
// PFmed HO 3.35; контрольный baseline на 30 месяцах — 153 сделки, PF 1.822) и, как у ELFV, планку
// не спас. Принятая точка даёт pooled OOS PF 2.361 на 98 сделках, ВСЕ ЧЕТЫРЕ фолда прибыльные;
// стоп-условие плана (pooled OOS PF ниже 1.0 либо меньше 20 сделок) не сработало.
// ТИП РИСКА ЗДЕСЬ РЕЖИМНЫЙ И СТАТИСТИЧЕСКИЙ, А НЕ ИСПОЛНИТЕЛЬНЫЙ, и это отличает DIAS от соседа
// по вселенной. Режим: это единственный тикер вселенной, у которого за всю историю НЕТ НИ ОДНОГО
// растущего полугодия — падают все шесть (−6.7% / −26.7% / −18.5% / −38.2% / −4.2% / −29.4%),
// окно −79.0%, пик-минимум −85.7%. Читать это надо в обе стороны: завысить лонговый результат
// режимом здесь нечем, но ПРОТИВ РОСТА КОНФИГУРАЦИЯ НЕ ПРОВЕРЯЛАСЬ ВОВСЕ — зеркало риска LSNGP.
// Статистика: истории 30.3 месяца (IPO 2024-02-13), поэтому штатный протокол §8 неисполним и
// прогоны шли по адаптированной схеме -months 30 -train-months 10 -test-months 5 (прецедент —
// IVAT 25/9/4); числа DIAS сопоставимы с IVAT, но НЕ ПОСТРОЧНО с остальным каталогом. Ликвидность
// тонкая: медиана оборота 42.6 млн ₽/день при p10 = 13.6 млн (уровень IVAT и LENT), гейт скринера
// в 50 млн бумага проходит только средним, поэтому размер живой позиции соотносится с медианой.
// А вот исполнение у DIAS ЛУЧШЕ, чем у ELFV: шаг цены 0.5 ₽ при медианной цене 3033.5 — это
// 0.0165% цены против 0.039% у ELFV, в 2.4 раза дешевле: реальный круг здесь ≈ 0.13%, поэтому
// сценарий удвоенных издержек (2.361 -> 1.895, −19.7%; у ELFV −18.1%, потеря сопоставима) на DIAS
// заведомо пессимистичен, а на ELFV реалистичен. Процедурный
// урок каталогу: дневной кэш DIAS был битым (600 свечей, дыра 2024-06-24…2024-12-23) и вылечен
// -refresh до прогонов — проверять непрерывность ОБЕИХ серий, а не только глубину истории.
// Подробности — в доке пакета strategy/dias.
func NewRSIPullbackConfig() *RSIPullbackConfig {
	return &RSIPullbackConfig{
		Tickers:  []string{"UGLD", "T", "GAZP", "DOMRF", "FESH", "WUSH", "LENT", "RENI", "NVTK", "LSNGP", "IVAT", "SVAV", "SIBN", "ELFV", "DIAS"},
		BuyPct:   5,
		Schedule: "1,31 6-23 * * *",
	}
}

// Ready reports whether the runner has its own account to trade on. Without both the
// account id and the token there is nothing to run: the portfolio call would target no
// account and the gRPC client would carry an empty token, turning every pass into a stream
// of auth failures. The caller skips the worker instead — the rest of the application,
// including the live reversion workers, must keep running.
func (c *RSIPullbackConfig) Ready() bool {
	return c.AccountID != "" && c.Token != ""
}
