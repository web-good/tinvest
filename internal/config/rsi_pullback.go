// Второе: планку не взяли ОБЕ ключевые темы, причём entry ушла ниже единицы (0.979 на 47
// сделках) — первый такой случай в каталоге; trend дала 1.282 при ведущей оси, устойчивой в
// двух фолдах из четырёх и развернувшейся на середине истории. Третье: принятая точка меряет
// pooled OOS PF 1.988 на 55 сделках, но 85% результата делает ОДНА НЕДЕЛЯ (четыре крупнейшие
// сделки всей истории — 21-27 июля 2026), а на OOS первых трёх фолдов, то есть за целый год и
// 42 сделки, та же конфигурация даёт 1.209. Режим — зеркало LSNGP: ни одного растущего
// полугодия за всю историю (train −45.6%, holdout −58.8%), значит против РАСТУЩЕГО рынка
// конфигурация не проверена ни разу, а трендовый фильтр самый закрытый в каталоге (открыт
// 29.4-36.0% баров). К статистическому риску добавляется исполнение: медиана оборота 43 млн
// ₽/день при p10 = 7 млн — половина дней тоньше гейта скринера в 50 млн, уровень LENT.
//
// SVAV заведён 2026-08-21 (риск 15) — единственный тикер вселенной с ДРУГОЙ ПРИРОДОЙ риска:
// это не непройденный протокол, а высокая волатильность инструмента, при том что протокол
// пройден целиком впервые в каталоге (entry pooled OOS PF 2.139/47, trend 2.343/104, обе ведущие
