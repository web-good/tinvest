// IVAT и LENT), вчетверо выше гейта скринера даже на десятом перцентиле, поэтому риск исполнения
// к статистическому не добавляется (в отличие от IVAT и LENT). Подробности — в доке
// пакета strategy/sibn.
//
// ELFV заведён 2026-08-22 четырнадцатым. Планка не взята, но в форме, которой в каталоге не было:
// ОБЕ ключевые темы взяли порог 1.5 по profit factor и ОБЕ провалили устойчивость — entry 1.575 на
// 106 сделках при устойчивости RSILower 1 из 4, trend 1.545 на 147 сделках при устойчивости
// EMASlow 0 из 4. Все десять тем выше 1.38, ни одна не убыточна — самая ровная таблица тем в
